// **K1** — инъективная каноническая форма входа ключей в репозитории РОВНО ОДНА (`M-05`).
//
// ПОЧЕМУ ЭТО ПРАВИЛО СТОИТ ЛИНТА, А НЕ ДИСЦИПЛИНЫ. На этой форме стоят ВСЕ ТРИ ключа кэша
// (ADR-0006 §2): `voiceKey` считается в пакете `voice`, `composeKey` и `segmentKey` — в
// `media`. Разойдись две копии на одну строку — переадресуется весь оплаченный кэш `voice`, а
// дубли не перегенерируются ни при каком промахе (ADR-0006 §2, `FACT` r1 §2.3: «Determinism
// is not guaranteed»). Цена ошибки — деньги, которые нельзя вернуть, и потому «форма одна»
// обязана быть свойством, а не соглашением.
//
// ФАЙЛ ПЕРЕЕХАЛ В `media` решением владельца (2026-08-25, `M-05` вопрос 2). Направление задано
// графом ADR-0009: стрелка `voice → media` уже есть, обратной нет и быть не может, а
// `core-model` владелец открывать отказался — «топологическая чистота не стоит вскрытия
// закрытого пакета ради переезда файла». В `voice` остался РЕЭКСПОРТ по прежнему адресу.
//
// ЧТО ИМЕННО ПРОВЕРЯЕТСЯ. Три вещи, и третья — не тавтология: сама рамка нетстринга
// (`<тег><длина в байтах><двоеточие><тело>`) не имеет права быть построена нигде, кроме
// канонического модуля. Именно её переписал бы тот, кто «быстро сделает свою склейку полей».

import { describe, expect, it } from 'vitest';

import { PACKAGES, codeLines, readSource, sourceFiles } from '../boundaries/repo';

/** Единственная реализация. Путь записан здесь и в шапке самого файла. */
const CANONICAL = 'packages/media/src/cache/canonical.ts';

/** Единственный законный реэкспорт: прежний адрес формы, на который ссылаются шапки `V-03`. */
const REEXPORT = 'packages/voice/src/plan/canonical.ts';

/**
 * Подпись рамки нетстринга: длина полезной части, двоеточие и КОНЕЦ шаблона сразу за ним.
 *
 * Ищется именно построение рамки, а не имя функции: вторая копия почти наверняка называлась
 * бы иначе, а рамку воспроизвела бы буква в букву — иначе она не была бы совместима.
 *
 * ЗАВЕРШАЮЩАЯ ОБРАТНАЯ КАВЫЧКА В ПОДПИСИ — НЕ ПРИДИРКА. Без неё правило ловило первое же
 * сообщение об ошибке вида «при заявленной длине ${String(times.length)}: …»
 * (`acceptance/health.ts`), то есть краснело на тексте, а не на коде. Ложное срабатывание
 * охранника хуже его отсутствия: его отключают вместе с правилом.
 */
const FRAME = '.length)}:`';

/** Таблица тегов типа — вторая подпись той же формы, независимая от имён переменных. */
const TAG_TABLE = /(?:text|int|json):\s*'[sij]'/u;

const allSources = (): string[] => PACKAGES.flatMap((pkg) => sourceFiles(pkg));

describe('K1 — каноническая форма входа ключей одна на репозиторий', () => {
  it('`canonicalFields` объявлена ровно в одном файле', () => {
    const definitions = allSources().filter((file) =>
      codeLines(readSource(file)).some((line) => /export function canonicalFields\b/u.test(line)),
    );
    expect(
      definitions,
      'Вторая реализация формы входа ключей переадресует весь оплаченный кэш `voice`, а ' +
        'дубли не перегенерируются ни при каком промахе (ADR-0006 §2).',
    ).toEqual([CANONICAL]);
  });

  it('рамка нетстринга строится ровно в одном файле', () => {
    const builders = allSources().filter((file) => codeLines(readSource(file)).some((line) => line.includes(FRAME)));
    expect(
      builders,
      'Рамка `<тег><длина в байтах>:<тело>` — это и есть каноническая форма. Построенная ' +
        'второй раз, она разойдётся с первой на первой же правке.',
    ).toEqual([CANONICAL]);
  });

  it('`plan/canonical.ts` — РЕЭКСПОРТ: ни одной строки алгоритма', () => {
    const lines = codeLines(readSource(REEXPORT));
    // Ни объявлений, ни ветвлений — только `export … from`. Файл существует затем, чтобы
    // прежний адрес формы остался рабочим, а не затем, чтобы что-то считать.
    expect(lines.filter((line) => /\b(function|const|let|class|switch|if)\b/u.test(line))).toEqual([]);
    expect(lines.filter((line) => line.trim() !== '')).toHaveLength(1);
    expect(lines.join('\n')).toContain("from '@vpe/media'");
  });

  it('таблица тегов типа объявлена ровно в одном файле', () => {
    // Тег отделён от длины намеренно (шапка `canonical.ts`): без него строка `"7"` и число 7
    // дают одинаковые байты, то есть `seed: 7` и `seed: "7"` получили бы ОДИН ключ. Вторая
    // таблица тегов — это второй ответ на тот же вопрос.
    const tables = allSources().filter((file) => codeLines(readSource(file)).some((line) => TAG_TABLE.test(line)));
    expect(tables).toEqual([CANONICAL]);
  });

  it('контроль прибора: обе подписи действительно есть в каноническом файле', () => {
    // Без этой строки два предыдущих теста были бы зелёными на пустом множестве — например,
    // если бы `codeLines` перестала возвращать содержимое.
    expect(readSource(CANONICAL)).toContain(FRAME);
    expect(readSource(CANONICAL)).toContain('export function canonicalFields');
    expect(codeLines(readSource(CANONICAL)).some((line) => TAG_TABLE.test(line))).toBe(true);
  });
});

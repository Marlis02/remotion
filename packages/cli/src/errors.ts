// Отказ команды: правило, текст и КОД ВЫХОДА.
//
// ПОЧЕМУ КОД ВЫХОДА ЖИВЁТ В ОШИБКЕ, А НЕ В `catch` НАВЕРХУ. Команду зовут не только глазами:
// `vpe template gate` встанет в скрипт автора, и «не разобрал аргументы» обязано отличаться от
// «шаблон гейт не прошёл» БЕЗ разбора текста. Разбирать текст — это ровно то, за что долг №164
// стоит на охраннике `PAGEERROR`.

/** Правила, на которые ссылаются отказы команд. */
export type CliRule =
  /** Аргументы: неизвестный флаг, пропущенное значение, значение вне закрытого списка. */
  | 'argv'
  /**
   * Вход сборки: файла проекта нет, он не разбирается, не проходит схему семейства либо
   * называет то, чего в v1 нет (чужой провайдер TTS). *(Добавлено: `L-01`.)*
   */
  | 'build вход'
  /**
   * **K8** — промах `voice` без `--allow-tts`. Отдельным правилом, а не «отказом входа»:
   * это единственный отказ сборки, у которого есть ЦЕНА (синтез стоит денег), и автор обязан
   * отличать его от «файла нет» без разбора текста. *(Добавлено: `L-01`.)*
   */
  | 'K8'
  /** Договорный отказ: шаблона нет, запрос зовёт другой шаблон, файл записей без спека. */
  | 'R12'
  /** Форма входного файла (запрос гейта) — не JSON либо не проходит `validateRequest`. */
  | 'ADR-0008 форма'
  /**
   * Вход `vpe store`: нет `project.yaml` или `store.lock`, они не разбираются, путь стора не
   * резолвится (**P8**), момент не той формы. *(Добавлено: `L-02`.)*
   *
   * Отдельным правилом от «`build` вход» намеренно: `vpe store verify` не читает проект
   * целиком и не обязан падать на том, на чём падает сборка, — он спрашивает про БАЙТЫ.
   */
  | 'store вход';

/**
 * Коды выхода команды. **PASS = 0; FLAKY, FAIL и `error` различимы** (требование задания
 * `E-00`), потому что это три разных решения автора: нормализовать контейнер, переписать
 * шаблон, починить окружение.
 */
export const EXIT = {
  /** Гейт снят и класс — `PASS`; запись создана. */
  pass: 0,
  /** Договорный отказ команды: шаблона нет в библиотеке, запрос зовёт другой шаблон и т. п. */
  refusal: 1,
  /** Вход не разобрался: аргументы, JSON запроса, форма запроса. */
  input: 2,
  /** Гейт снят, класс `FLAKY-по-контейнеру`. Записи НЕТ (решение владельца, развилка 2). */
  flaky: 3,
  /** Гейт снят, класс `FAIL`. Шаблон не версионируется и не используется (Charter V13). */
  fail: 4,
  /** Гейта НЕ БЫЛО: чужой профиль, отказ рендера, уехавшее окружение (`error` у `runGate`). */
  error: 5,
} as const;

/** Отказ команды. Текст уезжает в stderr дословно, код — в `process.exitCode`. */
export class CliError extends Error {
  readonly rule: CliRule;
  readonly exitCode: number;

  constructor(rule: CliRule, reason: string, exitCode: number = EXIT.refusal) {
    super(`${rule}: ${reason}`);
    this.name = 'CliError';
    this.rule = rule;
    this.exitCode = exitCode;
  }
}

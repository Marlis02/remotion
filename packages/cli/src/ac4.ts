// **AC4 — ОБЩИЕ ВЕЛИЧИНЫ ДВУХ КОНТУРОВ** (`F-01`; Charter AC4 rev5, ADR-0007 §7, §8, §10).
//
// ЧТО ЗДЕСЬ ЛЕЖИТ И ПОЧЕМУ ОТДЕЛЬНЫМ ФАЙЛОМ. Три вещи, которые обязаны быть ОДНИМИ и у
// команды `vpe verify ac4` (ночной прогон), и у теста коммит-цикла, и у стадий сборки:
// имя третьего профиля, причина прохода мимо гейта V13 на нём и разбор вывода `framemd5`.
// Файл — ЛИСТ: он не импортирует ничего из `cli`, поэтому его вправе звать и `inputs.ts`, и
// `build-stages/render.ts`, и сама команда, не заводя круга.
//
// ═══ ПОЧЕМУ У ТРЕТЬЕГО ПРОФИЛЯ НЕТ ЗАПИСИ ГЕЙТА И БЫТЬ НЕ МОЖЕТ ═══
// `GATE_PROFILES` — закрытый список из двух имён (`final`, `draftHalf`), и это не недосмотр:
// N = 10 и N = 3 названы Charter V13 для НИХ, а решение владельца 12 (RM2, 2026-08-22) говорит
// про `render.ac4.yaml` дословно — «полный прогон фикстурного проекта, а не гейт шаблона».
// Значит запись гейта на профиле `ac4` — невыразимое состояние, а не забытый файл, и
// требовать её значило бы сделать AC4 непроверяемым по построению. Проход именуется причиной
// (`gate: {mode: 'skip', why}` — механизм ADR-0008, уже существующий), а не умолчанием.
//
// ЧТО ЭТО НЕ ОТКРЫВАЕТ. `vpe build --profile ac4` остаётся НЕВЫРАЗИМЫМ: `profileOf` в
// `argv.ts` отвергает такое значение отдельным текстом. Единственный вход на профиль `ac4` —
// команда `vpe verify ac4`, то есть выпускной путь этим флагом мимо **R12** не проходит.

import { GATE_PROFILES, type GateProfileId } from '@vpe/templates-spec';

/**
 * `profileId` третьего профиля. Совпадает с полем `profileId` внутри `render.ac4.yaml` —
 * сверку «имя ↔ содержимое» делает `readRenderProfile` (ADR-0005 §1).
 */
export const AC4_PROFILE_ID = 'ac4';

/**
 * Профиль, на котором СБОРКА умеет идти: два профиля гейта плюс `ac4`.
 *
 * Тип шире, чем `GateProfileId`, ровно на одно значение, и разбор аргументов его НЕ
 * производит: `ac4` попадает сюда только из `vpe verify ac4`, конструирующей аргументы сама.
 */
export type BuildProfileId = GateProfileId | typeof AC4_PROFILE_ID;

/** Профиль пары гейта? Сужение типа, а не сравнение строк в трёх местах. */
export function isGateProfile(profileId: BuildProfileId): profileId is GateProfileId {
  return (GATE_PROFILES as readonly string[]).includes(profileId);
}

/**
 * Причина прохода мимо **R12** на профиле `ac4` — ДОСЛОВНО решение владельца 12.
 *
 * Текст уезжает в `gate: {mode: 'skip', why}` и в вывод команды: «мимо гейта» обязано быть
 * читаемо в отчёте прогона, а не только в коде.
 */
export const AC4_GATE_SKIP_WHY =
  'решение владельца 12 (RM2, 2026-08-22): гейт шаблона V13 снимается только на `final` ' +
  '(N = 10) и `draftHalf` (N = 3); `render.ac4.yaml` — ПОЛНЫЙ ПРОГОН ПРОЕКТА (компиляция → ' +
  'сегменты → конкат → мукс → аудио), то есть проверка всей цепочки, а не проверка шаблона. ' +
  'Записи гейта на этом профиле не существует по построению (`GATE_PROFILES` — закрытый ' +
  'список из двух имён), и требовать её значило бы сделать AC4 непроверяемым';

/**
 * Хэши кадров из вывода `framemd5` — **ТОЛЬКО последняя колонка** (ADR-0007 §8).
 *
 * ═══ ПОЧЕМУ `pts`/`dts` ОТБРАСЫВАЮТСЯ, И ПОЧЕМУ ЭТО НЕ ОСЛАБЛЕНИЕ ПРОВЕРКИ ═══
 * Строка `framemd5` — это `stream, dts, pts, duration, size, hash`. У сегмента шкала СВОЯ
 * (первый кадр `dts = 0`), в финале тот же кадр стоит со смещением на длину предыдущих
 * сегментов — то есть сравнение строк целиком отвечало бы «шов сдвинул время», а спрашивают
 * здесь другое: «декодировался ли тот же кадр». Ровно эту величину называет ADR-0007 §8
 * («`concat -c copy` обязан декодироваться в те же `framemd5`, что и сегменты по
 * отдельности»), и ровно её сравнивают два прогона AC4 между собой.
 *
 * Позиционное время при этом не выпадает из-под охраны вовсе: длительность и число кадров
 * финала сверяет `verifyAssembly` (**R8** и **R9**, `M-04`), а порядок кадров — сам порядок
 * этого списка.
 *
 * `size` тоже отброшен намеренно: он равен `width × height × 3/2` для всех кадров одного
 * потока и не несёт ничего, чего не несёт `hash`.
 */
export function frameHashes(lines: readonly string[]): readonly string[] {
  return lines.map((line) => {
    const columns = line.split(',');
    return (columns[columns.length - 1] ?? '').trim();
  });
}

/** Первое расхождение двух списков: индекс либо `null`. Нужен и отчёту, и тексту отказа. */
export function firstDifference(
  left: readonly string[],
  right: readonly string[],
): number | null {
  const common = Math.min(left.length, right.length);
  for (let i = 0; i < common; i += 1) {
    if (left[i] !== right[i]) return i;
  }
  return left.length === right.length ? null : common;
}

// 2026-08-31, вопрос 2 плана).
//
// ЗАЧЕМ ЭТО ВООБЩЕ ЕСТЬ. Живой тест (`tests/live/`) берёт ключ и id голоса ТОЛЬКО из окружения
// (CLAUDE.md §2), а владелец держит их в `.env`. Без этого файла живой прогон требовал бы
// руками экспортировать переменные, то есть третьего места, где живут секреты.
//
// ЧЕГО ЭТОТ ФАЙЛ НЕ ДЕЛАЕТ, И ЭТО ГЛАВНОЕ. Он НЕ включает живой режим. `ELEVENLABS_LIVE`
// перечислен в `IGNORED_FROM_FILE` и из файла не берётся никогда: строка, забытая в `.env`,
// иначе гоняла бы платные вызовы при каждом `pnpm test`. Разрешение потратить деньги пишется
// рукой в командной строке — `ELEVENLABS_LIVE=1 npx vitest run tests/live/…`.
//
// РАЗБОР — ТОТ ЖЕ, ЧТО У `vpe` (`env-file.ts`, файл рядом), и лежит этот setup здесь ровно
// поэтому: второй парсер `.env` разошёлся бы с первым, и «тесты видят то же окружение, что
// команда» перестало бы быть правдой. `tests/` пакетов не импортирует вовсе (у них нет ни
// ссылок, ни резолва) — значит общий разбор может жить только на этой стороне границы.

import path from 'node:path';

import { envWithFile } from './env-file.js';

// Корень репозитория от этого файла: `packages/cli/bin` → три уровня вверх. `process.cwd()`
// здесь не годится — vitest зовут и из подкаталога.
const ROOT = path.resolve(import.meta.dirname, '..', '..', '..');

const merged = envWithFile(path.join(ROOT, '.env'), process.env);
for (const [key, value] of Object.entries(merged)) {
  if (value !== undefined && process.env[key] === undefined) process.env[key] = value;
}

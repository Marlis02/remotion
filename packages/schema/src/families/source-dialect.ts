// `source-dialect/1` — ТОЛЬКО ШАПКА.
//
// Тело файла — проза с маркерами (ADR-0002 §1, §2), и разбирает её ЛЕКСЕР (`C-02`), а не это
// семейство. Здесь проверяется ровно одно: что файл объявляет своё семейство и версию (P1).
//
// ПОЧЕМУ ТЕЛА ЗДЕСЬ НЕТ И НЕ БУДЕТ. Диалект `source/` **не мигрируется никогда** (M7,
// ADR-0005 §4): маркеры добавляются, старые не удаляются и не меняют смысла, толерантный
// читатель понимает все исторические варианты. Схема тела означала бы вторую спецификацию
// прозы рядом с нормативной таблицей ADR-0002 §2 — и первый же новый маркер разводил бы их.
//
// Прямое следствие, записанное в реестре: `writable: false`. Писатель, вызванный на прозе,
// вернул бы файл из одной строки — то есть уничтожил бы сценарий. Отказ громче потери.

import { z } from 'zod';

export const SourceDialectHeaderSchema = z
  .object({
    schema: z.literal('source-dialect/1'),
  })
  .strict();

export type SourceDialectHeader = z.infer<typeof SourceDialectHeaderSchema>;

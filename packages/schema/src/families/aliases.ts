// `aliases/1` — `alias → sha256` (ADR-0005 §1). Замена фото не трогает прозу
// (класс правок 5 в таксономии ADR-0004 §7).

import { z } from 'zod';

import { sha256Hex } from './common.js';

/**
 * ЕДИНСТВЕННОЕ СЕМЕЙСТВО БЕЗ `.strict()`, и это не послабление, а форма данных: файл —
 * **открытая карта**, где ключи придумывает автор. `.strict()` означал бы «список алиасов
 * зашит в схему», то есть добавление фотографии требовало бы правки кода.
 *
 * Цена, принятая явно: опечатка в имени алиаса здесь **не** ловится — она ловится позже,
 * при развороте `[img: alias]` компилятором (`C-02`), где алиас обязан существовать.
 * Что схема ловит: значение обязано быть sha256, а не «чем угодно».
 */
export const AliasesSchema = z
  .object({
    schema: z.literal('aliases/1'),
  })
  .catchall(sha256Hex());

export type Aliases = z.infer<typeof AliasesSchema>;

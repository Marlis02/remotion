// Миграции: ТОЛЬКО ФОРМА (P2, ADR-0005 §2, §5).
//
// ЧТО ЗДЕСЬ ЕСТЬ И ЧЕГО НЕТ. Есть интерфейс и единственная его реализация — «миграций нет».
// Нет ни одной цепочки vN→vN+1, и это не недоделка: ADR-0005 §5 говорит прямо — «мигрировать
// пока нечего», первая версия у всех двенадцати семейств. Написать пустые цепочки сейчас
// значило бы написать двенадцать функций тождества и двенадцать тестов на них.
//
// ЧТО ТОГДА ЗАВЕДЕНО СЕЙЧАС И ЗАЧЕМ. Необратимая часть — заголовок `schema: <family>/N`
// в каждом файле и толерантный читатель — введена сразу (ADR-0005 §5), и она уже работает.
// Здесь заведено разделение, которое после первого бампа стало бы правкой архитектуры:
//
//   * **артефакт мигрируется, кэш инвалидируется** (P2, ADR-0005 §2). Для кэша миграций не
//     существует вовсе: несовпадение версии = удалить и пересчитать;
//   * **`source-dialect` не мигрируется НИКОГДА** (M7, `neverMigrates: true` в реестре).
//     Маркеры добавляются, старые не удаляются и не меняют смысла ⇒ самой опасной миграции
//     просто не существует. Попытка мигрировать его — ошибка, а не пустая операция.
//
// Экономика самой команды `vpe migrate --dry-run` записана в ADR-0005 §5 и здесь не
// повторяется: команда пишется при первом бампе схемы (`L-03` и позже).

import { FAMILIES } from './registry.js';

export class MigrationError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'MigrationError';
  }
}

export interface MigrationPlan {
  readonly family: string;
  readonly from: number;
  readonly to: number;
  /** Пусто, пока в проекте нет ни одного бампа схемы. */
  readonly steps: readonly string[];
}

/**
 * План миграции семейства с версии на версию.
 *
 * Сейчас успешен ровно в одном случае — `from === to`, — и это честное «мигрировать нечего»,
 * а не заглушка, возвращающая пустой результат на любой вход.
 *
 * @throws {MigrationError} неизвестное семейство; попытка мигрировать `source-dialect` (M7);
 *   любой запрос `from !== to`, потому что ни одной миграции в проекте не существует.
 */
export function migrate(family: string, from: number, to: number): MigrationPlan {
  const entry = FAMILIES.get(family);
  if (entry === undefined) {
    throw new MigrationError(`семейство \`${family}\` неизвестно`);
  }
  if (entry.neverMigrates) {
    throw new MigrationError(
      `семейство \`${family}\` не мигрируется никогда (M7, ADR-0005 §4): маркеры добавляются, старые не удаляются и не меняют смысла`,
    );
  }
  if (from === to) {
    return { family, from, to, steps: [] };
  }
  throw new MigrationError(
    `миграции \`${family}\` ${String(from)} → ${String(to)} не существует: в проекте нет ни одного бампа схемы (ADR-0005 §5)`,
  );
}

// Акустический детектор границ речи T7 (`V-04`, ADR-0003 T7 после SP-2, решение владельца 1).
//
// ПЕРЕНОС `docs/spikes/sp2/t7-prod.mjs` (функция `speechEdges`) и `sp2/acoustic-prod.mjs`
// (функция `measure` — она же источник имён `leadInSamples`/`tailSamples`). Метод перенесён
// ДОСЛОВНО, и это не педантизм переносчика, а прямая строка профиля: «метод менять нельзя —
// иначе числа несравнимы с измеренными (медиана лид-ина 95–100 мс, хвоста 296–310 мс на двух
// голосах)». Всё, что здесь изменено против спайка, названо поимённо в отчёте `V-04` §2.
//
// ПОЧЕМУ ПО АКУСТИКЕ, А НЕ ПО ТАЙМКОДАМ. `FACT` (SP-2, U4.3 + SP-2b.6): `start[0] = 0` на
// **56 строках из 56** двух голосов при реальном акустическом лид-ине 95–100 мс. То есть по
// таймкодам провайдера лид-ин тождественно нулевой и НЕ НАБЛЮДАЕМ ВОВСЕ; обрезка по ним
// работала ровно наполовину (хвост снимался — и то лишь потому, что последним символом чанка
// случайно всегда была точка). Детектор, заглянувший в `alignment`, воспроизвёл бы ровно ту
// ошибку, ради снятия которой T7 переписан, — поэтому в этом файле нет и не может быть ни
// одного обращения к таймкодам, и это охраняется грепом (`tests/lints/adr0003-t7-acoustic.test.ts`).
//
// ПАРАМЕТРОВ В КОДЕ НЕТ НИ ОДНОГО — та же форма, что у порогов приёмки (`V-02`). Числа `240`
// и `−45` живут в `audio-profile/1` (`fixtures/minimal/profiles/audio.yaml`, `SpeechEdgesSchema`),
// и `speechEdges` принимает их ОБЯЗАТЕЛЬНЫМ параметром: умолчание здесь было бы их второй
// записью, разъезжающейся с профилем при первой правке. Сверх обычного довода тут есть свой:
// комментарий профиля объявляет эти константы привязанными к ПАРЕ (голос, модель) и
// инвалидируемыми при смене любого из двух, — константа в коде пережила бы смену голоса молча.
//
// ЧТО ЭТА ФУНКЦИЯ НЕ ДЕЛАЕТ. Она НЕ РЕЖЕТ байты и не применяет микрофейд. В CAS лежит сырой
// s16le дубля (`V-03`), и он там и остаётся: `V-04` измеряет, а интервал речи вырезается там,
// где строится дорожка (`CP-01`/`CP-05`). Фейд — момент постройки дорожки (`M-03`, решение
// владельца A: «фейд до микса, к каждой дорожке»); применённый ещё и здесь, он стал бы первым
// из двух, а двойной фейд ADR-0003 T7 запрещает («внутри уже отведённого интервала»).
// Клипы `Silence` трёх видов (T8) — тоже не здесь: их строит Timeline (`CP-01`).

import { asSamples, type Samples } from '@vpe/core-model';
import { FULL_SCALE, type PcmS16 } from '@vpe/media';

import { VoiceError } from '../errors.js';

/**
 * Блок `speechEdges` из `audio-profile/1`.
 *
 * ТИП ОБЪЯВЛЕН ЗДЕСЬ, А НЕ ВЗЯТ ИЗ `@vpe/schema`, по той же причине, что и `TakeAcceptance`
 * (`V-02`, шапка `acceptance/health.ts`): по карте ADR-0009 `voice` зависит только от
 * `core-model` и `media`, а `@vpe/schema` из этого пакета не резолвится вовсе. Структурная
 * совместимость с `SpeechEdgesSchema` держится тем, что `AudioProfile['speechEdges']`
 * присваивается сюда без каста; охранник — тест, читающий значения ИЗ ФИКСТУРЫ.
 */
export interface SpeechEdgesParams {
  /** Длина неперекрывающегося окна RMS. В фикстуре — 10 мс при `projectSampleRate`. */
  readonly windowSamples: number;
  /** Порог «тишины» в dBFS. Величина отрицательная; значение — в профиле. */
  readonly thresholdDbFs: number;
  /** Какие стороны режутся. Реализовано ровно `both` (ADR-0003 T7: «с ОБЕИХ сторон»). */
  readonly sides: string;
}

/**
 * Границы речи в дорожке (ADR-0003 T7) — то, что уезжает в take-файл.
 *
 * Тип переехал сюда из `plan/record.ts` (`V-03`), где он был ВХОДОМ укладки с пометкой
 * «вычисление — граница задачи `V-04`». Теперь это ВЫХОД измерения, и входом быть перестал:
 * ноль, подставленный вызывающим, был бы записью измерения, которого не было (долг №85).
 */
export interface SpeechEdges {
  readonly leadInSamples: Samples;
  readonly tailSamples: Samples;
}

/** Измерение целиком: пара краёв плюс то, из чего она получена. */
export interface SpeechEdgeMeasurement extends SpeechEdges {
  /** Длина дорожки. Отсюда `интервал речи = [leadInSamples, numSamples − tailSamples)`. */
  readonly numSamples: Samples;
  /**
   * Ни одно окно не превысило порога.
   *
   * Поле обязательно и не выводится из пары: при `allSilent` края равны нулю (см. «Пустой
   * случай» у `speechEdges`), и без этого флага «тишины по краям нет» было бы неотличимо от
   * «дубль весь тихий» — два противоположных факта с одинаковой записью.
   */
  readonly allSilent: boolean;
}

/**
 * Пол энергии под логарифмом — эпсилон спайка, перенесённый дословно.
 *
 * Он не «сглаживает» ничего: без него окно из точных нулей давало бы `log10(0) = −Infinity`,
 * что сравнивается с порогом верно, но втягивает в тракт нечисло. Величина входит в МЕТОД
 * (обе спайковые реализации несут её), поэтому и правится только вместе с методом.
 */
const ENERGY_FLOOR = 1e-12;

/** Множитель перевода отношения мощностей в децибелы: `10·log10(P)`, не `20·log10(A)`. */
const DB_PER_DECADE_POWER = 10;

/** Единственная реализованная раскладка сторон. ADR-0003 T7 других и не называет. */
const SIDES_BOTH = 'both';

function assertParams(params: SpeechEdgesParams): void {
  if (!Number.isSafeInteger(params.windowSamples) || params.windowSamples <= 0) {
    throw new VoiceError(
      'ADR-0003 T7',
      `\`speechEdges.windowSamples\` = ${String(params.windowSamples)}: ожидалось целое > 0. ` +
        'Окно — длина неперекрывающегося блока RMS в сэмплах; величина живёт в ' +
        '`audio-profile/1 → speechEdges.windowSamples` (10 мс при `projectSampleRate`).',
    );
  }
  if (typeof params.thresholdDbFs !== 'number' || !Number.isFinite(params.thresholdDbFs)) {
    throw new VoiceError(
      'ADR-0003 T7',
      `\`speechEdges.thresholdDbFs\` = ${String(params.thresholdDbFs)}: ожидалось конечное число dBFS.`,
    );
  }
  if (params.sides !== SIDES_BOTH) {
    throw new VoiceError(
      'ADR-0003 T7',
      `\`speechEdges.sides\` = ${String(params.sides)}: реализовано ровно \`${SIDES_BOTH}\`. ` +
        'ADR-0003 T7 после SP-2 режет ГОЛОВУ И ХВОСТ по акустике и односторонней обрезки не ' +
        'знает: односторонняя вернула бы предусловие «последний символ чанка — пунктуация», ' +
        'снятое `FACT` SP-2 U4.3 (на строке без финальной точки правило срезает 0.4 мс вместо ' +
        '313.9). Значение, которого этот файл не понимает, обязано падать, а не молча означать ' +
        '«обе стороны».',
    );
  }
}

/**
 * Границы речи по акустике: RMS по неперекрывающимся окнам, порог в dBFS, обе стороны.
 *
 * МЕТОД (дословно спайковый, `sp2/t7-prod.mjs`):
 *   * дорожка режется на окна по `windowSamples` сэмплов ПОДРЯД, БЕЗ ПЕРЕКРЫТИЯ, от сэмпла 0;
 *   * у окна считается `10·log10(Σ(s/32768)² / W + 1e-12)` — среднеквадратичная мощность в dBFS;
 *   * окно «речь», если эта величина СТРОГО больше `thresholdDbFs`;
 *   * `leadInSamples` — начало первого такого окна, `tailSamples` — расстояние от конца
 *     последнего такого окна до конца дорожки.
 *
 * АРИФМЕТИКА ВНУТРИ — double (спайк делит на 32768 и работает в double; это тот самый метод,
 * которым сняты числа обоих голосов). ГРАНИЦА ВЫХОДА — целые сэмплы: обе величины кратны
 * `windowSamples` по построению, в бренд `Samples` они уходят через `asSamples`, и ни одна
 * дробь наружу не выходит.
 *
 * ПРАВИЛО ОКРУГЛЕНИЯ ГРАНИЦЫ (покрыто тестом `edges.test.ts`, блок «сетка окон»):
 *   1. обе границы лежат на СЕТКЕ ОКОН, отсчитываемой от сэмпла 0, то есть кратны
 *      `windowSamples`; разрешение прибора — одно окно, и меньше его он не различает;
 *   2. хвостовой остаток `numSamples mod windowSamples` НЕ ОСМАТРИВАЕТСЯ вовсе (цикл спайка
 *      идёт, пока `i + W ≤ n`) и целиком достаётся `tailSamples`;
 *   3. следствие, важное для потребителя: `leadInSamples` НЕДООЦЕНИВАЕТ настоящую тишину
 *      (граница округляется вниз, к началу окна) и потому никогда не съедает речь. У
 *      `tailSamples` та же недооценка от квантования, но п. 2 добавляет к нему до
 *      `windowSamples − 1` неосмотренных сэмплов, так что он бывает и завышен — на величину
 *      меньше окна. Обрезка, стоящая на этих числах, ошибается меньше чем на 10 мс при 24 кГц.
 *
 * ПУСТОЙ СЛУЧАЙ (`first < 0 ⇒ 0`, `last < 0 ⇒ n` — форма `t7-prod.mjs`, решение владельца
 * `V-04` вопрос 2). Если ни одно окно не превысило порога, обе величины равны НУЛЮ, а факт
 * «дубль весь тихий» несёт `allSilent`. Вторая спайковая реализация (`acoustic-prod.mjs`)
 * возвращает в этом случае `leadIn = n` И `tail = n`, то есть `2n` сэмплов тишины в дорожке
 * длины `n`: инвариант формы `leadInSamples + tailSamples ≤ numSamples` там нарушен, а на нём
 * стоит всякий, кто строит интервал речи. Расхождение двух спайков названо в отчёте `V-04`.
 *
 * @throws {VoiceError} `ADR-0003 T7` — параметр профиля не той формы либо `sides ≠ both`.
 */
export function speechEdges(pcm: PcmS16, params: SpeechEdgesParams): SpeechEdgeMeasurement {
  assertParams(params);
  const window = params.windowSamples;
  const n = pcm.samples.length;

  let first = -1;
  let last = -1;
  for (let i = 0; i + window <= n; i += window) {
    let acc = 0;
    for (let k = 0; k < window; k += 1) {
      const v = (pcm.samples[i + k] ?? 0) / FULL_SCALE;
      acc += v * v;
    }
    if (DB_PER_DECADE_POWER * Math.log10(acc / window + ENERGY_FLOOR) > params.thresholdDbFs) {
      if (first < 0) first = i;
      last = i + window;
    }
  }

  const allSilent = first < 0;
  const firstLoudSample = allSilent ? 0 : first;
  const lastLoudSample = last < 0 ? n : last;
  return {
    leadInSamples: asSamples(firstLoudSample),
    tailSamples: asSamples(n - lastLoudSample),
    numSamples: asSamples(n),
    allSilent,
  };
}

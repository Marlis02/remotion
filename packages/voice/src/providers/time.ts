// Перевод «секунды провайдера → сэмплы» — ЕДИНСТВЕННАЯ точка конверсии (`V-01`, решение
// владельца по вопросу 7, вариант «а»).
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. У проекта две единицы времени, и обе описаны: миллисекунды
// авторского слоя и сэмплы (ADR-0003 T1, `msToSamples`). Провайдер приносит **третью** —
// секунды с плавающей точкой, — и её не знает ни один ADR. Пока она размазана по коду,
// каждое место конвертирует её по-своему; собранная в одну функцию, она проверяется одним
// тестом и правится в одном месте. `INFERENCE` записан прямо в имя правила ошибки
// (`V-01 секунды провайдера (INFERENCE)`), кандидат в правку ADR-0003 — в отчёте сессии.
//
// ПОЧЕМУ ЧЕРЕЗ МИЛЛИСЕКУНДЫ, А НЕ `Math.round(seconds * sampleRate)`. Прямая формула — это
// `* sampleRate`, то есть ВТОРАЯ формула перевода времени, запрещённая линтом T1 везде, кроме
// `core-model/src/time/ms.ts`. Легализовать её пришлось бы новым исключением из T1 (решение
// владельца: отклонено — «цена выше точности, которая mock'у не нужна»). Путь через
// `msToSamples` не добавляет исключений ни одного.
//
// ЧТО ЭТО СТОИТ, ИЗМЕРЕНО, А НЕ ОБЕЩАНО:
//   * на выходе `tts:mock@1` — **ноль** отличий: его времена целые в миллисекундах по
//     построению, и `Math.round(seconds * 1000)` возвращает ровно ту же миллисекунду;
//   * на ЧУЖОМ alignment — расхождение не больше округления до 1 мс, то есть
//     ≤ `sampleRate/1000` сэмплов (12 при 24000). Слоп ровно этого порядка ADR-0010 уже
//     допускает на этой самой границе: ассерт `V-04` записан как
//     `end[last] ≤ numSamples + ⌈sampleRate/1000⌉`.

import { msToSamples, type Samples } from '@vpe/core-model';

import { VoiceError } from '../errors.js';

/** Миллисекунд в секунде. Именованной константой, чтобы литерал не выглядел магией. */
const MS_PER_SECOND = 1000;

/**
 * Таймкод провайдера (секунды) → сэмплы.
 *
 * @param seconds конечное число ≥ 0; таймкод из `alignment`.
 * @param sampleRate целое > 0; частота дорожки (у речи — частота из `pcmFormats`).
 * @throws {VoiceError} секунды не конечны или отрицательны.
 * @throws {TimeModelError} `sampleRate` не целое > 0 (проверка внутри `msToSamples`).
 */
export function providerSecondsToSamples(seconds: number, sampleRate: number): Samples {
  if (typeof seconds !== 'number' || !Number.isFinite(seconds)) {
    throw new VoiceError(
      'V-01 секунды провайдера (INFERENCE)',
      `таймкод = ${String(seconds)}: ожидалось конечное число секунд. ` +
        'Нечисловой таймкод — это либо `alignment: null` (ADR-0010 §1, обрабатывается приёмкой), ' +
        'либо испорченный ответ провайдера; молча превращать его в сэмплы нельзя.',
    );
  }
  if (seconds < 0) {
    throw new VoiceError(
      'V-01 секунды провайдера (INFERENCE)',
      `таймкод = ${String(seconds)}: отрицательное время у речи не бывает. ` +
        'Отрицательный сдвиг выражается `nudgeSamples` у `TimePoint` (ADR-0001), а не таймкодом.',
    );
  }
  return msToSamples(Math.round(seconds * MS_PER_SECOND), sampleRate);
}

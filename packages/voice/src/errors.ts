// Ошибка границы TTS (`V-01`).
//
// ОШИБКА НАЗЫВАЕТ ПРАВИЛО, А НЕ СЛЕДСТВИЕ — то же решение, что у `TimeModelError` (`C-01`),
// `AudioError` (`M-03`) и `AssetCatalogError` (`M-02`). «Частота 48000 не поддерживается» —
// следствие; «ADR-0010 §8: ветвление по capabilities» — причина, и по ней сразу видно, какую
// строку читать.

/** Правила, на которые ссылаются ошибки границы TTS. */
export type VoiceRule =
  /** Приёмка дубля: `charIdentity`, длины, монотонность, пороги профиля. */
  | 'ADR-0010 §1'
  /**
   * Лестница ретраев исчерпана — падение сборки (`V-02`).
   *
   * Имя правила несёт **M12** рядом с адресом ADR намеренно: M12 — это находка red-team, из-за
   * которой первая редакция §1 (провал ⇒ автоматическое деление чанка) была отменена. Читающий
   * эту ошибку обязан сразу видеть, что чанк НЕ поделён и делить его лестница права не имеет.
   */
  | 'ADR-0010 §1 (M12)'
  /**
   * Границы чанков — только структурные (**V3**, `V-03`).
   *
   * Множество границ абзаца — функция его байтов и структурного адреса, и ничего больше.
   * Ошибка с этим правилом означает, что делению подсунули то, чего у него быть не может:
   * предел из профиля, не являющийся положительным целым, или абзац, пришедший без адреса.
   */
  | 'ADR-0010 §3'
  /**
   * `chunkKey` и `voiceKey` — форма ключа и инъективность его входа (**V3**, **V4**, `V-03`).
   *
   * Правило названо адресом §3a намеренно: и определение обеих величин, и таблица их свойств
   * лежат там, а нарушение почти всегда одно и то же — в хэш уехало не то, что объявлено.
   */
  | 'ADR-0010 §3a'
  /**
   * Дубль самоописателен: пересчёт привязок из одного take-файла (`V-05`).
   *
   * Ошибка с этим правилом означает, что артефакту НЕ ХВАТАЕТ ВХОДОВ — блока `bind` нет, а
   * значит нет ни токенов исходника, ни ответа провайдера. Это не «пересчёт дал другие
   * числа», а «пересчитывать не из чего»: ровно то состояние, ради исключения которого
   * core.md §18.3 п. 6 запрещает откладывать самоописательность.
   */
  | 'ADR-0010 §2'
  /** Стичинг — только текстом; `previous_request_ids` не используется никогда (**V5**). */
  | 'ADR-0010 §4 (V5)'
  /**
   * Стадия `bind`: интерфейс биндера и его входы (`V-05`).
   *
   * Три нарушения ходят под этим именем, и все три — про ВЫДУМАННОЕ ВРЕМЯ (**V8**): биндер
   * позван без `alignment` (измерять нечем); ссылки на токены описывают не тот отправленный
   * текст (привязки уехали бы на чужие слова); в ответе слово, которого нет в исходнике
   * (`charIdentity` нарушена подменой, и чинить её сдвигом нельзя).
   */
  | 'ADR-0010 §5'
  /** Правило построения интервала токена: пробелы и пунктуация в слово не входят. */
  | 'ADR-0010 §6'
  /** Словари произношения в v1 не используются вовсе (**V7**). */
  | 'ADR-0010 §7a (V7)'
  /** Ветвление по capabilities, а не по имени провайдера. */
  | 'ADR-0010 §8'
  /**
   * Состав ключа кэша стадии `voice` и `roleDigest` (**V15**, `V-03`).
   *
   * Отдельно от §3a, потому что реестр ключей живёт в другом ADR и правится другой задачей
   * (`M-05`, матрица мутации): ошибка «в дайджест роли уехал весь файл» — это нарушение
   * ADR-0006 §2, а не ADR-0010.
   */
  | 'ADR-0006 §2'
  /**
   * Кэш стадии `voice`: форма записи и её восстановимость (`M-05`, ADR-0006 §8).
   *
   * Два нарушения ходят под этим именем, и оба — про МОЛЧАЛИВУЮ ПОДСТАНОВКУ. Первое:
   * запись кэша неполна, и дописать её умолчаниями нельзя — «краёв не измеряли» и «края
   * равны нулю» разные утверждения, а второе в артефакте есть ложь (долг №85). Второе:
   * take-файл без `voiceKey`, то есть индекс `voiceKey → sha256` из него не пересобирается;
   * пропустить такой файл значило бы заплатить за уже оплаченный дубль второй раз и не
   * сказать об этом.
   */
  | 'ADR-0006 §8'
  /** Внутри пайплайна речь запрашивается в `pcm_*`; частота — `projectSampleRate`. */
  | 'ADR-0010 §9'
  /**
   * Акустический детектор границ речи (**T7**, `V-04`).
   *
   * Правило названо адресом ADR-0003, а не ADR-0010, намеренно: T7 — строка МОДЕЛИ ВРЕМЕНИ
   * («дрейф провайдера убирается на импорте дубля»), и нарушение здесь всегда одно и то же —
   * детектору подсунули не тот параметр профиля либо не ту раскладку сторон. Числа `240`
   * и `−45` живут в `audio-profile/1` и в код не переезжают ни при каком исходе: комментарий
   * профиля привязывает их к ПАРЕ (голос, модель).
   */
  | 'ADR-0003 T7'
  /**
   * Связка «токен исходника ↔ якорь» (`V-05`, ADR-0004 §4).
   *
   * Правило названо адресом ADR-0004, а не ADR-0010, потому что нарушается именно оно:
   * ledger синхронизирован не с тем разбором исходника, и токену достаётся чужой якорь либо
   * не достаётся никакого. Ошибку бросает `voice`, а не `core-model`, потому что проверку
   * делает СВЯЗКА (`bind/tokens.ts`): минт и сам ledger к этому моменту уже отработали
   * безупречно, разошлись их ВХОДЫ.
   */
  | 'ADR-0004 §4'
  /**
   * Перевод «секунды провайдера → сэмплы». Единица «секунда с плавающей точкой» не описана
   * ни одним ADR: ADR-0003 T1 знает миллисекунды авторского слоя и сэмплы, а секунды приходят
   * с границы провайдера. Правило названо так, чтобы в тексте ошибки было видно: это
   * `INFERENCE` сессии `V-01`, а не строка ADR (кандидат в правку ADR-0003 — в отчёте).
   */
  | 'V-01 секунды провайдера (INFERENCE)';

/** Нарушение правила границы TTS: несёт имя правила, а не только текст. */
export class VoiceError extends RangeError {
  readonly rule: VoiceRule;

  constructor(rule: VoiceRule, reason: string) {
    super(`${rule}: ${reason}`);
    this.name = 'VoiceError';
    this.rule = rule;
  }
}

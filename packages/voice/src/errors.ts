// Ошибка границы TTS (`V-01`).
//
// ОШИБКА НАЗЫВАЕТ ПРАВИЛО, А НЕ СЛЕДСТВИЕ — то же решение, что у `TimeModelError` (`C-01`),
// `AudioError` (`M-03`) и `AssetCatalogError` (`M-02`). «Частота 48000 не поддерживается» —
// следствие; «ADR-0010 §8: ветвление по capabilities» — причина, и по ней сразу видно, какую
// строку читать.

/** Правила, на которые ссылаются ошибки границы TTS. */
export type VoiceRule =
  /** Приёмка дубля: `charIdentity`, длины, монотонность, пороги профиля. */
  | 'ADR-0010 §1'
  /**
   * Лестница ретраев исчерпана — падение сборки (`V-02`).
   *
   * Имя правила несёт **M12** рядом с адресом ADR намеренно: M12 — это находка red-team, из-за
   * которой первая редакция §1 (провал ⇒ автоматическое деление чанка) была отменена. Читающий
   * эту ошибку обязан сразу видеть, что чанк НЕ поделён и делить его лестница права не имеет.
   */
  | 'ADR-0010 §1 (M12)'
  /** Стичинг — только текстом; `previous_request_ids` не используется никогда (**V5**). */
  | 'ADR-0010 §4 (V5)'
  /** Правило построения интервала токена: пробелы и пунктуация в слово не входят. */
  | 'ADR-0010 §6'
  /** Словари произношения в v1 не используются вовсе (**V7**). */
  | 'ADR-0010 §7a (V7)'
  /** Ветвление по capabilities, а не по имени провайдера. */
  | 'ADR-0010 §8'
  /** Внутри пайплайна речь запрашивается в `pcm_*`; частота — `projectSampleRate`. */
  | 'ADR-0010 §9'
  /**
   * Перевод «секунды провайдера → сэмплы». Единица «секунда с плавающей точкой» не описана
   * ни одним ADR: ADR-0003 T1 знает миллисекунды авторского слоя и сэмплы, а секунды приходят
   * с границы провайдера. Правило названо так, чтобы в тексте ошибки было видно: это
   * `INFERENCE` сессии `V-01`, а не строка ADR (кандидат в правку ADR-0003 — в отчёте).
   */
  | 'V-01 секунды провайдера (INFERENCE)';

/** Нарушение правила границы TTS: несёт имя правила, а не только текст. */
export class VoiceError extends RangeError {
  readonly rule: VoiceRule;

  constructor(rule: VoiceRule, reason: string) {
    super(`${rule}: ${reason}`);
    this.name = 'VoiceError';
    this.rule = rule;
  }
}

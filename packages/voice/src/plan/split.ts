// Структурное деление слишком длинного абзаца (`V-03`, ADR-0010 §3).
//
// ФОРМАЛЬНЫЙ ИНВАРИАНТ, КОТОРЫЙ ЭТОТ ФАЙЛ ОБЯЗАН ИСПОЛНЯТЬ ДОСЛОВНО (**V3**):
// «множество границ чанков абзаца зависит только от байтов абзаца и его структурного адреса».
// Исполнимая форма — СИГНАТУРА: функция принимает текст одной части абзаца и предел из
// профиля, и НЕ ПРИНИМАЕТ ни позиции в документе, ни счётчика, ни номера сцены, ни чего-либо
// ещё, что менялось бы от правки выше по тексту. Бегущий счётчик символов по документу здесь
// невыразим — не «запрещён соглашением», а не имеет входа, из которого его можно взять.
// Цена нарушения названа в ADR прямо: вставка одного слова в начале сцены сдвинула бы все
// последующие границы, сменила бы все последующие `chunkKey` и вызвала бы ПЛАТНУЮ
// перегенерацию всего остатка проекта.
//
// ГРАНИЦА ПРЕДЛОЖЕНИЯ — ПРАВИЛО `C-02`, И ОНО ОДНО НА РЕПОЗИТОРИЙ (решение владельца
// 2026-08-24, `V-03` вопрос 2). Определение записано в шапке
// `packages/core-model/src/source/parse.ts`: «граница предложения = `.`/`!`/`?`, за которым
// пробельный, конец абзаца или сам маркер». Набор знаков приходит оттуда же вызовом
// `isSentenceEnd`, а не копией: вторая копия означала бы, что `[pause:]` законен там, где
// деление резать не станет, и наоборот.
// Честная остаточная цена, уже записанная долгом `C-03`: линт прозы запрещает `Dr.`, `St.`,
// `Mr.`, `Mrs.`, `Ms.`, `Prof.`, `e.g.`, `i.e.` (закрытый список `ABBREVIATIONS`), но
// пропускает `etc.`, `vs.`, `Jr.`, `Ph.D.` — на них деление сработает по ложной границе.
// Многоточие даёт границу после последней точки. Ни то, ни другое не ломает ключей: раскрой
// остаётся функцией байтов, просто в неудачном месте, и лечится `[pause:]` в тексте.
//
// ПРЕДЕЛ БЕРЁТСЯ ИЗ ПРОФИЛЯ, УМОЛЧАНИЯ НЕТ (прецедент `V-02`: пороги приёмки — обязательный
// параметр). `FACT` (SP-2, findings U6 + SP-2b.5): безопасный предел по КАЧЕСТВУ ALIGNMENT не
// найден вплоть до 2689 code points / 155.4 с, то есть значение выбирается из просодии,
// стоимости перегенерации и гранулярности AC3 — и живёт в `audio-profile/1`, а не в коде.
//
// ЕДИНИЦА ДЛИНЫ — CODE POINT. `FACT` (SP-2, U4.2 + SP-2b.2): именно в них считает и тарификация
// провайдера, и его `alignment.characters`. `Intl.Segmenter` не используется — он дал бы
// графемы (Charter V8 его и запрещает), а `str.length` дал бы UTF-16 units.

import { isSentenceEnd, isWhitespace } from '@vpe/core-model';

import { VoiceError } from '../errors.js';

/** Часть абзаца после деления: её текст и место внутри текста-родителя. */
export interface ParagraphPart {
  /** Текст части — ровно то, что уйдёт провайдеру одним запросом. */
  readonly spoken: string;
  /** Индекс первого code point части в тексте-родителе. Нужен `V-05` для привязок. */
  readonly spokenStart: number;
}

/**
 * Позиции, по которым резать законно: индекс ПЕРВОГО code point следующего предложения минус
 * ведущие пробельные, то есть смещение сразу за знаком конца предложения.
 *
 * Конец текста границей НЕ считается: резать там нечего.
 */
function cutPoints(points: readonly string[]): readonly number[] {
  const cuts: number[] = [];
  for (let i = 0; i < points.length - 1; i += 1) {
    if (!isSentenceEnd(points[i] ?? '')) continue;
    if (!isWhitespace(points[i + 1] ?? '')) continue;
    cuts.push(i + 1);
  }
  return cuts;
}

/**
 * Делит текст части абзаца по границам предложений ВНУТРИ неё, слева направо.
 *
 * Правило выбора границы: берётся САМАЯ ПРАВАЯ граница, при которой часть ещё укладывается в
 * предел. Если такой границы нет (одно предложение длиннее предела), берётся ПЕРВАЯ граница
 * за пределом: предложение не режется посреди себя ни при каких условиях — ADR-0010 §3
 * называет границами только границы предложений. Если границ нет вовсе, часть остаётся целой
 * и длиннее предела — это честный исход, и лечится он `[pause:]` в тексте (ADR-0010 §1),
 * а не молчаливым разрезом посреди фразы.
 *
 * Пробельные между предложениями в части НЕ ПОПАДАЮТ: разрез идёт сразу за знаком конца
 * предложения, ведущие пробельные следующей части снимаются. Это тот же исход, что даёт
 * `[pause:]` в `C-02` (маркер и пробелы вокруг него в spoken не уходят), и он значим —
 * ведущий пробел уехал бы провайдеру и попал бы в `charIdentity`.
 *
 * @throws {VoiceError} `ADR-0010 §3` — предел не положительное целое (умолчания у него нет).
 */
export function splitChunkText(spoken: string, maxChunkChars: number): readonly ParagraphPart[] {
  if (!Number.isSafeInteger(maxChunkChars) || maxChunkChars <= 0) {
    throw new VoiceError(
      'ADR-0010 §3',
      `\`maxChunkChars\` = ${String(maxChunkChars)} — предел деления абзаца обязан быть ` +
        'положительным целым и приходит из `audio-profile/1`. Умолчания у него нет: значение ' +
        'выбирается из просодии, стоимости перегенерации и гранулярности AC3 (`FACT` SP-2 U6 — ' +
        'по качеству alignment предел не найден до 2689 code points), то есть подставить его ' +
        'в коде значило бы принять решение владельца за него',
    );
  }

  const points = [...spoken];
  const cuts = cutPoints(points);
  const parts: ParagraphPart[] = [];

  let start = 0;
  while (points.length - start > maxChunkChars) {
    let chosen = -1;
    for (const cut of cuts) {
      if (cut <= start) continue;
      if (cut - start <= maxChunkChars) chosen = cut;
      else {
        // Первая граница ЗА пределом — запасной ход для предложения длиннее предела.
        if (chosen === -1) chosen = cut;
        break;
      }
    }
    if (chosen === -1) break; // границ дальше нет: остаток уходит одной частью
    parts.push({ spoken: points.slice(start, chosen).join(''), spokenStart: start });
    start = chosen;
    while (start < points.length && isWhitespace(points[start] ?? '')) start += 1;
  }

  parts.push({ spoken: points.slice(start).join(''), spokenStart: start });
  return parts;
}

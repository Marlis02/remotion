// Пересчёт привязок ИЗ ТАКЕ-ФАЙЛА — исполнимая форма «дубль самоописателен» (ADR-0010 §2;
// core.md §18.3 п. 6; критерий готовности `V-05`).
//
// ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ НА САМОМ ДЕЛЕ. Не то, что функция вернёт те же числа (это следствие),
// а то, что ВХОДОВ ХВАТАЕТ. Вход ровно два: сам take-файл и байты дорожки из CAS по
// `pcm.sha256`. Ни исходника, ни ledger'а, ни нормализатора: `spokenText`, токены с якорями и
// ответ провайдера лежат в файле, а «текст дубля ≠ текущий spoken-текст» становится явным
// условием инвалидации вместо молчаливого расхождения (ADR-0010 §2). Без этого AC6 для аудио
// мёртв: старый проект открывается, а времена его слов восстановить нечем.
//
// ПОЧЕМУ БАЙТЫ ПРИХОДЯТ ПАРАМЕТРОМ, А НЕ ЧИТАЮТСЯ ОТСЮДА. `voice` не ходит в CAS сам (это
// делает укладка, `plan/record.ts`), и `rebindTake` обязан оставаться чистым: тогда «файла и
// байтов хватает» — утверждение о ВХОДАХ, а не о доступности диска. Вызывающий берёт блоб по
// `take.pcm.sha256` — тем самым проверяя заодно, что адрес в артефакте настоящий.
//
// ПОЧЕМУ ЗДЕСЬ НЕТ СРАВНЕНИЯ `binderId`. Сверка «тем ли биндером пересчитываем» была бы
// сравнением по ИМЕНИ — ровно то, что запрещает **V16** и ловит охранник. Биндер приходит
// значением (дефолт — `provider-timestamps@1`), а несовпадение видно по результату: привязки
// чужого биндера не равны записанным, и это наблюдаемо, а не спрятано в `if`. Проверяется
// зато то, что проверяемо по ВОЗМОЖНОСТЯМ: пересчёт из артефакта не ходит в сеть (**V9**).

import { VoiceError } from '../errors.js';
import type { Take, TokenBinding } from '../providers/types.js';

import { providerTimestampsBinder } from './provider-timestamps.js';
import type { Binder } from './types.js';

export interface RebindInput {
  /** Take-файл целиком — так, как он прочитан с диска. */
  readonly take: Take;
  /** Байты дорожки из CAS по `take.pcm.sha256`. Акустический биндер читает их, этот — нет. */
  readonly pcm: Uint8Array;
  /** Чем пересчитывать. Умолчание — дефолтный биндер v1 (ADR-0010 §5). */
  readonly binder?: Binder;
}

/**
 * Пересчитывает привязки из take-файла.
 *
 * @throws {VoiceError} `ADR-0010 §2` — в файле нет блока `bind` (дубль записан без стадии
 *   `bind`, пересчитывать нечего), либо `ADR-0010 §5` — биндеру нужна сеть.
 */
export async function rebindTake(input: RebindInput): Promise<readonly TokenBinding[]> {
  const binder = input.binder ?? providerTimestampsBinder;
  const bind = input.take.bind;

  if (bind === null) {
    throw new VoiceError(
      'ADR-0010 §2',
      `дубль ${input.take.chunkKey} записан без стадии \`bind\`: блока \`bind\` в файле нет, ` +
        'а вместе с ним нет ни токенов исходника, ни ответа провайдера. Пересчитать привязки ' +
        'из такого файла нельзя — их не из чего считать, и выдумывать время вместо отказа ' +
        'запрещено (**V8**).',
    );
  }
  if (binder.requiresNetwork) {
    throw new VoiceError(
      'ADR-0010 §5',
      'пересчёт привязок из артефакта позван биндером, которому нужна сеть. Дубль на то и ' +
        'самоописателен, что восстанавливается офлайн из своих же полей (**V9**, core.md ' +
        '§18.3 п. 6); сетевой биндер здесь означал бы, что старый проект открывается только ' +
        'при живом провайдере.',
    );
  }

  return binder.bind(
    input.pcm,
    input.take.pcm.sampleRate,
    input.take.spokenText,
    bind.tokens,
    bind.providerAlignment ?? undefined,
  );
}

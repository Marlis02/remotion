// Стадия `bind` (`V-05`, ADR-0010 §5) — формы, и ни одной строки поведения.
//
// ЧТО ТАКОЕ `bind`. Явная точка расширения между дублём и Timeline: дубль знает, ЧТО сказано
// и КАК ЗВУЧИТ, а Timeline нужно знать, КОГДА звучит каждый токен исходника. Интерфейс
// вводится сразу, хотя биндер в v1 один: `FACT` (r1 §2.1) официальный воркэраунд вендора —
// forced alignment, значит переход вероятен, а без явной стадии он превращается в хирургию по
// Timeline (ADR-0010 §5).
//
// ГЛАВНОЕ ПРАВИЛО ЭТОГО КАТАЛОГА — ТО ЖЕ, ЧТО У ПРОВАЙДЕРОВ (**V16**, ADR-0010 §8): потребитель
// ветвится по ВОЗМОЖНОСТЯМ И ПОЛЯМ, а не по имени биндера. `binderId` существует ровно для двух
// вещей: попасть в артефакт («чем измерено») и в ключ стадии. Сравнивать его в `if` запрещено —
// охранник двойной, как у `providerId`: `CAPABILITY_SYNTAX` в `eslint.config.js` (форма
// сравнения) и греп по литералу в `tests/lints/adr0010-binder-branching.test.ts` (таблица
// «имя → поведение», которую селектор не видит).
//
// ЧЕГО ЗДЕСЬ НЕТ. Минта якорей. Пространство `w:` минтится РОВНО в одном файле репозитория —
// `packages/core-model/src/anchors/mint.ts` (128 бит CSPRNG, ADR-0004 §4), и это единственный
// законный недетерминизм модели (D4). Стадия `bind` якорей не порождает — она их СВЯЗЫВАЕТ с
// измеренным временем. Охранник — греп: в `packages/voice/src/bind/**` нет ни `mintAnchorId`,
// ни `node:crypto`, ни литерала `w:` (`tests/lints/adr0004-bind-mints-nothing.test.ts`).

import type { AnchorId } from '@vpe/core-model';

import type { ProviderAlignment, TokenBinding } from '../providers/types.js';

/**
 * Ссылка на токен ИСХОДНИКА — вход стадии `bind` (ADR-0010 §5, `tokens`).
 *
 * ТИП РОЖДАЁТСЯ ЗДЕСЬ (решение владельца, `V-05` вопрос 3). ADR-0010 §5 называет его в
 * сигнатуре `Binder`, но не объявляет ни в одном пакете; `core-model` закрыт заданием, а
 * `@vpe/schema` из `voice` не резолвится вовсе (`packages/voice/node_modules/@vpe/` — два
 * симлинка). Адрес типа — стадия, которая им пользуется.
 *
 * ЧТО ОН СВЯЗЫВАЕТ. Токен исходника (`TokenNode`, `C-02`: максимальный ряд непробельных
 * символов прозы ЛИБО маркер `[say:]` целиком) с его якорем `w:` из ledger'а (`C-04`). Обе
 * половины уже существуют и приходят готовыми — см. `tokens.ts`.
 */
export interface SourceTokenRef {
  /**
   * Якорь токена — `w:<base32(csprng(128 бит))[:16]>` (ADR-0004 §4).
   *
   * ТИП — БРЕНД `AnchorId` *(изменено: `CP-01`, решение владельца 2026-08-26, вопрос 5; долг
   * №100 закрыт)*. До этой задачи здесь стоял `string`, потому что бренд живёт в
   * `@vpe/schema`, который из `voice` не резолвится, а расширять адресный реэкспорт
   * `core-model` заданием `V-05` было запрещено. `CP-01` — первый посторонний читатель
   * `anchorId`, и решение принято на его границе: реэкспорт добавлен одной строкой
   * (`asAnchorId` + `AnchorId`), подделка адреса теперь не типизируется. Значения приходят
   * готовыми: `AnchorBinding.id` (`C-04`, `anchors/sync.ts`) УЖЕ `AnchorId` — бренд здесь не
   * добавляется, а перестаёт теряться.
   */
  readonly anchorId: AnchorId;
  /** Поверхностная форма токена (ADR-0004 §5): то, что автор написал. */
  readonly surface: string;
  /** Что из этого токена ушло провайдеру. У `[say:]` — spoken-сторона, у прозы равно `surface`. */
  readonly spoken: string;
  /**
   * Индекс первого code point токена в `spokenText`, КОТОРЫЙ ПРИШЁЛ БИНДЕРУ (не в `spoken`
   * родительского чанка AST). Пересчёт на границу части делает `tokensOfPlan`; биндеру
   * приходит уже готовая величина, и другой системы отсчёта у него нет.
   */
  readonly spokenStart: number;
}

/**
 * Биндер — ДОСЛОВНО ADR-0010 §5.
 *
 * `Promise` в подписи стоит по той же причине, что у `TtsProvider.synthesize`: акустический
 * биндер (`ctc-fa@1`, `mfa@3`) — внешний процесс, а `provider-timestamps@1` арифметичен и
 * оборачивает свою чистую функцию (`requiresNetwork: false`). Что обёртка отдаёт ровно то же,
 * что чистая функция, проверяется тестом — прецедент `mockProvider`.
 *
 * `pcm` принимают ВСЕ биндеры, включая те, кому он не нужен: у формы стадии один вход, иначе
 * потребителю пришлось бы знать, кого он зовёт, — то есть ветвиться по имени.
 */
export interface Binder {
  /** `'provider-timestamps@1' | 'ctc-fa@1' | 'mfa@3'`. В `if` — нет (**V16**). */
  readonly binderId: string;
  /** `false` — биндер исполним в тестовом контуре без сети и без ключа (**V9**). */
  readonly requiresNetwork: boolean;
  bind(
    pcm: Uint8Array,
    sampleRate: number,
    spokenText: string,
    tokens: readonly SourceTokenRef[],
    providerAlignment?: ProviderAlignment,
  ): Promise<readonly TokenBinding[]>;
}

/**
 * Блок `bind` take-файла — то, чем привязки ПЕРЕСЧИТЫВАЮТСЯ из одного лишь артефакта
 * (решение владельца, `V-05` вопрос 4, вариант «А»).
 *
 * ЗАЧЕМ ОН ЕСТЬ. Критерий готовности roadmap — «take-файл самодостаточен: привязки
 * пересчитываются БЕЗ старого нормализатора». Для `provider-timestamps@1` времена берутся
 * ТОЛЬКО из ответа провайдера, а ответ невоспроизводим (`FACT` r1 §2.3: «Determinism is not
 * guaranteed»); не лёг он в файл — пересчёт невозможен вовсе, и критерий выродился бы в
 * тождество «привязки уже лежат в файле», то есть в тест ни о чём.
 *
 * ЧЕМ ЭТОТ БЛОК НЕ ЯВЛЯЕТСЯ (требование владельца, записано в форму намеренно):
 * **`providerAlignment` — ДИАГНОСТИЧЕСКИЙ ВХОД ПЕРЕСЧЁТА, А НЕ ВТОРАЯ ИСТИНА О ВРЕМЕНИ.**
 * Единственный потребляемый выход стадии — `bindings[]` (сэмплы, статусы). Читать времена
 * прямо из `alignment` — значит завести вторую точку конверсии секунд провайдера (запрещено
 * `V-01`: она одна, `providerSecondsToSamples`) и обойти статусы **V8**. Компилятор
 * (`CP-01`) читает `bindings[]`; сюда он не заглядывает.
 */
export interface TakeBind {
  /** Чем измерено. В артефакте — да; в условии — нет (**V16**). */
  readonly binderId: string;
  /** Токены исходника с якорями — второй вход пересчёта. Порядок — порядок исходника. */
  readonly tokens: readonly SourceTokenRef[];
  /** Ответ провайдера как он пришёл. `null` — биндер, которому alignment не нужен. */
  readonly providerAlignment: ProviderAlignment | null;
}

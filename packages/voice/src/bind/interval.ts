// Правило построения интервала токена (ADR-0010 §6) — **ПЕРЕЕЗД** из `providers/mock.ts`.
//
// ПОЧЕМУ ПЕРЕЕЗД, А НЕ КОПИЯ. Это правило стадии `bind`, а не свойство провайдера: адрес
// назван отчётом `V-04` §6 п. 6 дословно — «спайковое правило `PUNCT` не переносится… его
// адрес `V-05` (`bind`)». В `V-01` оно физически лежало в `mock.ts`, потому что там же лежала
// его спайковая форма и там же был единственный потребитель. Теперь потребителей два (биндер
// и mock), и владеет правилом тот, чьё оно, — mock остаётся ПОТРЕБИТЕЛЕМ, ровно как он уже
// потребитель приёмки (`V-02`).
//
// САМО ПРАВИЛО, ДОСЛОВНО (ADR-0010 §6): интервал = `[start` первого небелого символа,
// `end` последнего небелого символа`]`; пробелы и пунктуация в интервал слова НЕ входят;
// интервал токена исходника = объединение интервалов его произнесённых слов (объединение
// исполняет биндер, `provider-timestamps.ts`).
//
// `FACT` (SP-2, findings D10 п.6 + SP-2b.3; два голоса, 5 разделителей `,` `;` `.` `—` `…`):
// вся межпредложенческая пауза лежит на ЗНАКЕ и ПРОБЕЛАХ, сумма «знак + пробелы» равна зазору
// на 5/5 вариантах; длительность буквы до разделителя (81–117 мс) и после (23–59 мс) остаётся
// в обычном диапазоне букв. `INFERENCE`: правило исключает ровно те две категории символов, на
// которые провайдер кладёт паузу, — и потому переменность пропорции ему безразлична.
//
// ЧТО ИЗМЕНИЛОСЬ ПРОТИВ `V-01`, И ЭТО ЕДИНСТВЕННОЕ ИЗМЕНЕНИЕ ПОВЕДЕНИЯ. Классы символов
// перестали браться из ПРОФИЛЯ MOCK'А. В `mock.ts` «знак препинания» означало «ключ таблицы
// `MOCK_PROFILE.punctuationPauseMs`» (девять символов), то есть правило, применяемое к ответу
// ЖИВОГО провайдера, зависело бы от таблицы пауз синтетического. Здесь класс — свойство
// Unicode: `\p{P}` (пунктуация) и `\p{White_Space}` (пробельные). Оба — обычные regexp-эскейпы
// ECMAScript (ES2018), не `Intl` и не локаль: запрет **V8**/D4 их не касается, результат от
// часового пояса и языка среды не зависит.
//
// ЧТО ЭТО СТОИЛО НА УЖЕ ИЗМЕРЕННОМ МАТЕРИАЛЕ — НОЛЬ. Все девять знаков таблицы mock'а
// (`. ! ? … , ; : — –`) входят в `\p{P}`; парные кавычки (`"` `“` `”`), которые в `V-01`
// перечислялись отдельным условием, — тоже (`Po`/`Pi`/`Pf`), поэтому отдельного условия для
// них больше нет. Ловушки, на которых стоит `token-status.test.ts`, сохраняют свой класс:
// `+` — `Sm`, `©` — `So`, `🚢`/`👍` — `So`, то есть НЕ пунктуация, и токены `5+`, `©c`, `hi🚢`
// остаются одним словом, как в `V-01`; `§` — `Po`, и он пунктуация в обеих редакциях.
// Проверяется это тестом на пяти разделителях и переехавшими проверками статусов.

import { timeAt } from '../acceptance/health.js';
import type { ProviderAlignment } from '../providers/types.js';

/**
 * Пробельный символ. Шире, чем `isWhitespace` из `C-02` (там ровно `' '`, `'\t'`, `'\n'`), и
 * это не расхождение: `C-02` судит ИСХОДНИК, уже приведённый к NFC и `\n` первым шагом лексера,
 * а здесь судится ОТВЕТ ПРОВАЙДЕРА — байты, через нормализацию исходника не проходившие.
 * NBSP (` `), который в `V-01` перечислялся эскейпом отдельной строкой, входит сюда сам.
 */
const WHITE_SPACE = /\p{White_Space}/u;

/** Пунктуация Unicode. `Sm`/`So` (`+`, `©`, эмодзи) сюда НЕ входят — см. шапку файла. */
const PUNCTUATION = /\p{P}/u;

/**
 * Произносим ли текст: есть ли в нём хоть одна буква или цифра.
 *
 * ПОЧЕМУ ПО КЛАССУ СИМВОЛА, А НЕ ПО ИЗМЕРЕННОЙ ДЛИТЕЛЬНОСТИ (перенос довода `V-01`). У
 * `tts:mock@1` эмодзи получает обычную длительность буквы — он арифметический и про
 * произносимость не знает ничего. У настоящего провайдера `FACT` (SP-2 U6): непроизносимый
 * code point получает интервал НУЛЕВОЙ длины. Выводись статус из длительности — правило
 * «токен из одних непроизносимых ⇒ `absent`» (ADR-0010 §1, §5, **V8**) на mock'е не
 * срабатывало бы вовсе, то есть его нельзя было бы проверить в тестовом контуре (**V9**), а
 * именно там оно и проверяется.
 */
export function isPronounceable(text: string): boolean {
  return /[\p{L}\p{N}]/u.test(text);
}

/** Слово — максимальный ряд символов, не пробельных и не пунктуационных. */
export interface Word {
  readonly text: string;
  /** Индекс ПЕРВОГО code point слова во входном массиве. */
  readonly startIndex: number;
  /** Индекс ПОСЛЕДНЕГО code point слова, включительно. */
  readonly endIndex: number;
}

/**
 * Разбиение потока code point'ов на слова по правилу §6 — ЕДИНСТВЕННОЕ место этого разбиения.
 *
 * Вход — массив code point'ов, а не строка, потому что у одного из двух вызывающих он уже
 * массив (`alignment.characters`), а у второго получается из `[...text]`. Единица индексации —
 * code point (ADR-0010 §10 F13), и второй меры длины в этом файле нет.
 */
export function wordsOf(points: readonly string[]): readonly Word[] {
  const out: Word[] = [];
  let start = -1;

  for (let i = 0; i < points.length; i += 1) {
    const c = points[i] ?? '';
    const wordish = !WHITE_SPACE.test(c) && !PUNCTUATION.test(c);
    if (wordish) {
      if (start < 0) start = i;
    } else if (start >= 0) {
      out.push({ text: points.slice(start, i).join(''), startIndex: start, endIndex: i - 1 });
      start = -1;
    }
  }
  if (start >= 0) {
    out.push({ text: points.slice(start).join(''), startIndex: start, endIndex: points.length - 1 });
  }
  return out;
}

/**
 * Интервал слова в ответе провайдера. `absent` времени НЕ несёт — ни `[t, t]`, ни `null`-заглушки
 * в секундах.
 *
 * Размеченное объединение, а не поле-флаг: та же форма и по той же причине, что у
 * `TokenBinding` (`providers/types.ts`) — состояние «времени нет» обязано быть невыразимо
 * иначе, а не запрещено проверкой.
 */
export type TokenInterval =
  | {
      readonly text: string;
      readonly startIndex: number;
      readonly status: 'measured';
      /** Секунды: интервал живёт в домене таймкодов провайдера, перевод — в биндере. */
      readonly start: number;
      readonly end: number;
    }
  | {
      readonly text: string;
      readonly startIndex: number;
      readonly status: 'absent';
      readonly start: null;
      readonly end: null;
    };

/**
 * Слова ответа провайдера с их временами — правило §6, применённое к `alignment`.
 *
 * Статус решается ЗДЕСЬ и только здесь (**V8**): слово без единой буквы и цифры уходит
 * `absent` и СВОЁ ИЗМЕРЕННОЕ ВРЕМЯ ТЕРЯЕТ — иначе субтитр получил бы слово нулевой (у
 * настоящего провайдера) длительности, и это прошло бы мимо всех проверок.
 *
 * @throws {VoiceError} `ADR-0010 §1` — массив времён разрежен при заявленной длине (`timeAt`).
 */
export function tokenIntervals(alignment: ProviderAlignment): readonly TokenInterval[] {
  return wordsOf(alignment.characters).map((word) =>
    isPronounceable(word.text)
      ? {
          text: word.text,
          startIndex: word.startIndex,
          status: 'measured',
          start: timeAt(
            alignment.character_start_times_seconds,
            word.startIndex,
            'character_start_times_seconds',
          ),
          end: timeAt(alignment.character_end_times_seconds, word.endIndex, 'character_end_times_seconds'),
        }
      : { text: word.text, startIndex: word.startIndex, status: 'absent', start: null, end: null },
  );
}

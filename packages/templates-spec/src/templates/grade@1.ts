// `grade@1` — единый тон поверх сцены: цветокоррекция, виньетка, зерно.
//
// **ФОРМА ВЫБРАНА НЕ ЗДЕСЬ.** Решение владельца 11 (RM2, roadmap §8 и §4 `E-07`) называет
// CSS-фильтры — `saturate`, `contrast`, `hue-rotate`, `sepia` — и отклоняет два соседних
// варианта: **LUT-ассет** (provenance по V10, `declareAssets`, вход в `segmentKey` и ещё один
// WebGL-слой в запас AC2 ×1.42) и **расширение реестра D5 на цвет** (гамма без `Math.pow`
// только аппроксимируется, то есть это отдельное решение, а не деталь). Условие пересмотра
// записано словами: «тон канала не выражается фильтрами».
//
// **РЕЕСТР D5 НЕ ЗАТРАГИВАЕТСЯ ВОВСЕ, И ЭТО НЕ ОБЕЩАНИЕ, А СВОЙСТВО ФОРМЫ.** Фильтр —
// декларативное свойство, применяемое браузером; кривой в нашем коде нет, `easingIds` пуст,
// твина нет ни одного. Запрет `Math.pow/sin/exp` в рендер-пути остаётся дословно и охраняется
// тем же линтом (`tests/lints/d5-easing-render-path.test.ts`), что и до этого шаблона.
//
// **ШЕСТЬ ПАРАМЕТРОВ, А НЕ ЧЕТЫРЕ, И ДВА ЛИШНИХ НАЗВАНЫ.** Четыре — из решения 11 дословно.
// `vignette` и `grain` добавлены заданием `E-07` и обе остаются в границах того же решения:
// виньетка есть `radial-gradient` (чистая декларация, не вычисление), зерно —
// SVG `feTurbulence` с ФИКСИРОВАННЫМ `seed` (тоже декларация: шум считает браузер по
// алгоритму, нормированному спецификацией SVG, а не наш код). Ни то, ни другое не заводит
// ассета — зерно процедурное, файла у него нет, `declaredAssets` пуст.
//
// **ЧИСЛА ЗДЕСЬ НЕ ЖИВУТ.** Схема держит ГРАНИЦЫ, а умолчания принадлежат коду шаблона
// (`renderer-hyperframes/src/templates/grade@1.ts`) — ровно то правило, которое `still@1`
// записал для `fit`: «умолчание в схеме — это число, которое видит валидатор и не видит
// автор». Все шесть полей поэтому НЕОБЯЗАТЕЛЬНЫ: автор вправе тронуть одну ось и оставить
// остальные тону канала.
//
// **ГРАНИЦЫ — ГРАНИЦЫ ОСМЫСЛЕННОГО, А НЕ ГРАНИЦЫ CSS.** CSS принял бы `saturate(40)`;
// `grade@1` — нет, потому что тон канала не выражается сорокакратной насыщенностью, а
// опечатка в единице измерения (проценты вместо доли) выражается ею прекрасно. Отказ схемы
// с путём к полю дешевле кадра, на который смотрят.

import { z } from 'zod';

import type { TemplateManifest } from '../manifest.js';
import type { TemplateSpec } from '../spec.js';

/**
 * Множитель — доля, а не проценты. Верхняя граница 4 выбрана как «вчетверо» — предел, за
 * которым это уже не тон, а другой шаблон; нижняя 0 — полное снятие (законно: `saturate(0)`
 * есть чёрно-белый архив, и он назван вариантом тона, а не ошибкой).
 */
const multiplier = (what: string): z.ZodNumber =>
  z
    .number()
    .min(0, `${what}: множитель — доля, не проценты; 0 — полное снятие`)
    .max(4, `${what}: больше четырёхкратного — это не тон канала, а другой шаблон`);

/** Доля 0…1: `sepia`, `vignette`, `grain`. */
const fraction = (what: string): z.ZodNumber =>
  z.number().min(0, `${what}: доля 0…1`).max(1, `${what}: доля 0…1`);

const ParamsSchema = z
  .object({
    /** `saturate()`: 1 — как есть, ниже — приглушённее, 0 — чёрно-белое. */
    saturate: multiplier('`saturate`').optional(),
    /** `contrast()`: 1 — как есть. */
    contrast: multiplier('`contrast`').optional(),
    /** `sepia()`: доля перевода в сепию. */
    sepia: fraction('`sepia`').optional(),
    /**
     * `hue-rotate()` в ГРАДУСАХ — единственное поле не-доля, и единица названа в имени.
     *
     * Полный оборот в обе стороны: −360…360. Шире не бывает по смыслу (оборот замкнут), уже
     * — было бы запретом на законный поворот.
     */
    hueRotate: z
      .number()
      .min(-360, '`hueRotate`: градусы, −360…360')
      .max(360, '`hueRotate`: градусы, −360…360')
      .optional(),
    /** Сила виньетки: 0 — нет, 1 — чёрные края. */
    vignette: fraction('`vignette`').optional(),
    /**
     * Сила зерна: 0 — нет, 1 — предел.
     *
     * **Зерно СТАТИЧНО и не анимируется покадрово** — это свойство реализации (`seed`
     * фиксирован константой шаблона), а не параметра; анимированное зерно потребовало бы
     * источника случайности на кадр и упёрлось бы в guard **D4**.
     */
    grain: fraction('`grain`').optional(),
  })
  .strict();

/** Разобранные `params` шаблона `grade@1`. */
export type GradeParams = z.infer<typeof ParamsSchema>;


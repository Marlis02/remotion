// `kenburns@1` — медленный наезд/отъезд по кадру. Спек: схема `params`, две декларации,
// манифест. **Кода рендера здесь нет ни строки** — он живёт в `renderer-hyperframes`
// (`E-*`/`H-06`), а этот пакет рендерера не знает (**M1**, **M6**).
//
// НОРМА `params` — `fixtures/minimal/direction/01-intro.yaml`, запись `a3f19c2b`:
// `from: {scale, x, y}`, `to: {scale, x, y}`, `easing: "power2.inOut"`. Ни одного поля сверх
// того, что лежит в фикстуре: поле, которого автор не писал, — это поведение, которого никто
// не решал.
//
// **`declareAssets` — ПУСТО** (решение владельца `TS-01`, вопрос 5). В `params` этого шаблона
// ассета нет вовсе: он анимирует то, что лежит под ним, — эффект над визуальным слоем, а не
// собственная картинка. Отсюда `declaredAssets: []` в манифесте. Семантика «эффект над слоем»
// — то есть КАК именно слой под ним выбирается — принадлежит `TS-02`/`E-*`, и выдумывать её
// здесь значило бы решать за них.
//
// ПОРЯДОК ТРАНСФОРМАЦИЙ ЗДЕСЬ НЕ ОБЪЯВЛЯЕТСЯ, И ЭТО ВАЖНО ИМЕННО ДЛЯ ЭТОГО ШАБЛОНА.
// `FACT` (SP-3c §6.2 п. 3): GSAP собирает `translate → scale`, Remotion в SP-3 — наоборот, и
// на Ken Burns разница доходит до 5.4 px на последнем кадре. Порядок фиксирует реестр easing
// (`TS-02`, строка **D5**), а не спек: иначе он был бы записан в двенадцати местах. С `TS-02`
// у этого предложения есть адрес — `TRANSFORM_ORDER` в [`easing.ts`](../easing.ts).

import { z } from 'zod';

import type { EasingId } from '../easing.js';
import type { TemplateManifest } from '../manifest.js';
import { geometry } from '../params.js';
import type { TemplateSpec } from '../spec.js';

/**
 * Кривые, которые шаблон объявляет, что умеет, — **ПОДМНОЖЕСТВО закрытого реестра**.
 *
 * **Один источник на схему и на манифест.** `easingIds` манифеста и `z.enum` схемы — это одна
 * константа, а не два списка: два разъехались бы, и шаблон принимал бы кривую, которой не
 * объявлял. ~~Членство `power2.inOut` в РЕЕСТРЕ easing проверяет `TS-02`.~~ *(изменено:
 * `TS-02`, 2026-08-28.)* Реестр появился ([`easing.ts`](../easing.ts)), и членство проверяется
 * ЗДЕСЬ ЖЕ, типом: `satisfies readonly EasingId[]` закрывает список кривых шаблона реестром на
 * КОМПИЛЯЦИИ. Отсюда «один источник» стал двухуровневым и остался одним: реестр говорит, какие
 * кривые вообще существуют; эта константа — какие из них объявил этот шаблон.
 *
 * СПИСОК ОСТАЛСЯ ИЗ ОДНОГО ИМЕНИ, И ЭТО НЕ НЕДОСМОТР. Импортировать сюда весь `EASING_REGISTRY`
 * значило бы объявить, что `kenburns@1` умеет шесть кривых, — то есть сменить поведение схемы
 * `params` правкой, задуманной как смена ИСТОЧНИКА. Шаблон объявляет то, что объявлял.
 *
 * Почему именно эта кривая: фикстура приведена к реестру решением RM2 (дрейф roadmap §9 п. 8),
 * `easing: "power2.inOut"` вместо прежнего `inOutCubic`, которого в уточнённом реестре нет.
 * ~~`INFERENCE`, записанный там же: cubic in-out у GSAP называется `power2.inOut`.~~
 * *(изменено: `TS-02`, 2026-08-28.)* **`FACT`, ИЗМЕРЕНО:** `gsap@3.15.0`,
 * `parseEase('power2.inOut')` совпадает с cubic in-out (`t < 0.5 ? 4t³ : 1 − (−2t+2)³/2`) с
 * расхождением не более `1.39e-17` на сетке 0…1 шаг 0.1 — охранник
 * [`easing-parity.test.ts`](../../../renderer-hyperframes/test/easing-parity.test.ts).
 * Фикстура правки не потребовала.
 */
const EASING_IDS = ['power2.inOut'] as const satisfies readonly EasingId[];

/** Опорная точка кадрирования: масштаб и смещение в долях кадра. */
const FrameStopSchema = z
  .object({
    /** Масштаб. `1.00` — кадр целиком; `1.12` фикстуры — наезд на 12 %. */
    scale: geometry(),
    /** Смещение по горизонтали в долях ширины кадра. */
    x: geometry(),
    /** Смещение по вертикали в долях высоты кадра. */
    y: geometry(),
  })
  .strict();

const ParamsSchema = z
  .object({
    from: FrameStopSchema,
    to: FrameStopSchema,
    easing: z.enum(EASING_IDS),
  })
  .strict();

/** Разобранные `params` шаблона `kenburns@1`. */
export type KenburnsParams = z.infer<typeof ParamsSchema>;

const manifest: TemplateManifest = {
  templateId: 'kenburns',
  templateVersion: 1,
  declaredAssets: [],
  declaredFonts: [],
  // Записей нет и быть не может: рендерера нет, прогонов не было. Ноль записей — честное
  // состояние, и именно на нём **R12** обязана не пустить сборку.
  gates: [],
  // `INFERENCE`, не `FACT`: этот шаблон не измерял ни один спайк. Ближайшее измеренное —
  // стеклянная карточка (`FACT` SP-3f §2: +0.9 мс/кадр при разбросе серии ±4.7 %, то есть
  // «ниже шума»). Ken Burns дешевле по эффектам, но масштабирует полноэкранное фото, поэтому
  // взято вдвое больше «ниже шума». Число заменяется ИЗМЕРЕНИЕМ при прохождении гейта
  // (`E-00`), и до тех пор оно — оценка, а не результат.
  msPerFrameBudget: 2,
  easingIds: [...EASING_IDS],
  needsAudioFeatures: false,
  // Случайности шаблон не требует: `from`/`to`/`easing` заданы автором целиком. ADR-0007 §1
  // приводит `'kenburns.jitter'` как ПРИМЕР формы `purpose`, а не как параметр этого шаблона;
  // джиттера у `kenburns@1` нет ни в одном документе проекта. Пустой список — измерение.
  purposes: [],
};

/** `kenburns@1` — контракт шаблона фикстуры. */
export const kenburns1: TemplateSpec<KenburnsParams> = {
  templateId: 'kenburns',
  templateVersion: 1,
  paramsSchema: ParamsSchema,
  declareAssets: () => [],
  declareFonts: () => [],
  manifest,
};

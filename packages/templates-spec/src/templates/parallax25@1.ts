  templateId: 'parallax25',
  templateVersion: 1,
  paramsSchema: ParamsSchema,
  // Роль несёт МЕСТО слоя в списке, а место есть глубина: `layer0` — самый дальний. Порядок
  // деклараций сохраняет `contract.ts` компилятора, поэтому в IR роли приедут в том же
  // порядке, в каком их написал автор.

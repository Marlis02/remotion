// `parallax25@1` — 2.5D-параллакс на слоях, нарезанных АВТОРОМ. Спек: схема `params`, две
// декларации, манифест. **Кода рендера здесь нет ни строки** — он живёт в
// `renderer-hyperframes` (`E-02`), а этот пакет рендерера не знает (**M1**, **M6**).
//
// **СЛОИ РЕЖЕТ АВТОР, А НЕ ДВИЖОК** (решение владельца `E-02`, 2026-08-31, вариант «а»).
// Оценки глубины, сегментации и ML в шаблоне нет и не будет: каждый слой приезжает ОТДЕЛЬНЫМ
// ассетом каталога, у производного слоя в записи стоит `derivedFrom` (sha исходного снимка +
// инструмент и его версия), а статус лицензии наследуется от источника по цепочке
// (`resolveProvenance`, `media/src/assets/catalog.ts`). Отсюда `layers` — СПИСОК ALIAS'ОВ, а
// не «путь к фото и число слоёв»: шаблон не имеет права породить файл, у которого нет
// provenance (**V10**).
//
// **ПОРЯДОК СПИСКА — ОТ ДАЛЬНЕГО К БЛИЖНЕМУ, И ЭТО ЧАСТЬ КОНТРАКТА, А НЕ СОГЛАШЕНИЕ.** По
// нему реализация раскладывает слои по глубине внутри своего `host` и по нему же считает
// амплитуду каждого: дальний движется медленнее ближнего в `depthSpread` раз. Обратный
// порядок дал бы законный, компилирующийся и НЕВЕРНЫЙ кадр — фон, едущий быстрее фигуры.
// Поэтому порядок назван здесь словами, а не подразумевается индексами ролей.
//
// **РОЛЬ АССЕТА — `layer<i>`, И ЭТО ТО ЖЕ ПРАВИЛО, ЧТО У `still@1`.** Роль есть имя
// параметра, который ассет держит (ADR-0002 §4, шапка `refs.ts`); у списочного параметра имя
// одного элемента — это имя списка с индексом. Общая роль `'layers'` на все четыре ассета
// сделала бы список запроса неразличимым: реализация ищет ассет ПО РОЛИ (`still@1` дословно:
// «индекс `[0]` работал бы ровно до первого шаблона с двумя ассетами и сломался бы молча»).
//
// **`declaredAssets` ПЕРЕЧИСЛЯЕТ ВСЕ ЧЕТЫРЕ РОЛИ, ХОТЯ ВЫЗОВ ОБЪЯВЛЯЕТ ОТ ОДНОЙ ДО ЧЕТЫРЁХ.**
// Манифест обязан быть НАДМНОЖЕСТВОМ ролей `declare*` (`manifest.ts`, дословно: «шаблон с
// необязательным ассетом объявит роль в манифесте и не вернёт её на `params` без ассета») —
// здесь это ровно тот случай, только необязательных ролей три.
//
// **ОДИН СЛОЙ — ЗАКОННЫЙ ВХОД, А НЕ ВЫРОЖДЕНИЕ ВХОДА** (решение владельца `E-02`, вариант
// «в»). Нарезка стоит времени автора, и шаблон обязан работать до неё: с одним слоем
// реализация строит ЛОЖНЫЙ параллакс — ближний план есть само фото, дальний — оно же,
// увеличенное и размытое. Настоящий 2.5D начинается с двух слоёв. Схема этого различия НЕ
// делает: и то и другое — законный вызов, а разница живёт в коде шаблона (`E-02`), как
// умолчание `fit` у `still@1`.
//
// ПЯТЫЙ СЛОЙ — ОТКАЗ СХЕМЫ (протокол нарушений `E-02`, Н1). Потолок в четыре взят у roadmap
// §3 (`parallax25@1` — «2.5D-параллакс, 4 слоя») и стоит ЗДЕСЬ, а не в реализации: список,
// который валидатор пропустил, реализация обязана уметь нарисовать.

import { z } from 'zod';

import type { EasingId } from '../easing.js';
import type { TemplateManifest } from '../manifest.js';
import { aliasRef, geometry } from '../params.js';
import type { AssetRef } from '../refs.js';
import type { TemplateSpec } from '../spec.js';

/**
 * Потолок числа слоёв — **четыре** (roadmap §3, строка `E-02`).
 *
 * Число не «на всякий случай»: каждый слой есть отдельная полноэкранная картинка, которую
 * браузер ресэмплирует на КАЖДОМ кадре, — то есть цена шаблона линейна по этой величине
 * (измерение бюджета — отчёт `E-02` §бюджет). Потолок здесь и есть форма, в которой эта цена
 * ограничена.
 */
export const MAX_PARALLAX_LAYERS = 4;

/**
 * Префикс роли слоя — **одна строка на три стороны границы**.
 *
 * Её читают: схема и манифест здесь, реализация в `renderer-hyperframes` (она собирает имя
 * роли ВНУТРИ текста `mountSource`, интерполируя эту константу) и билдер запросов гейта.
 * Вторая копия строки означала бы, что спек объявляет роль `layer0`, а реализация ищет
 * `depth0`, — и обе стороны были бы зелены поодиночке.
 */
export const LAYER_ROLE_PREFIX = 'layer';

/** Имя роли слоя по его месту в списке — **единственный источник** для схемы и реализации. */
export function layerRole(index: number): string {
  return `${LAYER_ROLE_PREFIX}${String(index)}`;
}

/**
 * Роли ассетов — `layer0`…`layer3`, **выведены из потолка, а не выписаны списком**.
 *
 * Две копии (список ролей и потолок) разъехались бы при первой правке: манифест объявлял бы
 * четыре роли, а схема принимала пять alias'ов. Здесь величина одна, и это она же —
 * надмножество, которого требует `manifest.ts` (см. шапку файла).
 */
const LAYER_ROLES: readonly string[] = Array.from({ length: MAX_PARALLAX_LAYERS }, (_, index) =>
  layerRole(index),
);

/**
 * Кривая, которую шаблон объявляет, что умеет, — **ПОДМНОЖЕСТВО закрытого реестра**.
 *
 * Тот же приём, что у `kenburns@1` (`TS-02`): `satisfies readonly EasingId[]` закрывает
 * список реестром на КОМПИЛЯЦИИ, а `z.enum` и `easingIds` манифеста читают ОДНУ константу —
 * два списка разъехались бы, и шаблон принимал бы кривую, которой не объявлял.
 *
 * Кривых две, и обе названы по делу. `power2.inOut` — ход с плавным началом и концом, тот же,
 * которым идёт `kenburns@1` в демо: у параллакса ровно та же задача — движение, которое не
 * начинается рывком. `none` — линейный проход без ускорения; он нужен потому, что на дрейфе
 * длиной в сцену ускорение читается как «камера дёрнулась», и автор обязан иметь возможность
 * его выключить. Остальные четыре кривые реестра (`power1.inOut`, `power3.out`,
 * `back.out(1.7)`, `sine.inOut`) не объявлены: `back.out` уводит слой ЗА конечную точку, то
 * есть за посчитанный запас покрытия кадра (см. `drift` ниже), а три остальные никем для
 * этого шаблона не названы — объявить их значило бы решить за автора, не измерив.
 */
const EASING_IDS = ['power2.inOut', 'none'] as const satisfies readonly EasingId[];

/** Доля кадра в диапазоне `[0, 0.2]` — амплитуда дрейфа ближнего слоя. */
const driftFraction = (): z.ZodType<number> =>
  geometry().refine(
    (value) => value >= 0 && value <= 0.2,
    '`drift`: доля кадра от 0 до 0.2 включительно (решение владельца `E-02`)',
  );

/** Во сколько раз дальний слой медленнее ближнего: `>= 1`. */
const depthSpreadRatio = (): z.ZodType<number> =>
  geometry().refine(
    (value) => value >= 1,
    '`depthSpread`: во сколько раз ДАЛЬНИЙ слой медленнее ближнего, то есть `>= 1`. ' +
      'Значение меньше единицы означало бы фон, едущий быстрее переднего плана, — это не ' +
      'параллакс, а его зеркало',
  );

/** Масштаб «дыхания»: положительный конечный множитель. */
const breathScale = (): z.ZodType<number> =>
  geometry().refine(
    (value) => value > 0,
    '`scale`: положительный множитель («дыхание» кадра). Ноль и отрицательные схлопывают ' +
      'или отражают слой, а не масштабируют его',
  );

const ParamsSchema = z
  .object({
    /**
     * Слои от ДАЛЬНЕГО к БЛИЖНЕМУ — alias'ы каталога, от одного до четырёх.
     *
     * Повторы не запрещены схемой намеренно: один и тот же alias дальним и ближним слоем —
     * это законный приём (тот же снимок в двух планах), а не опечатка, и решает его автор.
     */
    layers: z.array(aliasRef()).min(1).max(MAX_PARALLAX_LAYERS),
    /**
     * Амплитуда дрейфа БЛИЖНЕГО слоя в долях кадра (по 0.2 в каждую сторону от центра).
     *
     * Доли, а не пиксели: `compileProfile` шаблону не виден (**K4**), и пиксель здесь
     * означал бы разное на `draftHalf` и `final`. Ноль законен — параллакс без движения есть
     * стопка слоёв, и это осмысленный кадр.
     */
    drift: driftFraction(),
    /**
     * Во сколько раз ДАЛЬНИЙ слой медленнее ближнего. Единица — все слои идут вместе,
     * то есть глубины нет; чем больше, тем сильнее расслоение.
     */
    depthSpread: depthSpreadRatio(),
    easing: z.enum(EASING_IDS),
    /**
     * «Дыхание» — общий масштаб, к которому слои приходят к концу окна. Необязательно:
     * параллакс осмыслен и без наезда, и умолчание принадлежит коду шаблона, а не схеме
     * («умолчание в схеме — это число, которое видит валидатор и не видит автор», `still@1`).
     */
    scale: breathScale().optional(),
  })
  .strict();

/** Разобранные `params` шаблона `parallax25@1`. */
export type Parallax25Params = z.infer<typeof ParamsSchema>;


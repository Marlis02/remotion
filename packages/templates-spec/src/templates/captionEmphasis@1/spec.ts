// `captionEmphasis@1` — ВИД ПОЛОСЫ СУБТИТРОВ И ЭМФАЗА АКТИВНОГО СЛОВА.
//
// ═══ ЧТО ИЗМЕНИЛА `CAPTION-01` (2026-09-11, решение владельца) ═══
// ~~`style: bold` — ЗАКРЫТЫЙ СПИСОК ИЗ ОДНОГО ЗНАЧЕНИЯ.~~ Одного поля больше нет. Владелец
// назвал предмет прямо: «шрифт, кегль, фон (цвет / прозрачный / полупрозрачный), цвет текста,
// цвет активного слова, положение — и, как в шортсах, обводку/тень для читаемости без
// плашки». До этой задачи всё перечисленное было ЗАШИТО в двух местах: акцентный цвет — в
// реализации шаблона, а плашка, кегль и положение — константами `BAND` в
// [`composition/runtime.js`](../../../../renderer-hyperframes/src/composition/runtime.js),
// то есть автор не мог поменять вид субтитров, не правя код движка.
//
// **ГДЕ ТЕПЕРЬ ЖИВЁТ ВИД ПОЛОСЫ — ЧЕСТНЫЙ ОТВЕТ В ДВУХ ЧАСТЯХ.** Умолчание канала осталось в
// `runtime.js`: полосу рисует ТРЕК `IR.captions`, а клип эмфазы есть в меньшинстве сегментов,
// и сегмент без клипа обязан получить полосу на месте и в нужном кегле (это решение `H-07`, и
// оно не отменено). Изменилось второе: теперь клип, если он есть, **подаёт рантайму свои
// значения данными**, и рантайм накладывает их поверх умолчания. Отсюда два следствия,
// названные вслух:
//   * ручка, которую автор не написал, берётся из умолчания канала — а не из второго
//     комплекта чисел в этом файле. Поэтому НИ ОДНО поле ниже не имеет `.default()`: второе
//     место, где живут те же числа, разъехалось бы с первым в день первой правки;
//   * ручки, поданные клипом, действуют на ВЕСЬ сегмент, а не на окно клипа. Полоса одна, и
//     менять её вид в середине сегмента нечем — это названо долгом, а не сделано молча.
//
// **СЕМЕЙСТВО ШРИФТА ПО-ПРЕЖНЕМУ НЕ НАЗЫВАЕТСЯ ЗДЕСЬ** (долг №13, за владельцем). Шаблон
// объявляет РОЛЬ, семейство подставляет проект. Новое поле `font` — это имя РОЛИ, а не имя
// гарнитуры: `FontRef.family` необязателен именно для такого случая. Вписать сюда
// `family: 'DejaVu Sans'` значило бы увезти временный выбор в `engineFingerprint` вместе с
// первым же гейтом.
//
// **МАРКЕР `[emph]` ОСТАЁТСЯ ЧИСТО ВИЗУАЛЬНЫМ** (Charter V5): голосовой эмфазы в v1 нет, TTS
// этого маркера не видит и денег он не стоит. Ручка `weight` — начертание АКТИВНОГО слова по
// оси `wght` вариативного шрифта, как и было; расширение с одного значения до двух не решает
// за `DOC-06` вопрос scope маркера (долг №128) — оно вообще его не касается.

import { z } from 'zod';

import type { TemplateManifest } from '../../manifest.js';
import { geometry, hexColor } from '../../params.js';
import type { FontRef } from '../../refs.js';
import type { TemplateSpec } from '../../spec.js';

/** Роль шрифта по умолчанию — та же строка, что жила в `declaredFonts` до `CAPTION-01`. */
const FONT_ROLE = 'caption';

/**
 * Грамматика имени роли шрифта — та же, что у имени пресета (`presets.ts`).
 *
 * Роль называет ПРОЕКТ (`fonts/records`), а не шаблон, поэтому закрытого списка здесь быть не
 * может; закрыта только форма, чтобы опечатка `Caption ` с пробелом стала отказом схемы, а не
 * отказом реализации в браузере на третьей стадии.
 */
const FONT_ROLE_NAME = /^[a-z][a-z0-9-]*$/u;

/** Кегль субтитра в пикселях БАЗОВОГО кадра (1080×1920), а не черновика. */
const SIZE_MIN = 40;
const SIZE_MAX = 120;
/** Отступ полосы от края кадра по `position`. Потолок — чуть больше трети высоты 1920. */
const MARGIN_MIN = 0;
const MARGIN_MAX = 600;
/** Доля ширины кадра под блок субтитров. Ниже 40 % строка ломается на каждом слове. */
const WIDTH_PCT_MIN = 40;
const WIDTH_PCT_MAX = 95;
/** Толщина обводки. Выше восьми пикселей контур съедает внутренности букв. */
const OUTLINE_MAX = 8;

/** Фон под текстом. Три значения, и третье — ОТСУТСТВИЕ плашки, а не прозрачный цвет. */
const BACKGROUNDS = ['plate', 'translucent', 'none'] as const;
/** Начертание активного слова по оси `wght`. КЛЮЧЕВЫМИ СЛОВАМИ — см. реализацию. */
const WEIGHTS = ['regular', 'bold'] as const;
/** Положение полосы по вертикали. */
const POSITIONS = ['bottom', 'center', 'top'] as const;

/**
 * Тень под текстом — **четыре числа и отдельная прозрачность**.
 *
 * `opacity` ОТДЕЛЬНЫМ ПОЛЕМ, а не альфой в цвете, и это не украшение формы: умолчание канала
 * — `rgba(0, 0, 0, 0.55)`, и шестицифровой hex такую тень невыразим, а `#rrggbbaa` дал бы
 * альфу 140/255 = 0.549, то есть ДРУГОЙ пиксель при том же намерении. Выключается нулями:
 * `blurPx: 0` с нулевыми сдвигами — тени нет.
 */
const ShadowSchema = z
  .object({
    dxPx: z.int(),
    dyPx: z.int(),
    blurPx: z.int().nonnegative(),
    color: hexColor(),
    opacity: geometry().refine((v) => v >= 0 && v <= 1, '`shadow.opacity`: доля от 0 до 1'),
  })
  .strict();

/**
 * Обводка — толщина и цвет. **Для `bg: none` и `bg: translucent`.**
 *
 * Это шортсовый приём и единственный способ читать белый текст на светлом кадре без плашки.
 * `widthPx: 0` — обводки нет (её и не должно быть под непрозрачной плашкой: контур под
 * плашкой — лишние пиксели на каждой букве).
 */
const OutlineSchema = z
  .object({
    widthPx: z.int().nonnegative().max(OUTLINE_MAX),
    color: hexColor(),
  })
  .strict();

const ParamsSchema = z
  .object({
    /** Роль шрифта проекта; не задана — роль `caption`, как было до `CAPTION-01`. */
    font: z.string().regex(FONT_ROLE_NAME, 'роль шрифта: строчные, цифры и дефис').optional(),
    sizePx: z.int().min(SIZE_MIN).max(SIZE_MAX).optional(),
    weight: z.enum(WEIGHTS).optional(),
    textColor: hexColor().optional(),
    activeColor: hexColor().optional(),
    bg: z.enum(BACKGROUNDS).optional(),
    plateColor: hexColor().optional(),
    plateOpacity: geometry().refine((v) => v >= 0 && v <= 1, '`plateOpacity`: доля от 0 до 1').optional(),
    outline: OutlineSchema.optional(),
    shadow: ShadowSchema.optional(),
    position: z.enum(POSITIONS).optional(),
    marginPx: z.int().min(MARGIN_MIN).max(MARGIN_MAX).optional(),
    widthPct: geometry()
      .refine((v) => v >= WIDTH_PCT_MIN && v <= WIDTH_PCT_MAX, '`widthPct`: доля кадра от 40 до 95 процентов')
      .optional(),
  })
  .strict()
  // ── ТРИ ПЕРЕКРЁСТНЫЕ ПРОВЕРКИ, И ВСЕ ТРИ — ПРО ОДНО: ПОЛЕ БЕЗ АДРЕСАТА ─────────────────
  // Написанное и не действующее хуже ненаписанного: автор поправит `plateColor`, посмотрит
  // кадр и не увидит разницы, а причина («у вас `bg: none`») не напечатана нигде.
  .refine((v) => !(v.bg === 'none' && v.plateColor !== undefined), {
    error:
      '`plateColor` задан при `bg: "none"`. Плашки нет вовсе — красить нечего. Либо уберите ' +
      'цвет, либо возьмите `bg: "plate"` (непрозрачная) или `bg: "translucent"` (с альфой)',
    path: ['plateColor'],
  })
  .refine((v) => !(v.plateOpacity !== undefined && v.bg !== 'translucent'), {
    error:
      '`plateOpacity` осмысленна ТОЛЬКО при `bg: "translucent"`. При `bg: "plate"` плашка ' +
      'непрозрачна по определению (условие применимости **R13**: прибор мерит смену строки, ' +
      'а не движущееся под ней фото), при `bg: "none"` плашки нет',
    path: ['plateOpacity'],
  })
  .refine((v) => !(v.marginPx !== undefined && v.position === 'center'), {
    error:
      '`marginPx` задан при `position: "center"`. Отступ отсчитывается ОТ КРАЯ кадра, а у ' +
      'центра края нет — число не подействовало бы ни на один пиксель. Уберите его либо ' +
      'возьмите `position: "bottom"` или `"top"`',
    path: ['marginPx'],
  });

/** Разобранные `params` шаблона `captionEmphasis@1`. */
export type CaptionEmphasisParams = z.infer<typeof ParamsSchema>;


// `video@1` — ВИДЕО В РОЛИКЕ. Первый шаблон движка, чья картинка приходит не из браузера.
//
// **ЧТО ОН ТАКОЕ ДЛЯ КОМПИЛЯТОРА И ДЛЯ БРАУЗЕРА — ДВЕ РАЗНЫЕ ВЕЩИ, И ЭТО НЕ ХИТРОСТЬ.**
// Для компилятора это обычный шаблон: `params`, ассет роли `video`, окно `[at, until)`, клип
// в IR. Для браузера он не рисует НИЧЕГО видимого: вся картинка видео приезжает снизу от
// ffmpeg отдельной стадией (`media/src/assemble/video-underlay.ts`), а браузерная реализация
// (`renderer-hyperframes/.../video@1/impl.ts`) занята единственным делом — ПРОБИВАЕТ ДЫРУ в
// слоях ниже по `z`, чтобы видео было видно сквозь них. Разбор варианта — `SP-VID`, решение
// «(а)»; разбор дыры — шапка реализации.
//
// **ЗВУК ВИДЕО В ЭТОЙ ВЕРСИИ ВСЕГДА ВЫКЛЮЧЕН, И СПЕК ГОВОРИТ ЭТО ВСЛУХ.** `audio` — ручка с
// ОДНИМ допустимым значением `off`. Не «поля нет» и не «звук молча теряется»: автор, который
// принёс видео со звуком, обязан прочитать в `vpe spec export`, что звук не поедет, — и
// узнать это до сборки, а не после просмотра. Значения `full` и `duck` придут в `VID-02b`
// через наш PCM-микшер по окнам речи; там же снимается `unmixedClips` у `bed@1` (`X-02`).
// Заводить их здесь заранее значило бы обещать поведение, которого нет.
//
// **ВИД АССЕТА — `video`, И ЭТО КОНТРАКТ, А НЕ ПОЖЕЛАНИЕ.** `declareAssets` возвращает
// `kind: 'video'`, и картинка под этой ролью — отказ компиляции с адресом записи
// (`compile/src/timeline/contract.ts`, проверка вида: `ASSET-01` §2.3). Без неё картинка
// доехала бы до стадии ffmpeg и упала там — в подпроцессе, в трёх стадиях от записи, которую
// надо чинить.
//
// **ЧЕГО В ЭТОЙ ВЕРСИИ НЕТ И ПОЧЕМУ — НАЗВАНО ЗДЕСЬ, А НЕ ОСТАВЛЕНО НА ДОГАДКУ:**
//   * `move` (переезд прямоугольника между `full` и `corner` внутри окна) — дыра в слоях
//     ниже ставится СТАТИЧЕСКИМ правилом CSS (`clip-path`), и едущий прямоугольник требует
//     пересчёта дыры НА КАЖДОМ КАДРЕ, то есть колбэка в композиции, детерминизм которого не
//     измерен. Долг;
//   * `radius` (скругление окна) — скругление обязано совпасть по обе стороны границы: и в
//     дыре (`clip-path` с дугами), и в маске видео у ffmpeg. Две независимые реализации
//     одной кривой — ровно тот класс расхождения, который проект запрещает себе с ADR-0002.
//     Долг;
//   * `loop` и `speed` — «показать ещё раз» и «показать медленнее» суть другие намерения,
//     чем «показать»; молча выбирать между ними шаблон не вправе. Долги.

import { z } from 'zod';

import type { TemplateManifest } from '../../manifest.js';
import { aliasRef, geometry } from '../../params.js';
import type { AssetRef } from '../../refs.js';
import type { TemplateSpec } from '../../spec.js';

/** Раскладка кадра видео внутри его прямоугольника. */
const FITS = ['cover', 'contain'] as const;
/** Углы для `frame: corner`. Порядок — читаемый: верх-лево, верх-право, низ-лево, низ-право. */
const CORNERS = ['tl', 'tr', 'bl', 'br'] as const;
/** Режимы прямоугольника. */
const FRAMES = ['full', 'corner'] as const;

/** Границы `size` — доля ШИРИНЫ кадра, которую занимает окно в углу. */
export const SIZE_MIN = 0.25;
export const SIZE_MAX = 0.6;
/** Потолок наезда. Выше трёх на исходнике 1080p начинается видимая каша пикселей. */
export const ZOOM_MAX = 3;

const HoldSchema = z
  .object({
    /** Секунда ВИДЕО, на которой кадр замирает. Секунды, а не кадры: автор смотрит плеером. */
    atVideoSec: geometry().refine((v) => v >= 0, { error: '`atVideoSec` не может быть отрицательным' }),
    /** Сколько кадров СЕГМЕНТА держится замерший кадр. */
    durationFrames: z.int().positive(),
  })
  .strict();

const ZoomSchema = z
  .object({
    startFrame: z.int().nonnegative(),
    durationFrames: z.int().positive(),
    from: geometry(),
    to: geometry(),
    /** Центр наезда в долях прямоугольника видео. */
    center: z.object({ x: geometry(), y: geometry() }).strict(),
  })
  .strict()
  .refine((z0) => z0.from >= 1 && z0.from <= ZOOM_MAX, {
    error: `\`zoom.from\` вне [1, ${String(ZOOM_MAX)}]: меньше единицы — это отъезд за край кадра, а не наезд`,
  })
  .refine((z0) => z0.to >= 1 && z0.to <= ZOOM_MAX, {
    error: `\`zoom.to\` вне [1, ${String(ZOOM_MAX)}]`,
  })
  .refine((z0) => z0.center.x >= 0 && z0.center.x <= 1 && z0.center.y >= 0 && z0.center.y <= 1, {
    error: '`zoom.center` — доли прямоугольника видео, обе координаты в [0, 1]',
  });

const ParamsSchema = z
  .object({
    /** Alias каталога. Роль ассета = имя ЭТОГО поля (ADR-0002 §4), вид — `video`. */
    asset: aliasRef(),
    /** Кадр видео, с которого начинается окно. Кадр, а не секунда: сик по времени недетерминирован. */
    inPointFrame: z.int().nonnegative().optional(),
    fit: z.enum(FITS).optional(),
    frame: z.enum(FRAMES).optional(),
    corner: z.enum(CORNERS).optional(),
    /** Доля ширины кадра под окно в углу. */
    size: geometry().optional(),
    /** Отступ окна от края в долях ширины кадра. */
    margin: geometry().optional(),
    /** Цвет полей при `contain` — `#rrggbb` строчными. */
    bg: z
      .string()
      .regex(/^#[0-9a-f]{6}$/u, { error: '`bg` — цвет вида `#rrggbb` строчными буквами' })
      .optional(),
    holds: z.array(HoldSchema).optional(),
    zooms: z.array(ZoomSchema).optional(),
    /**
     * Звук видео. **Ровно одно значение в этой версии** — см. шапку файла.
     *
     * Поле НЕОБЯЗАТЕЛЬНО и при этом объявлено: так «звука не будет» читается в схеме и в
     * `vpe spec export`, а не выясняется на готовом ролике.
     */
    audio: z.literal('off').optional(),
  })
  .strict()
  .refine((p) => p.corner === undefined || p.frame === 'corner', {
    error:
      '`corner` задан, а `frame` не равен `corner`: угол окна имеет смысл только у окна в углу. ' +
      'Либо поставьте `frame: "corner"`, либо уберите `corner` — молча выбрать за автора одно ' +
      'из двух значило бы решить, полноэкранное видео он хотел или врезку',
  })
  .refine((p) => p.size === undefined || (p.size >= SIZE_MIN && p.size <= SIZE_MAX), {
    error:
      `\`size\` вне [${String(SIZE_MIN)}, ${String(SIZE_MAX)}]: меньше четверти ширины врезка ` +
      'нечитаема на телефоне, больше трёх пятых — это уже не врезка, а полноэкранное видео с полями',
  })
  .refine((p) => p.size === undefined || p.frame === 'corner', {
    error: '`size` задан, а `frame` не равен `corner`: у полноэкранного окна размер не выбирают',
  })
  .refine((p) => p.margin === undefined || (p.margin >= 0 && p.margin <= 0.25), {
    error: '`margin` вне [0, 0.25] доли ширины кадра',
  });

/** Разобранные `params` шаблона `video@1`. */
export type VideoParams = z.infer<typeof ParamsSchema>;

const manifest: TemplateManifest = {
  templateId: 'video',
  templateVersion: 1,
  declaredAssets: ['video'],
  declaredFonts: [],
  gates: [],
  // **БЮДЖЕТ БРАУЗЕРА, А НЕ БЮДЖЕТ ШАБЛОНА, И РАЗНИЦА НАЗВАНА.** Сумма по кадру (ADR-0008
  // «Бюджет AC2») меряет ЦЕНУ КОМПОЗИЦИИ — то, что платит Chrome. Браузерная часть этого
  // шаблона рисует пустой слой и ставит одно статическое правило CSS на монтировании, то есть
  // на кадр не работает вовсе — как `still@1`, чья измеренная цена (0.936 мс/кадр) оказалась
  // НИЖЕ шума прибора. Значение **1** взято по тому же правилу д1 (решение владельца `H-06`):
  // у визуального шаблона ноль означал бы «шаблона нет», а не «шаблон дёшев».
  //
  // **ЦЕНА САМОГО ВИДЕО ЖИВЁТ НЕ ЗДЕСЬ, И ЭТО НЕ ДЫРА В УЧЁТЕ.** Стадия нижнего слоя — не
  // Chrome: она платится ffmpeg'ом, после рендера, и в сумму по кадру композиции не входит по
  // определению величины. Её измерение — мс на секунду ролика (`SP-VID` A5: +52.8 за
  // наложение), и живёт оно в отчёте сборки, а не в манифесте.
  msPerFrameBudget: 1,
  // Кривых нет, и это не забывчивость: наезд считает ffmpeg линейно по номеру кадра, а реестр
  // **D5** принадлежит браузеру. Вторая реализация `power2.inOut` на стороне фильтров была бы
  // вторым источником одной кривой — ровно то, что запрещает D5.
  easingIds: [],
  needsAudioFeatures: false,
  purposes: [],
};


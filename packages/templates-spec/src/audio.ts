// Четвёртая декларация шаблона: ЗВУК, который он кладёт в дорожку ролика (`X-02`).
//
// ЗАЧЕМ ОНА ВООБЩЕ НУЖНА. Микс обязан знать три числа вызова — с какой точки ассета играть,
// насколько тише голоса и насколько уходить под речь. Все три лежат в `params` (`bed@1`:
// `inPoint`, `gainDb`, `duckUnderSpeechDb`), а компилятору читать `params` ПО ИМЕНИ ПОЛЯ
// запрещено — правило `CP-07` «компилятор не интерпретирует шаблон», и оно охраняется грепом
// (`tests/lints/cp07-template-params.test.ts`), а не дисциплиной. Значит путь ровно один:
// шаблон читает свои параметры сам и объявляет РЕЗУЛЬТАТ. Ровно так же решён долг №119
// (`declareDuration`), и эта декларация — его сестра, а не новый приём.
//
// АССЕТ НАЗЫВАЕТСЯ РОЛЬЮ, А НЕ ALIAS'ОМ И НЕ SHA. Alias уже объявлен `declareAssets`, и
// компилятор его уже разрешил; называть его здесь второй раз значило бы завести второй путь
// разрешения — и первое же расхождение между ними было бы молчаливым (сыграл бы не тот файл).
// Роль — это ключ, по которому микс находит уже разрешённую ссылку в `contract.assets`.
//
// ДЕЦИБЕЛЫ УЕЗЖАЮТ ЧИСЛАМИ, А НЕ ДРОБЬЮ. Перевод «дБ → целое усиление» — свойство ТРАКТА
// (`media/audio/gain.ts`, `gainFromDb`), а не шаблона: у него одно правило округления на весь
// репозиторий и один охранник устойчивости. Шаблон, посчитавший дробь сам, завёл бы второе.
//
// ЧЕГО ЗДЕСЬ НЕТ: громкости в абсолютных единицах, нормализации, огибающих и «автоматики».
// Компилятор не выдумывает звук: он складывает ровно то, что объявлено вызовом.

/**
 * Точка внутри источника, с которой звучит клип, — В ЕДИНИЦАХ, КОТОРЫЕ ШАБЛОН ЗНАЕТ.
 *
 * **ПОЧЕМУ СОЮЗ, А НЕ ОДНО ЧИСЛО В СЭМПЛАХ** *(добавлено: `VID-02b`, 2026-09-12)*. У `bed@1`
 * in-point записан `MediaTime` — сэмплами проекта, и шаблон их знает. У `video@1` он записан
 * НОМЕРОМ КАДРА ВИДЕО (`inPointFrame`), а перевести кадр в сэмпл может только тот, кто видит
 * частоту кадров ФАЙЛА, — то есть каталог, а не шаблон. Общее число в сэмплах потребовало бы
 * от `video@1` знания, которого у него нет по построению (декларации — функции ТОЛЬКО
 * `params`), и он вернул бы либо ноль вместо смещения, либо выдуманную частоту.
 *
 * Переводит союз в сэмплы ОДНО место — стадия контракта компилятора, там же, где разрешаются
 * alias'ы: у неё есть и запись ассета, и частота проекта.
 */
export type AudioInPoint =
  /** Сэмплы ПРОЕКТА — как есть (`bed@1`, `MediaTime`). */
  | { readonly unit: 'samples'; readonly value: number }
  /** Кадры ИСТОЧНИКА (`video@1`, `inPointFrame`): переводит компилятор по частоте файла. */
  | { readonly unit: 'sourceFrames'; readonly value: number };

/**
 * Пауза, на которой звук клипа ЗАМОЛКАЕТ, — след паузы КАДРА (`holds` у `video@1`).
 *
 * **ПОЧЕМУ ТИШИНА, А НЕ ПЕТЛЯ И НЕ РАСТЯЖЕНИЕ.** Кадр замер — значит время источника
 * остановилось; звук, который продолжал бы играть, разъехался бы с картинкой на всю длину
 * паузы и дальше уже не сошёлся. Растянуть звук — значит изменить его высоту, то есть
 * выдумать звук, которого в файле нет. Тишина — единственное, что не утверждает ничего
 * лишнего, и ровно её выбрал владелец (`IMPL-NIGHT-03` §2.2).
 *
 * ЕДИНИЦЫ РАЗНЫЕ У ДВУХ ПОЛЕЙ, И ЭТО НЕ НЕДОСМОТР: `atSourceMs` — момент ВНУТРИ файла
 * (миллисекунды, потому что автор пишет секунды плеером), `frames` — длительность паузы в
 * кадрах СЕГМЕНТА (потому что пауза измеряется в кадрах ролика, а не файла). Обе переводит
 * компилятор: первую — `msToSamples`, вторую — по кадровой сетке проекта.
 */
export interface AudioPause {
  readonly atSourceMs: number;
  readonly frames: number;
}

/**
 * Звук одного вызова шаблона — то, что микс обязан о нём знать.
 *
 * ВСЕ ПОЛЯ ОБЯЗАТЕЛЬНЫ, И ЭТО НАМЕРЕННО: «шаблон не высказался о звуке» выражается
 * отсутствием метода `declareAudio` либо ответом `null`, а не пропущенным полем. Иначе
 * умолчание пришлось бы держать в двух местах — у шаблона и у микса.
 */
export interface AudioContribution {
  /** Роль ассета из `declareAssets` — по ней микс находит уже разрешённый sha. */
  readonly role: string;
  /** Смещение внутри ассета, с которого звучит клип, — в единицах шаблона (`AudioInPoint`). */
  readonly inPoint: AudioInPoint;
  /** Уровень клипа. `0` — «как есть»; положительные значения тракт отвергает (`gainFromDb`). */
  readonly gainDb: number;
  /**
   * Насколько клип уходит ПОД РЕЧЬ. `0` — не уходит вовсе (`audio: 'full'` у `video@1`).
   *
   * Величина отрицательная и СКЛАДЫВАЕТСЯ с `gainDb` (децибелы — логарифм, сложение здесь
   * есть умножение отношений): уровень под речью равен `gainDb + duckUnderSpeechDb`.
   */
  readonly duckUnderSpeechDb: number;
  /**
   * Зацикливать ли ассет, когда окно клипа длиннее него.
   *
   * `true` у подложки (`bed@1`): она играет до конца окна. `false` у звука видео: он
   * кончается вместе с видео, и дальше — тишина, а не вторая копия.
   */
  readonly loop: boolean;
  /**
   * Паузы источника: на них звук клипа замолкает (`holds` у `video@1`).
   *
   * Пустой список — законное и обычное значение (`bed@1`: подложка не замирает никогда).
   * ОБЯЗАТЕЛЬНОЕ поле, а не `?`: «пауз нет» обязано быть сказано, а не пропущено, — иначе
   * шаблон, забывший их объявить, молча получил бы звук, разъехавшийся с картинкой.
   */
  readonly pauses: readonly AudioPause[];
}

// Манифест шаблона — **ДАННЫЕ ПАКЕТА**, а не семейство схемы (решение владельца `TS-01`,
// вопрос 1, вариант «а»).
//
// ПОЧЕМУ НЕ СЕМЕЙСТВО `template-manifest/1`. Реестр `@vpe/schema` — двенадцать семейств
// (решение `V-03`), и заводить тринадцатое означало бы открыть пакет, который эта задача
// трогать не должна. Манифест живёт TS-литералом рядом со спеком и валидируется zod-схемой
// НИЖЕ. **Цена названа заранее и принята:** манифест не попадает под `vpe fmt --check` и под
// миграции V7, а команда `vpe template gate` (`E-00`) будет править TS-файл, а не YAML.
// Долг «форма хранения манифеста — при `E-00`» заведён.
//
// ПОЛЯ — ИЗ ТАБЛИЦЫ roadmap §4.8, ПЛЮС ДВА, И ОБА НАЗВАНЫ:
//   * `purposes[]` — ADR-0007 §1 определяет `purpose` как «строковую константу шаблона»
//     (`'kenburns.jitter'`), то есть перечень принадлежит именно манифесту. Таблица §4.8 его
//     не называет только потому, что писалась до `CP-04`, который взял временную форму
//     `purpose = templateId` (долг №135). Кандидат в правку roadmap §4.8 — в отчёте;
//   * `forkedFrom?` — ADR-0008 («Оспариваю V3»): `local:kenburns@1` + `forkedFrom: {id,
//     version, hash}`. Без него namespace `local:` был бы допустим и пуст.
//
// ПОЛЕ, КОТОРОГО ЗДЕСЬ НЕТ, ХОТЯ ТАБЛИЦА ЕГО НАЗЫВАЕТ: `determinismClass` (решение владельца
// `TS-01`, вопрос 3). Класс — свойство ПАРЫ (профиль, отпечаток), и он уже лежит в каждой
// записи гейта. Второе его хранение на уровне манифеста было бы величиной, которую никто не
// может держать в согласии с записями: снял гейт заново — обязан не забыть переписать и
// сводное поле. Поэтому уровень манифеста — ПРОИЗВОДНОЕ (`determinismClassOf`), и он не
// хранится. Кандидат в правку roadmap §4.8 — в отчёте.
//
// ПОЛЕ, КОТОРОГО ЗДЕСЬ НЕТ ПО РЕШЕНИЮ 9 (RM1): бюджета СЦЕНЫ. Сумма `msPerFrameBudget` по
// пересекающимся клипам считается компилятором и печатается в отчёте сборки; в манифест
// шаблона она не едет (ADR-0008 «Бюджет AC2»).

import { z } from 'zod';

import { EASING_REGISTRY, easingRejection, type EasingId } from './easing.js';
import { parseTemplateName } from './name.js';

/**
 * Форма hex-дайджеста — **вторая копия в репозитории, и цена названа**.
 *
 * Первая живёт в `@vpe/schema/types/brands.ts` (`asSha256`/`asBlake3`: 64 строчных hex).
 * Скопирована она потому, что `@vpe/schema` из этого пакета НЕ РЕЗОЛВИТСЯ вовсе — карта
 * ADR-0009 даёт `templates-spec` ровно одну стрелку (`core-model`), а `core-model`
 * реэкспортирует `asSamples`/`asFrames`/`asAnchorId`/`Blake3`, но не конструкторы дайджестов.
 * Альтернативы обе хуже: адресный реэкспорт означает правку `core-model` (закрытая зона этой
 * задачи), а `z.string().min(1)` принял бы запись гейта со строкой `"todo"` на месте хэша —
 * ровно то, что **R12** запрещает («запись обязана содержать оба хэша, иначе она неотличима
 * от „прогнали когда-то на другой машине“»). Долг заведён с адресом.
 */
export const hexDigest = (what: string): z.ZodString =>
  z
    .string()
    .length(64, `${what}: ожидалось 64 hex-символа (32-байтовый дайджест)`)
    .regex(/^[0-9a-f]+$/, `${what}: ожидался строчный hex \`[0-9a-f]\` — один дайджест имеет одну форму записи`);

/**
 * Профили, на которых снимается гейт, — **ровно два** (решение владельца 12, RM1;
 * ADR-0008 «Гейт → Процедура» п. 2; **R12**).
 *
 * `render.ac4.yaml` формально тоже пара, но записи гейта НЕ получает: он остаётся полным
 * прогоном фикстурного проекта (Charter AC4 rev5), то есть проверкой всей цепочки, а не
 * проверкой шаблона.
 */
export const GATE_PROFILES = ['final', 'draftHalf'] as const;

/** `final` либо `draftHalf`. Третьего профиля гейта нет. */
export type GateProfileId = (typeof GATE_PROFILES)[number];

/**
 * N прогонов на профиль — **не настройка, а часть правила** (Charter V13, ADR-0008 п. 2).
 *
 * Основание N = 10: `FACT` (SP-3e §4) там, где расхождение вообще было, оно проявлялось на
 * 1–3-м прогоне; десяти хватило во всех клетках. `UNKNOWN`, записанный там же: нижняя граница
 * N не искалась. Запись с другим N отвергается схемой: она означала бы гейт, которого никто
 * не проводил.
 */
export const GATE_RUNS: Readonly<Record<GateProfileId, number>> = { final: 10, draftHalf: 3 };

/**
 * Классы результата гейта — ADR-0008, «Классы результата», ДОСЛОВНО.
 *
 * `FLAKY-по-контейнеру` — `sha256` расходится, `framemd5` нет: расхождение в метаданных
 * контейнера, а не в картинке. ADR называет это «не провалом ПОСЛЕ того, как нормализация
 * применена и гейт переснят», то есть запись этого класса означает работу НЕЗАКОНЧЕННУЮ —
 * и `assertBuildMayStart` её не принимает (см. `gate.ts`).
 */
export const GATE_CLASSES = ['PASS', 'FAIL', 'FLAKY-по-контейнеру'] as const;

/** Класс результата одного гейта. */
export type GateClass = (typeof GATE_CLASSES)[number];

/**
 * Сводный класс детерминизма шаблона — **производное, не поле** (решение владельца 3).
 * `UNGATED` — записей гейта нет ни одной: это не «чисто», а «проверки не выполнялись».
 */
export type DeterminismClass = GateClass | 'UNGATED';

/**
 * Запись гейта: **весь состав обязателен** (**R12**) — «иначе она не отличима от „прогнали
 * когда-то на другой машине“».
 */
export const GateRecordSchema = z
  .object({
    profileId: z.enum(GATE_PROFILES),
    /** Сверяется с `GATE_RUNS` ниже: 10 на `final`, 3 на `draftHalf`. */
    N: z.int().positive(),
    /** `sha256` готового файла: контейнер + битстрим (ADR-0008 п. 3). */
    sha256: hexDigest('sha256'),
    /**
     * `framemd5` — md5 каждого декодированного кадра, свёрнутый в один дайджест.
     *
     * Имя поля — из таблицы roadmap §4.8; величина — та же, что `SegmentArtifact.framemd5Sha256`
     * (ADR-0008 «Контракт»). Различать её с `sha256` обязательно: «файл может разойтись при
     * совпадающей картинке и наоборот».
     */
    framemd5: hexDigest('framemd5'),
    /** Когда гейт снят. `now` — вход команды (`E-00`), а не `Date.now()` внутри (Charter V8). */
    date: z.iso.datetime(),
    /**
     * Отпечаток окружения — **строка целиком** (решение владельца `TS-01`, вопрос 6).
     *
     * ADR-0006 §3 определяет `engineFingerprint` как `blake3(…)` от пяти завендоренных
     * компонентов, строки запуска Chrome, платформы и командной строки энкодера, — то есть
     * это дайджест, и сравнивается он строгим равенством. Структура из пяти версий (**R14**)
     * — форма ВЫЧИСЛЕНИЯ отпечатка, и она появится там, где отпечаток впервые считается
     * (`H-01`/`H-03`), а не в записи, которая его цитирует.
     */
    engineFingerprint: hexDigest('engineFingerprint'),
    class: z.enum(GATE_CLASSES),
  })
  .strict()
  .superRefine((gate, ctx) => {
    const expected = GATE_RUNS[gate.profileId];
    if (gate.N !== expected) {
      ctx.addIssue({
        code: 'custom',
        path: ['N'],
        message:
          `N = ${String(expected)} на профиле \`${gate.profileId}\` — часть правила, а не ` +
          `настройка (Charter V13, ADR-0008 «Гейт → Процедура» п. 2). Получено ${String(gate.N)}: ` +
          'такая запись означала бы гейт, которого никто не проводил',
      });
    }
  });

/** Одна запись гейта (**R12**). */
export type GateRecord = z.infer<typeof GateRecordSchema>;

/** Непустое имя без повторов — роли и purposes. Кривые — `easingIds` ниже: форма ПЛЮС членство. */
const names = (what: string): z.ZodType<string[]> =>
  z
    .array(z.string().min(1, `${what}: пустое имя`))
    .superRefine((list, ctx) => {
      const seen = new Set<string>();
      for (const [index, name] of list.entries()) {
        if (seen.has(name)) {
          ctx.addIssue({ code: 'custom', path: [index], message: `${what}: \`${name}\` повторяется` });
        }
        seen.add(name);
      }
    });

/**
 * Кривые шаблона: **форма `names()` ПЛЮС членство в закрытом реестре** (`TS-02`, решение
 * владельца, развилка 1 вариант «А»; поправка П1).
 *
 * ДВЕ ПРОВЕРКИ, А НЕ ОДНА, И ПОРЯДОК ЗНАЧИМ. `names('easingIds')` остаётся первым: он ловит
 * повторы (`z.enum` их не видит — шесть раз `none` для него шесть законных значений) и пустое
 * имя. Только потом `pipe` сверяет каждое имя с реестром. Отказ формы отменяет проверку
 * членства, и это правильный порядок: сказать «`power2.inOut` повторяется» полезнее, чем
 * дважды рассказать про реестр.
 *
 * ПОЧЕМУ ЧЛЕНСТВО ЖИВЁТ ЗДЕСЬ, А НЕ В `registry.ts`. Отказ выдаётся в МЕСТЕ ОБЪЯВЛЕНИЯ, до
 * построения реестра, и достаётся реестру даром: `register` уже зовёт
 * `TemplateManifestSchema.safeParse`, то есть второй копии правила не появляется. Сверх того
 * `z.enum` даёт ТИП: `easingIds` манифеста имеет тип `EasingId[]`, и кривая вне реестра —
 * **ошибка `tsc`**, а не только рантайма. Это дословный критерий готовности roadmap §4.8
 * `TS-02` («кривая вне реестра — ошибка компиляции»), и проверка при регистрации дать его не
 * может: она видит значения, а не типы.
 *
 * СПИСОК И ТЕКСТ ОТКАЗА — ИЗ РЕЕСТРА, НЕ ОТСЮДА. Вторая копия шести имён здесь означала бы
 * ровно ту беду, ради которой `TS-01` строила схему `params` и манифест из одной константы.
 */
const easingIds = (what: string): z.ZodType<EasingId[]> =>
  names(what).pipe(
    z.array(
      z.enum(EASING_REGISTRY, { error: (issue) => easingRejection(what, String(issue.input)) }),
    ),
  );

/**
 * Источник форка — ADR-0008: «копия шаблона в локальном реестре проекта, вызов
 * `local:kenburns@1`, `forkedFrom: {id, version, hash}`».
 *
 * `hash` — дайджест реализации шаблона-источника. Какой именно функцией он считается,
 * ADR-0008 не называет; форма (64 строчных hex) общая у `sha256` и `blake3`, и выбор функции
 * принадлежит команде `vpe template fork`, которой в v1 нет. Записано долгом.
 */
export const ForkSourceSchema = z
  .object({
    templateId: z.string().min(1),
    templateVersion: z.int().positive(),
    hash: hexDigest('forkedFrom.hash'),
  })
  .strict();

/** Откуда форкнут локальный шаблон (Charter V3, ADR-0008). */
export type ForkSource = z.infer<typeof ForkSourceSchema>;

/** Манифест шаблона — данные пакета, валидируемые этой схемой. */
export const TemplateManifestSchema = z
  .object({
    /** Имя БЕЗ префикса и версии; вместе с `templateVersion` обязано разбираться грамматикой. */
    templateId: z.string().min(1),
    templateVersion: z.int().positive(),
    /**
     * Роли ассетов, которые шаблон ВООБЩЕ может объявить — статический список.
     *
     * Сверяется с результатом `declareAssets` на фикстурных `params` тестом: манифест обязан
     * быть надмножеством (`declaredAssets ⊇ роли из declare*`). Надмножеством, а не
     * равенством: `still@1` объявляет ассет всегда, а шаблон с необязательным ассетом объявит
     * роль в манифесте и не вернёт её на `params` без ассета.
     */
    declaredAssets: names('declaredAssets'),
    declaredFonts: names('declaredFonts'),
    /**
     * Записи гейта: **0..2, по одной на профиль** (решение владельца 12, RM1).
     *
     * Ноль — честное состояние шаблона, который ещё не прогоняли: рендерера нет, прогонов не
     * было. Именно на нуле **R12** обязана не пустить сборку, а не на «поле забыли».
     */
    gates: z.array(GateRecordSchema).max(GATE_PROFILES.length),
    /**
     * Бюджет мс/кадр (ADR-0008 «Бюджет AC2»). **Обязателен: без него шаблон не
     * регистрируется** — критерий готовности `E-00`.
     *
     * `nonnegative`, а не `positive` — поправка владельца П1 (`TS-01`). Ноль законен у
     * шаблона АУДИО-домена (`bed@1`): он не рисует кадров вовсе, и «> 0» у него было бы
     * фикцией — числом, которого никто не мерил и не мог измерить. Правило «> 0 у
     * визуального шаблона» остаётся ожиданием и проверяется ТАМ, ГДЕ ИЗВЕСТЕН ТРЕК
     * (`CP-06`/`E-00`), а не реестром, который трека не видит. Долг заведён.
     *
     * `int` — тоже поправка владельца П1. Оговорка, входящая в число: измеренные величины
     * SP-3f §2 ДРОБНЫЕ (шейдер 13.5 мс/кадр, частицы ≈ 37, стекло +0.9), то есть при `E-00`
     * их придётся округлять. Записано долгом, а не исполнено молча.
     */
    msPerFrameBudget: z.int().nonnegative(),
    /**
     * Идентификаторы кривых, которые шаблон может использовать (ADR-0007 §3, реестр **D5**).
     *
     * ~~Здесь проверяется только ФОРМА — непустые имена без повторов. Членство в реестре
     * easing — `TS-02`.~~ *(изменено: `TS-02`, 2026-08-28.)* Проверяется И ФОРМА, И ЧЛЕНСТВО:
     * реестр появился ([`easing.ts`](./easing.ts)), и список кривых берётся ИЗ НЕГО, а не
     * повторяется здесь. Кривая вне шести — отказ схемы (с именем кривой и полным реестром в
     * тексте) и ошибка `tsc` у поля типа `EasingId[]`: спек с чужой кривой не построится.
     */
    easingIds: easingIds('easingIds'),
    /** `core.md §18.1 п. 6` — поле есть, механики нет. */
    needsAudioFeatures: z.boolean(),
    /**
     * Перечень `purpose` шаблона (ADR-0007 §1: «строковая константа шаблона»,
     * `'kenburns.jitter'`).
     *
     * Пустой список — шаблон случайности не требует, и это НЕ заглушка: ни один из пяти
     * шаблонов фикстуры её не требует (измерено `TS-01`, §таблица отчёта). Долг №135
     * (`purpose = templateId`) сужается этим измерением.
     */
    purposes: names('purposes'),
    /** Только у `local:` — ADR-0008. Наличие поля И ЕСТЬ признак локальности (см. `registry.ts`). */
    forkedFrom: ForkSourceSchema.optional(),
  })
  .strict()
  .superRefine((manifest, ctx) => {
    // Имя обязано разбираться ЕДИНСТВЕННОЙ грамматикой репозитория, а не второй регуляркой.
    try {
      parseTemplateName(`${manifest.templateId}@${String(manifest.templateVersion)}`);
    } catch (error) {
      ctx.addIssue({
        code: 'custom',
        path: ['templateId'],
        message: error instanceof Error ? error.message : String(error),
      });
    }
    const byProfile = new Set<string>();
    for (const [index, gate] of manifest.gates.entries()) {
      if (byProfile.has(gate.profileId)) {
        ctx.addIssue({
          code: 'custom',
          path: ['gates', index, 'profileId'],
          message:
            `две записи гейта на профиль \`${gate.profileId}\`. Записей ровно две — по одной ` +
            'на `final` и `draftHalf` (решение владельца 12, RM1): вторая запись на тот же ' +
            'профиль означала бы два разных ответа на один вопрос, и сборка выбирала бы из ' +
            'них молча. Гейт переснят — прежняя запись ЗАМЕЩАЕТСЯ',
        });
      }
      byProfile.add(gate.profileId);
    }
  });

/** Манифест шаблона (roadmap §4.8, ADR-0008). */
export type TemplateManifest = z.infer<typeof TemplateManifestSchema>;

/** Порядок «от худшего»: сводный класс — худший из записей (решение владельца 3). */
const SEVERITY: readonly GateClass[] = ['FAIL', 'FLAKY-по-контейнеру', 'PASS'];

/**
 * Сводный класс детерминизма шаблона — **производное от `gates`, а не поле манифеста**
 * (решение владельца `TS-01`, вопрос 3).
 *
 * Без записей — `UNGATED`: «проверки не выполнялись», а не «чисто». Различать обязательно —
 * это то же правило, по которому Policy Guard на пустом журнале печатает «проверки не
 * выполнялись» (roadmap `CP-06`).
 */
export function determinismClassOf(manifest: TemplateManifest): DeterminismClass {
  if (manifest.gates.length === 0) return 'UNGATED';
  for (const cls of SEVERITY) {
    if (manifest.gates.some((gate) => gate.class === cls)) return cls;
  }
  // Недостижимо: `class` — закрытая сумма, а `gates` непуст. Ветка существует, чтобы
  // расширение `GATE_CLASSES` без правки `SEVERITY` падало, а не возвращало «PASS» молча.
  throw new Error(`determinismClassOf: класс вне \`SEVERITY\` — расширьте порядок «от худшего»`);
}

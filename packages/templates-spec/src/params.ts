// Общие формы полей `params` — и **закрытие долга №35 схемой, а не сканом**.
//
// ЧТО ЗАКРЫВАЕТСЯ. `C-05` ищет `gridPoint` СКАНОМ значений `params` на объекты с полем `kind`
// (`assertNoGridPoint`, `core-model/model/direction.ts`) и сам называет это временной мерой:
// «контракт `params` — обязанность манифеста шаблона (`TS-01`); когда манифест появится,
// этот скан заменяется контрактом параметров». Контракт — здесь: **каждый шаблон называет
// свои поля-точки ЯВНО**, и `gridPoint` в них невыразим, потому что его нет в сумме.
//
// ЧТО НЕ ЗАКРЫВАЕТСЯ И ПОЧЕМУ. Скан в `direction.ts` остаётся на месте до тех пор, пока
// компилятор не начнёт звать схемы шаблонов (`CP-06`). Причина не в осторожности: сегодня
// `readDirection` — единственное место, где `params` вообще проверяются, и снять скан значило
// бы оставить `gridPoint` непроверенным до появления вызывающего. Долг №35 сужается адресом,
// а не закрывается целиком.
//
// ОТКАЗ ЖИВЁТ В СУММЕ, А НЕ В ПРОВЕРКЕ. `TimePointParamSchema` перечисляет ровно два варианта
// ADR-0001 — `anchor` и `mediaTime`. Третий (`gridPoint`) не «отвергается условием»: его
// невозможно построить. Это то же решение, по которому `Clip.at` объявлен
// `RealizableTimePoint`, а не `TimePoint` (`core-model/model/entities.ts`).
//
// АССЕТ В `params` — ALIAS, А НЕ SHA (долг №120). `MediaTimePoint.asset` в `core-model`
// типизирован `Sha256`, а в фикстуре на этом месте стоит `"pad-loop"` — ключ
// `assets/aliases.yaml`. Форма ниже описывает то, ЧТО ЛЕЖИТ В ФАЙЛЕ, а не то, во что это
// превратится после `resolveAlias` (`M-02`). Расхождение зафиксировано решением владельца
// (`TS-01`, вопрос 4), а не устранено.

import { z } from 'zod';

/**
 * Alias каталога ассетов: непустая строка, и **ничего сверх**.
 *
 * Форму ключа не проверяет и `aliases/1` — единственное семейство без `.strict()`, потому что
 * «файл — открытая карта, где ключи придумывает автор» (`schema/src/families/aliases.ts`).
 * Завести здесь регулярку значило бы объявить форму ключа, которой владелец не решал, и
 * запретить фотографию с именем, законным в самом каталоге.
 */
export const aliasRef = (): z.ZodString => z.string().min(1, 'alias ассета: пустая строка');

/**
 * Геометрическая величина: конечный double, но **не `-0`**.
 *
 * Double разрешён для геометрии (ADR-0007 §3: «масштаб, поворот, прозрачность»); `NaN`,
 * `Infinity` и `-0` — нет, там же: «линт на `NaN`, `Infinity`, `-0`». `-0` отвергается не из
 * педантизма: `canonicalJson` его отвергает, и число, прошедшее схему, уронило бы канонизацию
 * на следующем шаге — ровно то рассуждение, которым `assertCountable`
 * (`schema/src/types/brands.ts`) обосновывает свой отказ.
 */
export const geometry = (): z.ZodType<number> =>
  z
    .number()
    .refine((v) => Number.isFinite(v), 'геометрия: ожидалось конечное число (ADR-0007 §3)')
    .refine((v) => !Object.is(v, -0), '`-0` не является геометрической величиной (ADR-0007 §3)');

/**
 * Величина в децибелах: конечный double, не `-0`. Знак не ограничен — ослабление или усиление
 * решает автор, а порог клиппинга проверяет аудио-тракт (`M-03`, `X-02`), а не схема шаблона.
 */
export const decibels = (): z.ZodType<number> => geometry();

/** Якорь как точка времени в `params` (ADR-0001, V1: позиции на речи — только якоря). */
export const AnchorPointParamSchema = z
  .object({
    kind: z.literal('anchor'),
    anchor: z.string().min(1),
    /** Сдвиг в сэмплах. Бренд `Samples` из `@vpe/schema` в этом пакете недостижим. */
    nudgeSamples: z.int().optional(),
  })
  .strict();

/**
 * In-point внутри ассета (ADR-0001; V1: «точки внутри ассета выражаются явным типом
 * `MediaTime`»). `asset` — **alias**, см. шапку файла.
 */
export const MediaTimePointParamSchema = z
  .object({
    kind: z.literal('mediaTime'),
    asset: aliasRef(),
    offsetSamples: z.int().nonnegative(),
  })
  .strict();

/**
 * Точка времени в `params` — **ровно два варианта** (ADR-0001). `gridPoint` невыразим:
 * «сетки ассетов в v1 не реализуются, и формат не имеет права обещать то, чего нет».
 */
export const TimePointParamSchema = z.discriminatedUnion(
  'kind',
  [AnchorPointParamSchema, MediaTimePointParamSchema],
  {
    error:
      'точка времени в `params`: допустимы только `kind: "anchor"` и `kind: "mediaTime"`. ' +
      '`gridPoint` в v1 не реализуется (ADR-0001) — сетка ассета была бы артефактом ' +
      '`assets/grids/<assetSha>.<gridId>.json`, которого нет ни в одном профиле',
  },
);

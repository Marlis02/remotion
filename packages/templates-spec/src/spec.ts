// Контракт ОДНОГО шаблона: схема `params`, две декларации ресурсов, манифест.
//
// ЧТО ЗДЕСЬ ЕСТЬ И ЧЕГО НЕТ. Есть контракт — то, что шаблон обязан предъявить, чтобы попасть
// в реестр. Нет ни строки рендера: `templates-spec` по карте ADR-0009 не знает ни рендерера,
// ни его библиотеки анимации (**M1**, **M6**), а «разворачивание шаблона» — чистая функция,
// исполняемая В АДАПТЕРЕ (ADR-0008, «Разрешение V3 × V9»), и живёт она в `H-01`/`E-*`.
//
// `declareAssets` / `declareFonts` — **ЧИСТЫЕ** (ADR-0008 «Декларация ресурсов шаблона»).
// Не «желательно чистые»: компилятор вызывает их ДО Policy Guard, «иначе PG-D1 (BLOCK)
// неисполним и ключ кэша неполон». Функция, читающая диск или сеть, сделала бы ключ кэша
// зависящим от того, что на диске лежало в момент компиляции. Охранник — два: тест «два
// вызова дают структурно равный результат» и греп по исходникам пакета на `node:fs`/сеть.
//
// ПОЧЕМУ ДЕКЛАРАЦИИ БЕРУТ `params`, А НЕ ВЫЗОВ ЦЕЛИКОМ. `TemplateCall` (Charter V3) — это
// `{templateId, templateVersion, params}`; id и версия шаблону известны про себя, и подавать
// их обратно значило бы разрешить шаблону вести себя по-разному в зависимости от того, как
// его назвали. Ровно та же причина, по которой линт `V-01` запрещает ветвление по имени
// провайдера (ADR-0010 §8).

import type { z } from 'zod';

import type { TemplateManifest } from './manifest.js';
import type { AssetRef, FontRef } from './refs.js';

/**
 * Контракт шаблона.
 *
 * `P` — тип разобранных `params`. **Декларации объявлены МЕТОДАМИ, а не полями-функциями,**
 * и это не стиль: под `strictFunctionTypes` параметры метода биваринтны, поэтому
 * `TemplateSpec<KenburnsParams>` кладётся в реестр, объявленный над `TemplateSpec<unknown>`,
 * без единого каста. Соответствие типа схеме при этом не теряется: `params` перед вызовом
 * ПРОГОНЯЮТСЯ через `paramsSchema` (`requestFiles` ниже, `resolve` реестра), а не приводятся.
 */
export interface TemplateSpec<P = unknown> {
  /** Имя БЕЗ префикса и версии. Обязано совпасть с манифестом (проверяет реестр). */
  readonly templateId: string;
  readonly templateVersion: number;
  /**
   * Схема `params` — zod, `.strict()` (образец — `CaptionsSchema` в
   * `schema/src/families/compile-profile.ts`). `.strict()` обязателен: лишнее поле в `params`
   * — это либо опечатка в имени, либо параметр, которого шаблон не читает, и в обоих случаях
   * молчание означало бы, что автор видит в файле не то, что получит на экране.
   */
  readonly paramsSchema: z.ZodType<P>;
  /** Чистая (ADR-0008). Ассеты объявляются ALIAS'ами: sha разрешает компилятор (`CP-06`). */
  declareAssets(params: P): readonly AssetRef[];
  /** Чистая (ADR-0008). Роль обязательна, семейство — нет (шрифт канала не выбран, №13). */
  declareFonts(params: P): readonly FontRef[];
  readonly manifest: TemplateManifest;
}

/** Спек любого шаблона — то, чем оперируют реестр и гейт. */
export type AnyTemplateSpec = TemplateSpec<unknown>;

/**
 * Полный список файлов, которые шаблон просит на этих `params`.
 *
 * **ВХОД R3.** Инвариант: «адаптер не открывает файлов вне `assets`/`fonts` запроса». Чтобы
 * это правило было исполнимым, список запроса обязан иметь ЕДИНСТВЕННЫЙ источник — иначе
 * «вне запроса» нечем определить. Источник — эта функция: объединение двух деклараций и
 * ничего сверх них.
 */
export interface RequestedFiles {
  readonly assets: readonly AssetRef[];
  readonly fonts: readonly FontRef[];
}

/**
 * `declareAssets ∪ declareFonts` — **единственный источник списка файлов запроса** (вход R3).
 *
 * `params` прогоняются схемой ДО деклараций, а не после: декларация, получившая невалидные
 * `params`, вернула бы список, которого никто не объявлял, — и адаптер открыл бы файл, не
 * попавший в запрос. Это и есть та дыра, которую R3 закрывает.
 *
 * ВЫЗЫВАЮЩЕГО ПОКА НЕТ. Запрос собирает адаптер (`H-01`), список в него кладёт компилятор
 * (`CP-06`); здесь — вход, и строка **R3** получает пометку «вход есть, вызывающего нет».
 *
 * @throws {z.ZodError} `params` не соответствуют схеме шаблона — с путём к полю.
 */
export function requestFiles(spec: AnyTemplateSpec, params: unknown): RequestedFiles {
  const parsed: unknown = spec.paramsSchema.parse(params);
  return { assets: spec.declareAssets(parsed), fonts: spec.declareFonts(parsed) };
}

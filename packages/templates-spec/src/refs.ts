// Ссылки, которые шаблон ОБЪЯВЛЯЕТ: ассет и шрифт.
//
// АССЕТ ОБЪЯВЛЯЕТСЯ ALIAS'ОМ, А НЕ SHA — решение владельца (`TS-01`, вопрос 4). В `params`
// лежат alias'ы (`asset: "ledger"`, `asset: "pad-loop"` — `fixtures/minimal`), а sha
// разрешает компилятор через каталог (`resolveAlias`, `media/src/assets/catalog.ts`, `M-02`).
// Объявить здесь sha было бы невозможно честно: шаблон каталога не видит и видеть не должен —
// `templates-spec` по карте ADR-0009 зависит только от `core-model`.
//
// **ДОЛГ №120 ЗДЕСЬ ФИКСИРУЕТСЯ, А НЕ УСТРАНЯЕТСЯ.** Он говорит: «форма поля с alias'ами
// расходится с моделью» — `MediaTimePoint.asset` типизирован `Sha256`, а в фикстуре на этом
// месте стоит alias. Решение владельца: `AssetRef` — alias-форма, тип в `core-model` НЕ
// заводится, расхождение записано явно. Кто переписывает alias в sha — компилятор, и это
// `CP-06`, а не эта задача.
//
// РОЛЬ — ИМЯ ПАРАМЕТРА, КОТОРЫЙ ДЕРЖИТ АССЕТ. Это не выбор имени, а уже записанное правило:
// ADR-0002 §4 разворачивает `[img: alias]` в `params: { asset }`, и `compile-ir.ts`
// (`CP-04`) кладёт в IR `role: 'asset'` — «имя параметра шаблона, который ассет держит»
// (комментарий у `IrAssetRef.role`). Назвать роль иначе (`'image'`, `'still.source'`)
// означало бы сменить `segmentIrHash` всех сегментов с картинками ради переименования
// (цена долга №138). Поэтому роль берётся из имени параметра — и №138 закрывается без смены
// ни одного хэша.
//
// У ШРИФТА ALIAS'А НЕТ. Шрифт адресуется записью `asset-record/1` с `kind: font`
// (`fixtures/minimal/fonts/records/…0005.json`), а не строкой каталога: у него нет
// `aliases.yaml`. Поэтому `FontRef` несёт роль и НЕОБЯЗАТЕЛЬНОЕ семейство: шаблон объявляет,
// ЧЕМ шрифт ему служит (`caption`), а какое именно семейство подставить — свойство проекта,
// и оно не выбрано (долг №13, шрифт канала за владельцем).

/**
 * Ассет, объявленный шаблоном: **alias каталога** и роль.
 *
 * Пары `{alias, role}` — вход `SegmentRenderRequest.assets` (ADR-0008 «Контракт», форма
 * `{sha256, path, role}`) после того, как компилятор разрешит alias через каталог и адаптер
 * подставит путь. Ни sha, ни пути здесь нет и быть не может: и то и другое — свойство
 * конкретного прогона, а не произведения.
 */
export interface AssetRef {
  /** Ключ `assets/aliases.yaml` — то, что автор написал в `params`. */
  readonly alias: string;
  /** Имя параметра, который ассет держит (ADR-0002 §4): `asset`. */
  readonly role: string;
  /**
   * **ВИД ФАЙЛА, КОТОРОГО РОЛЬ ЖДЁТ** — `kind` записи `asset-record/1` (`ASSET-01`, 2026-09-10).
   *
   * ПОЧЕМУ ПОЛЕ ПОЯВИЛОСЬ. До него компилятор разрешал alias в sha и клал пару `{sha, role}`
   * в IR, НЕ СПРАШИВАЯ, что это за файл (`compile/src/timeline/contract.ts`, шаг 4). Пока
   * ассеты были только картинками, спросить было не о чем; с приходом вида `video`
   * (`VID-01`) видео под `still@1` доехало бы молча до рендерера и упало бы там — далеко от
   * причины, в подпроцессе, сообщением про `<img src>`. Теперь это `problem` компилятора с
   * адресом записи.
   *
   * **НЕОБЯЗАТЕЛЬНОЕ, УМОЛЧАНИЕ — `image`** (задание `ASSET-01` §2.3, решение владельца).
   * Умолчание покрывает шесть спеков из семи и потому не трогает ни строки в них: у пяти
   * `declareAssets` пуст вовсе, у `still@1` и `parallax25@1` картинка и есть то, чего они
   * ждут. Седьмой — `bed@1` — называет вид ЯВНО (`audio`), потому что умолчание ему не
   * подходит: подложка есть звук, и молчаливый `image` означал бы, что шаблон объявил не то,
   * что просит.
   *
   * ЧЕГО ЭТО ПОЛЕ НЕ ДЕЛАЕТ: не разрешает шаблону выбрать ФАЙЛ. Оно объявляет ТИП роли — то
   * же, что делает `paramsSchema` для чисел, — а какой именно ассет под неё подставлен,
   * по-прежнему решает автор через alias.
   */
  readonly kind?: AssetKind;
}

/**
 * Виды ассетов, различимые контрактом роли.
 *
 * ТРИ, А НЕ ЧЕТЫРЕ: шрифт сюда не входит и входить не может — он объявляется `FontRef`, у
 * него нет alias'а вовсе (`assets/aliases.yaml` его не знает), и роль шрифта разрешается
 * другим путём (`fontRefOf`). Перечень закрыт намеренно, в отличие от `kind` в самой записи
 * (`identifier()`, свободная строка): здесь это не описание файла, а ОЖИДАНИЕ шаблона, и
 * шаблон, ждущий вида, которого движок не знает, — ошибка `tsc`, а не тихий пропуск.
 */
export type AssetKind = 'image' | 'video' | 'audio';

/** Вид, которого роль ждёт по умолчанию, если спек его не назвал. */
export const DEFAULT_ASSET_KIND: AssetKind = 'image';

/**
 * Шрифт, объявленный шаблоном: роль и — необязательно — семейство.
 *
 * Роль обязательна: ADR-0008 требует, чтобы адаптер не открыл ни одного файла вне
 * `assets`/`fonts` запроса (**R3**), а список запроса собирается из объявленных ролей.
 * Семейство необязательно и на фикстуре ОТСУТСТВУЕТ — шрифт канала не выбран (долг №13),
 * а `DejaVu Sans Bold` в `fixtures/minimal/fonts/records` назван временным решением
 * владельца 4 (RM2). Шаблон, называющий семейство, привязал бы к себе выбор, который
 * принадлежит проекту.
 */
export interface FontRef {
  /** Чем шрифт служит шаблону: `caption`. */
  readonly role: string;
  /** `intrinsic.family` записи `asset-record/1`, если шаблон его требует. */
  readonly family?: string;
}

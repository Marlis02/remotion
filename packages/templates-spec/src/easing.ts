// Закрытый реестр easing (**D5**) — **ДАННЫЕ, А НЕ КОД**.
//
// ЧТО ЗДЕСЬ ЛЕЖИТ. Шесть ИМЁН кривых и порядок сборки трансформаций. Ни одной формулы, ни
// одной таблицы значений, ни одного `Math.*`. Реализация кривой живёт в пришпиленном
// `gsap@3.15.0` рендерера, её версия входит в `engineFingerprint` (ADR-0006 §3, **R14**), а в
// IR едут строка-идентификатор и числа опорных точек — ADR-0007 §3 дословно: «IR хранит
// опорные точки и идентификатор кривой, **никогда** покадровые значения».
//
// ПОЧЕМУ ИМЕНА ЖИВУТ ИМЕННО ЗДЕСЬ, А НЕ В РЕНДЕРЕРЕ. Кривую объявляет ШАБЛОН — полем
// `easingIds` манифеста и схемой своих `params`, — а шаблоны живут в этом пакете. Рендерер
// эти имена ПОТРЕБЛЯЕТ (`H-06`: `gsap.parseEase(id)`), и стрелка `renderer-hyperframes →
// templates-spec` в карте ADR-0009 есть, обратной нет. Сам этот пакет `gsap` не импортирует и
// импортировать не вправе (**M6**): у него ровно одна стрелка — `core-model`.
//
// ПОЧЕМУ КРИВАЯ НАЗЫВАЕТСЯ ПО ИМЕНИ РЕНДЕРЕРА, А НЕ «ПО СМЫСЛУ». `FACT` (SP-3c §6.2 п. 1):
// `Easing.inOut(Easing.ease)` Remotion — bezier-solver с ньютоновскими итерациями, у GSAP
// такого ease нет, у Remotion нет CSS-кривых; цена расхождения между «одинаковыми» роликами —
// PSNR 30 dB. Отсюда правило ADR-0007 §3: **переносимой записи «то же easing на другом
// рендерере» не существует**, и делать вид, что она есть, значит закладывать тихое
// расхождение. Поэтому в реестре стоит `power2.inOut`, а не `inOutCubic`: второе имя обещало
// бы смысл, за которым нет одинаковых пикселей. Дрейф фикстуры по этому основанию уже закрыт
// решением RM2 (roadmap §9 п. 8).
//
// ПОЧЕМУ ЗДЕСЬ НЕТ `spring()`. `FACT` (SP-3e §2 п. 4): длительность пружины — ПРОИЗВОДНАЯ от
// `damping`/`stiffness`/`mass`, а не заданная величина. Значит окно клипа в кадрах перестаёт
// быть функцией объявленных автором параметров, и **T4** (`frameEnd ≤
// segmentDurationInFrames`) проверялся бы по поведению библиотеки, а не по IR. Запрет
// исполняется **отсутствием имени в реестре** — отдельного механизма нет и не нужно: список
// закрыт, а всё, чего в нём нет, отвергается схемой манифеста и `assertEasingId`. Тем же
// отсутствием исполняется и запрет любой другой кривой: реестр — это перечисление, а не
// фильтр.
//
// ПОКАДРОВЫХ ЗНАЧЕНИЙ ЗДЕСЬ НЕТ И БЫТЬ НЕ МОЖЕТ. Предвычисленная таблица значений — тот самый
// обход, которым SP-3 добывал чужую кривую (`Easing.inOut(Easing.ease)` через таблицу), и
// ADR-0007 §3 его запрещает: Ken Burns получил бы видимую ступенчатость, а IR распух. Форма
// реестра — список строк — этого просто не выражает; отдельного охранника на «не заводи
// таблицу» не существует, и это сказано вслух, а не подразумевается.

import { z } from 'zod';

import { TemplateSpecError } from './errors.js';

/**
 * Шесть кривых — **весь** реестр (ADR-0007 §3, строка **D5**, roadmap §4.8 `TS-02`).
 *
 * Список ЗАКРЫТ: седьмая кривая — решение владельца, а не деталь реализации. Ровно так уже
 * решался вопрос о цвете (ADR-0007, RM1, решение владельца 11: «реестр D5 на цвет не
 * расширяется в v1»), и по той же причине: каждая новая кривая — это новые пиксели, за
 * которые никто не отвечал измерением.
 *
 * ПАРАМЕТРИЗОВАННАЯ КРИВАЯ — СТРОКА ЦЕЛИКОМ. `'back.out(1.7)'` записана одним литералом, как
 * в D5, а не парой «имя + число». Причина не в лени: `gsap.parseEase` принимает именно строку,
 * и разбор её на имя и параметр здесь означал бы вторую грамматику кривых рядом с той,
 * которая уже есть у рендерера, — то же рассуждение, по которому в репозитории одна
 * грамматика имени шаблона (долг №37).
 *
 * `none` — тождественная (`f(t) = t`), линейное движение. Её присутствие делает список
 * достаточным: без неё шаблон, которому easing не нужен, был бы вынужден назвать кривую,
 * которой не хотел.
 */
export const EASING_REGISTRY = [
  'power1.inOut',
  'power2.inOut',
  'power3.out',
  'back.out(1.7)',
  'sine.inOut',
  'none',
] as const;

/** Идентификатор кривой из закрытого реестра **D5**. Ничего сверх шести имён. */
export type EasingId = (typeof EASING_REGISTRY)[number];

/**
 * Порядок сборки трансформаций — **данные реестра, а не наследство библиотеки**.
 *
 * ИЗМЕРЕНИЕ, ОТКУДА ПОРЯДОК. `FACT` (SP-3c §6.2 п. 3): GSAP собирает `transform` в порядке
 * `perspective → translate → rotate → skew → scale` — `gsap/dist/gsap.js`, строки 5091–5121,
 * `translate3d(...)` дописывается РАНЬШЕ `scale(...)`, то есть сдвиг **не** масштабируется.
 * SP-3 (Remotion) задавал обратное — `scale(s) translate(tx, ty)`, где сдвиг масштабируется.
 * На нашем Ken Burns разница — **до 5.4 px сдвига на последнем кадре** (36 px × 0.15).
 *
 * ПОЧЕМУ ЗАПИСАНО ЯВНО. Порядок — часть кривой движения, и он у рендереров разный (ADR-0007
 * §3: «реестр обязан фиксировать порядок явно, а не наследовать его от библиотеки»). Живи он
 * в шаблонах, он был бы записан в двенадцати манифестах; живи он «в GSAP» — сменился бы молча
 * вместе с версией библиотеки. Здесь он назван один раз, и `engineFingerprint` стережёт версию,
 * от которой он взят.
 *
 * ДВА ЧЛЕНА, А НЕ ПЯТЬ. Названы те, которыми пользуются шаблоны v1 (`kenburns@1` — `x`/`y` и
 * `scale`), в их относительном порядке из измерения выше. `rotate`/`skew`/`perspective` в
 * реестре не названы, потому что ни один шаблон v1 их не объявляет, а называть порядок для
 * компонент, которых никто не двигает, значило бы записать не проверенное ничем. Долг заведён.
 *
 * ЧЕГО ЭТА КОНСТАНТА НЕ ДЕЛАЕТ. Она ничего не исполняет: реализаций шаблонов сегодня нет
 * (`H-06`), и проверять порядок поведением нечем. Она — объявление, на которое `H-06` обязан
 * сослаться; долг об этом заведён этой же сессией.
 */
export const TRANSFORM_ORDER = ['translate', 'scale'] as const;

/** Компонента трансформации, чей порядок зафиксирован реестром. */
export type TransformComponent = (typeof TRANSFORM_ORDER)[number];

/**
 * Текст отказа — **один на всех потребителей**.
 *
 * Схема манифеста, `assertEasingId` и `EasingIdSchema` говорят ОДНО И ТО ЖЕ, потому что
 * читают одну функцию: три разных текста про одно правило означали бы три разных
 * представления о том, что такое реестр. Сообщение называет и кривую, и ПОЛНЫЙ список —
 * человек, получивший отказ, обязан увидеть, из чего выбирать, не открывая исходник.
 */
export function easingRejection(what: string, id: string): string {
  return (
    `${what}: кривая \`${id}\` вне закрытого реестра easing (**D5**, ADR-0007 §3). ` +
    `Реестр состоит из шести кривых и ЗАКРЫТ: ${EASING_REGISTRY.map((e) => `\`${e}\``).join(', ')}. ` +
    'Кривая называется ПО ИМЕНИ РЕНДЕРЕРА, а не «по смыслу» (`FACT` SP-3c §6.2 п. 1: цена ' +
    'расхождения между «одинаковыми» роликами — PSNR 30 dB), поэтому имя вроде `inOutCubic` ' +
    'или `easeInOutCubic` реестром не принимается даже тогда, когда кривая с таким смыслом в ' +
    'нём есть. Седьмая кривая — решение владельца, а не правка этого файла'
  );
}

/**
 * Схема одного идентификатора — `z.enum` ИЗ ТОЙ ЖЕ КОНСТАНТЫ (решение владельца, развилка 2,
 * вариант «А»).
 *
 * Она даёт ТИП: поле, объявленное через неё, имеет тип `EasingId`, и кривая вне реестра
 * становится ошибкой `tsc` — дословный критерий готовности roadmap §4.8 `TS-02` «кривая вне
 * реестра — ошибка компиляции». Рантайм-отказ она даёт тоже, но он здесь вторичен: спек —
 * TS-литерал, и до рантайма такая ошибка доживать не должна.
 */
export const EasingIdSchema = z.enum(EASING_REGISTRY, {
  error: (issue) => easingRejection('easing', String(issue.input)),
});

/** Членство в реестре как предикат-сужение. Ничего не бросает — вопрос, а не отказ. */
export function isEasingId(value: string): value is EasingId {
  return (EASING_REGISTRY as readonly string[]).includes(value);
}

/**
 * Членство как ОТКАЗ — для потребителя, который держит `string` (поправка владельца П2).
 *
 * ОБЫЧНЫЙ `throw`, БЕЗ ZOD ВНУТРИ, И ЭТО РЕШЕНИЕ, А НЕ ЭКОНОМИЯ. Потребитель — `H-06` в
 * рендер-пути: он получает `easing` строкой из `params` клипа IR и нуждается в СУЖЕНИИ типа,
 * а не в разборе схемой. `EasingIdSchema.parse` дал бы там `z.ZodError` — ошибку про форму
 * данных в месте, где нарушено ПРАВИЛО, и с текстом, называющим путь в объекте вместо кривой.
 *
 * @throws {TemplateSpecError} `D5` — кривой нет в реестре.
 */
export function assertEasingId(value: string, at = 'easing'): asserts value is EasingId {
  if (!isEasingId(value)) {
    throw new TemplateSpecError('D5', easingRejection(at, value));
  }
}

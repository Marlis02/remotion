// Дамп AST. ЕДИНСТВЕННЫЙ выход AST наружу — и он не персистируется (ADR-0002 §5).
//
// НЕТ СХЕМЫ И НЕТ ФАЙЛА. AST вырождается в Timeline и span-map, обе доступны дальше по
// пайплайну; заводить под него семейство и цепочку миграций значило бы платить за объект,
// который пересчитывается за миллисекунды.
//
// КАНОНИЧЕСКАЯ ФОРМА, А НЕ `JSON.stringify`: порядок ключей байтовый на всех уровнях, ни одного
// незначимого пробела, `NaN`/`undefined`/классы — ошибка с путём. Golden-тест сравнивает БАЙТЫ,
// поэтому «почти каноническая» форма сделала бы его тестом порядка вставки ключей.

import { canonicalJson } from '@vpe/schema';

import type { SourceDocument } from './ast.js';

/** Канонический JSON AST — для отладки (`--dump-ast`) и golden-теста, больше ни для чего. */
export function dumpAst(ast: SourceDocument): string {
  return canonicalJson(ast);
}

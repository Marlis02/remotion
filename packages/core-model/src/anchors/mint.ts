// Минт идентификатора якоря — ЕДИНСТВЕННОЕ место недетерминизма во всём `core-model`.
//
//     w:<base32(csprng(128 бит))[:16]>          (ADR-0004 §4, ревизия M3)
//
// ПОЧЕМУ CSPRNG, А НЕ ФУНКЦИЯ ОТ `ledgerRev`. Первая редакция ADR-0004 минтила
// `w:<base32(blake3(seedRoot ‖ ledgerRev ‖ mintIndex))[:12]>` и называла коллизию «невозможной»,
// потому что новый id проверяется по множеству живых. Проверка локальна для ВЕТКИ. Две ветки,
// отошедшие от одного `ledgerRev` (работа с LLM-драфтами в отдельной ветке — рабочий сценарий,
// Charter §1), минтят с одинаковым `seedRoot`, одинаковым `ledgerRev` и одинаковыми `mintIndex`
// ⇒ РАЗНЫМ токенам детерминированно достаются ОДИНАКОВЫЕ id, а merge (ADR-0005 §10 — объединение
// множеств) сводит их в один файл. Это ровно «правка применяется к чужому слову», ради
// предотвращения которого отвергнута контент-производная схема. Тест двух веток
// (`test/anchors-merge.test.ts`) держит это правило: подставленный ДЕТЕРМИНИРОВАННЫЙ источник
// байтов роняет инвариант A3, настоящий CSPRNG — нет.
//
// V8 НЕ НАРУШЕН. Charter V8 запрещает недетерминизм в РЕНДЕР-ПУТИ; минт id — акт авторства,
// ровно как уже принятый `recordId` (4 случайных байта из CLI, ADR-0007 §1). Значение попадает
// в git и дальше является ВХОДОМ, а не вычисляемой величиной. Свойство «два `parse` подряд на
// одном ledger'е дают одинаковый результат» держится потому, что минт происходит только для
// НОВЫХ якорей, а результат немедленно фиксируется в ledger'е (см. `sync.ts`).
//
// ПОЧЕМУ ИСТОЧНИК БАЙТОВ — ПАРАМЕТР. Тест детерминизма обязан уметь подставить свой источник,
// иначе «два прогона дали одно и то же» проверялось бы вместе со случайностью. Порт заодно
// оставляет `node:crypto` в ОДНОМ файле пакета — это и есть исключение линта (`eslint.config.js`,
// расширение правила D4).

import { randomBytes as nodeRandomBytes } from 'node:crypto';

import { asAnchorId, base32, type AnchorId } from '@vpe/schema';

import { AnchorLedgerError } from './errors.js';

/** Источник случайных байтов. Продакшн — `csprng`; тест подставляет свой. */
export type RandomBytes = (byteLength: number) => Uint8Array;

/** 128 бит — дословно ADR-0004 §4. */
export const MINT_BYTES = 16;

/**
 * Сколько символов base32 идёт в id. Дословно ADR-0004 §4 (`[:16]`).
 *
 * 16 символов base32 = 80 бит энтропии из 128 сгенерированных. Обрезка ЗДЕСЬ не является
 * дефектом (3) из Context ADR-0004 («обрезка хэша без проверки уникальности»): дефект был у
 * КОНТЕНТ-ПРОИЗВОДНОЙ схемы, где обрезка складывалась с предсказуемостью входа. Здесь вход —
 * CSPRNG, а уникальность живых id проверяется инвариантом A3 на каждом `vpe fmt --check`.
 */
export const MINT_LENGTH = 16;

/** Криптографический источник — единственный импорт `node:crypto` в `core-model`. */
export const csprng: RandomBytes = (byteLength) => nodeRandomBytes(byteLength);

/**
 * Минтит новый идентификатор токена.
 *
 * @throws {AnchorLedgerError} источник вернул не то число байтов (мок в тесте ошибся) или
 *   получившийся id не проходит форму ADR-0004 §1.
 */
export function mintAnchorId(random: RandomBytes = csprng): AnchorId {
  const bytes = random(MINT_BYTES);
  if (bytes.length !== MINT_BYTES) {
    throw new AnchorLedgerError(
      'ADR-0004 §4',
      `источник случайности вернул ${String(bytes.length)} байт вместо ${String(MINT_BYTES)}: ` +
        'минт обязан брать ровно 128 бит, иначе энтропия id — не та, что записана в ADR',
    );
  }
  return asAnchorId(`w:${base32(bytes).slice(0, MINT_LENGTH)}`);
}

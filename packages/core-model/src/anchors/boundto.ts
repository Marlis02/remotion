// `boundTo` — контекстная подпись якоря (ADR-0004 §6).
//
//     boundTo = blake3(prevSurface, surface, nextSurface, ordinal)
//
// ЗАЧЕМ ОНА СУЩЕСТВУЕТ. Это те самые «пять строк, превращающие тихий отказ в громкий»
// (ADR-0004 §6). Совпал id, но не совпал контекст ⇒ ОШИБКА КОМПИЛЯЦИИ, правка не применяется,
// сборка останавливается. Без неё дефект (1) из Context ADR-0004 — тихое перенацеливание
// правки на другое физическое слово — не обнаруживается ничем.
//
// ВХОД СОБИРАЕТСЯ `canonicalJson`, А НЕ КОНКАТЕНАЦИЕЙ, И ЭТО НЕ СТИЛЬ. Склейка строк не
// является инъективной кодировкой кортежа: `("ab", "c")` и `("a", "bc")` дают один и тот же
// поток байтов, то есть один и тот же `boundTo` у двух РАЗНЫХ контекстов — ровно та тихая
// коллизия, ради устранения которой подпись и заводится. Канонический JSON массива границы
// сохраняет (`["ab","c"]` против `["a","bc"]`), и это проверяется тестом, а не подразумевается.
// Массив, а не объект: имена полей в хэш не идут — их порядок задан формулой ADR, а не схемой.
//
// `null` НА КРАЯХ — ЗНАЧИМОЕ ЗНАЧЕНИЕ. У первого якоря сцены нет предыдущего, у последнего нет
// следующего; пустая строка была бы неотличима от пустого токена, поэтому в схеме `anchors/1`
// поля `prev`/`next` объявлены `nullable`, а в `canonicalJson` `null` кодируется отдельно.
//
// ЧЕГО ЗДЕСЬ НЕТ. Хранения значения. `boundTo` живёт в ЗАПИСИ OVERRIDE (ADR-0004 §7 перечисляет
// его среди полей журнала правок), а не в ledger'е: в схеме `anchors/1` такого поля нет, и это
// не упущение — из записи ledger'а подпись вычисляется за один вызов, а хранимая копия
// вычисляемого значения расходится с оригиналом при первой же правке. Сверка перед применением
// правки — задача `O-01`, единственного писателя overrides.

import { blake3, canonicalJson, type AnchorEntry, type Blake3 } from '@vpe/schema';

import { AnchorLedgerError } from './errors.js';

/** Контекст якоря: соседние ПОВЕРХНОСТНЫЕ формы и порядковый номер в сцене. */
export interface AnchorContext {
  /** Поверхностная форма предыдущего токена сцены; `null` — якорь первый. */
  readonly prev: string | null;
  /** Поверхностная форма самого якоря (ADR-0004 §5: токен исходника, не нормализованное слово). */
  readonly surface: string;
  /** Поверхностная форма следующего токена сцены; `null` — якорь последний. */
  readonly next: string | null;
  /** Порядковый номер якоря внутри сцены, 1-based. */
  readonly ordinal: number;
}

/** Подпись контекста. Порядок аргументов — дословно ADR-0004 §6. */
export function boundTo(context: AnchorContext): Blake3 {
  return blake3(canonicalJson([context.prev, context.surface, context.next, context.ordinal]));
}

/**
 * Подпись контекста, записанного в ledger'е.
 *
 * Запись описывает якорь на момент своей ревизии (см. `ledger.ts`), поэтому подпись последней
 * записи якоря — это его подпись «как сейчас в ledger'е». Сравнение её с подписью, посчитанной
 * по свежему разбору, и есть проверка §6.
 */
export function boundToOf(entry: AnchorEntry): Blake3 {
  return boundTo({ prev: entry.prev, surface: entry.surface, next: entry.next, ordinal: entry.ordinal });
}

/**
 * Сверка перед применением правки (ADR-0004 §6, §8: **ошибка компиляции, а не WARN**).
 *
 * Сообщение называет обе подписи и обещанный контекст: без них человек видит «хэши не сошлись»
 * и не знает, что именно поехало. Что делать дальше, ADR-0004 §8 говорит прямо, и это же
 * говорит текст ошибки: `vpe override rm` или заново `vpe nudge` (обе команды — `O-01`).
 *
 * @throws {AnchorLedgerError} контекст якоря изменился.
 */
export function assertBoundTo(id: string, expected: Blake3, actual: Blake3, context?: AnchorContext): void {
  if (expected === actual) return;
  const where =
    context === undefined
      ? ''
      : ` Сейчас вокруг него: \`${context.prev ?? '—'}\` ${context.surface} \`${context.next ?? '—'}\`` +
        `, порядковый номер ${String(context.ordinal)}.`;
  throw new AnchorLedgerError(
    'ADR-0004 §6',
    `контекст якоря \`${id}\` изменился: правка ждала \`${expected}\`, а сейчас \`${actual}\`.` +
      `${where} Правка НЕ применена и сборка остановлена — это дешевле, чем применить её к ` +
      'соседнему слову. Дальше: `vpe override rm` или заново `vpe nudge`',
  );
}

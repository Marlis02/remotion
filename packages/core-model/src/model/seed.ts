// `seedOf` — иерархия seed'ов ADR-0007 §1.
//
//     seed(node) = uint64( blake3( seedRoot ‖ chapterId ‖ sceneId ‖ recordId ‖ purpose ) )
//
// ЧЕТЫРЕ ВХОДА, И НИ ОДНОГО СВЕРХ НИХ. Инвариант рядом с V8, дословно: «ни один вход seed'а не
// зависит от порядка узлов, от значений `params` и от разбиения на сегменты» (**D1**), и
// «`segmentId` в seed не входит — иначе изменение сегментации меняло бы картинку» (**D2**).
// Дефект, ради которого это написано, назван в Context ADR-0007 п. 1: позиционный
// `templateInstanceId` означал, что вставка `[img:]` в начало сцены ТИХО переснимает визуал всей
// сцены при зелёном AC4, а хэш от параметров — что подкрутка `pad: 8→9` меняет ещё и случайность.
//
// Поэтому у функции РОВНО ДВА аргумента, и второй — структура из четырёх полей. Всё, чего в
// `SeedNode` нет, в seed попасть не может физически; это охраняется тремя способами: типом,
// тестом (лишнее поле, поданное кастом, seed'а не меняет) и грепом по коду этого файла
// (`tests/lints/d2-seed-inputs.test.ts`, вторая половина охранника D2).
//
// ВХОД ХЭША — КАНОНИЧЕСКИЙ JSON, А НЕ КОНКАТЕНАЦИЯ (решение владельца, `C-05` вопрос 2).
// ADR-0007 §1 пишет `‖`. Склейка строк не является инъективной кодировкой кортежа: пара
// ("ab","c") и пара ("a","bc") дают один и тот же поток байтов, то есть один seed у двух разных
// узлов — ровно та тихая коллизия, против которой пишется вся эта иерархия. `purpose` —
// свободная строка шаблона, sceneId и chapterId — свободные идентификаторы, так что случай не
// умозрительный. То же решение и по той же причине было принято в `C-04` для `boundTo`
// (ADR-0004 §6). Расхождение с буквой ADR записано в `docs/DEBTS.md`; правка ADR — за владельцем.
//
// `null` У СЦЕНЫ — ЗНАЧИМОЕ ЗНАЧЕНИЕ, а не «пусто»: запись на якоре главы сцены не имеет
// (`Scope`, `direction.ts`). Пустая строка была бы неотличима от сцены с пустым id;
// `canonicalJson` кодирует `null` отдельно.
//
// ЧЕГО ЗДЕСЬ НЕТ. Материализации seed'ов в IR (ADR-0007 §2: «seed'ы материализуются в RenderIR
// на этапе компиляции; рендерер их не выводит») — это `CP-03`. Формы, в которой 64-битное
// число попадёт в JSON IR, здесь тоже нет: она принадлежит тому, кто пишет IR.

import { blake3, canonicalJson } from '@vpe/schema';

import { ModelError } from './errors.js';

/**
 * Узел, которому нужна случайность. Все поля — из формулы ADR-0007 §1, и других нет.
 *
 * `purpose` — «строковая константа шаблона (`'kenburns.jitter'`)»: у одной записи режиссуры
 * узлов может быть несколько, и различает их только он.
 */
export interface SeedNode {
  readonly chapterId: string;
  /** `null` — узел стоит на якоре главы: сцены у него нет. */
  readonly sceneId: string | null;
  readonly recordId: string;
  readonly purpose: string;
}

/** Сколько байтов дайджеста идёт в `uint64`. */
export const SEED_BYTES = 8;

/** Столько же в hex. Дайджест blake3 — 32 байта, берётся его начало. */
const SEED_HEX = SEED_BYTES * 2;

/**
 * Seed узла.
 *
 * **`bigint`, а не `number`, и это не стиль** (`INFERENCE`, решение владельца `C-05` вопрос 3).
 * ADR-0007 §1 пишет `uint64`; `uint64` не помещается в `Number.isSafeInteger` (граница 2^53−1),
 * то есть `number` молча терял бы младшие биты у примерно 99.9 % значений. Тихая потеря битов —
 * ровно тот класс дефекта, против которого написан ADR-0007 §3.
 *
 * **Какие байты и в каком порядке** — ADR не говорит, взято: **первые 8 байт дайджеста,
 * big-endian**, то есть первые 16 hex-символов, прочитанные как число. Это самое прямое чтение
 * «начала хэша» и единственное, которое совпадает с тем, что человек видит в дампе дайджеста.
 * `INFERENCE`, записан в `docs/DEBTS.md`.
 *
 * @param seedRoot `project.yaml` → `seedRoot`; коммитится (ADR-0007 §1).
 * @throws {ModelError} `seedRoot` — не целое ≥ 0 в пределах безопасных целых.
 */
export function seedOf(seedRoot: number, node: SeedNode): bigint {
  if (!Number.isSafeInteger(seedRoot) || seedRoot < 0 || Object.is(seedRoot, -0)) {
    throw new ModelError(
      'ADR-0007 §1',
      `\`seedRoot\` = ${String(seedRoot)} — не целое ≥ 0 в пределах Number.isSafeInteger. ` +
        'Величина коммитится в `project.yaml` и входит в каждый seed проекта',
    );
  }
  const digest = blake3(canonicalJson([seedRoot, node.chapterId, node.sceneId, node.recordId, node.purpose]));
  return BigInt(`0x${digest.slice(0, SEED_HEX)}`);
}

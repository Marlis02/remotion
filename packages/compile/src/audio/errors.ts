// Ошибка зоны `audio` (`CP-05`).
//
// ПОЧЕМУ НЕ `CompileError` И НЕ `RenderIrError`. Первый живёт в `timeline/errors.ts` и несёт
// перечень `CompileRule` авторского слоя; второй — в `render-ir/`, куда зоне `audio` вход
// закрыт строкой зон (решение владельца 6). Общий класс ошибок ради удобства открыл бы
// границу, ради которой она заведена, — то же рассуждение, которым `CP-04` отказался от
// `CompileError` в пользу `RenderIrError`.
//
// ОШИБКА НАЗЫВАЕТ ПРАВИЛО, А НЕ СЛЕДСТВИЕ — как `TimeModelError` (`C-01`), `ModelError`
// (`C-05`), `CompileError` (`CP-01`), `AudioError` (`M-03`), `RenderIrError` (`CP-04`).

/** Правила, на которые ссылаются ошибки стадии звука. */
export type CompileAudioRule =
  /**
   * Дорожка непрерывна, не режется и добивается тишиной до `frameStartSample(F)` (ADR-0003 T5).
   *
   * Под этим именем ходят: дыра или перекрытие между элементами, сумма длин ≠ длине дорожки,
   * поправка `boundary-correction` не последним элементом сегмента, вторая поправка у одного
   * сегмента, поправка, попавшая в `L_i`, и добивка не в самом конце ролика.
   */
  | 'ADR-0003 T5'
  /**
   * `Σ A_i ≤ frameStartSample(F)`, разница `< n` — свойство (3) T6 (**T6c**).
   *
   * Считает величину `CP-04` (`assemblyManifest` → `trackTailSamples`); здесь по ней ПАДАЮТ,
   * и здесь же манифест сверяется с сеткой: `Σ A_i + хвост == frameStartSample(F)`. Манифест,
   * собранный на другой сетке, ловится ровно этим равенством.
   */
  | 'ADR-0003 T6c'
  /**
   * `ε_i = frameStartSample(f_i) − a_i` — A/V-невязка сегментации (**T6d**).
   *
   * Форма: `ε_i ≥ 0`; `ε_0 == 0`; `ε_i < i` при `i ≥ 1`; `ε_i < n`. Порог не проверен на
   * реальном ролике до `X-02`/SP-5 (roadmap, риск `CP-05`) — ассерт при этом стоит.
   */
  | 'ADR-0003 T6d'
  /**
   * Дубль пришёл не тем, чем обещал take-файл (ADR-0003 T7).
   *
   * Под этим именем ходят: `pcm.sha256 == null` у речевого клипа, отсутствие байтов у
   * источника PCM, чужая частота дискретизации (ресемплинг — ingest, не сборка) и окно
   * `[leadIn, numSamples − tail)`, не помещающееся в присланные байты.
   */
  | 'ADR-0003 T7'
  /**
   * `F ≤ maxDurationFrames`; компилятор ПАДАЕТ и печатает раскладку (ADR-0003 T9, он же PG-E1).
   *
   * `FACT` (r3 §3.3): Short длиннее минуты с claimed-музыкой теряет монетизацию. Величина,
   * которую движок добавляет сам (`Σ δ` T6 и `Σ gap` T8), обязана иметь охранника.
   */
  | 'ADR-0003 T9';

/** Нарушение правила стадии звука: несёт имя правила, а не только текст. */
export class CompileAudioError extends RangeError {
  readonly rule: CompileAudioRule;

  constructor(rule: CompileAudioRule, reason: string) {
    super(`${rule}: ${reason}`);
    this.name = 'CompileAudioError';
    this.rule = rule;
  }
}

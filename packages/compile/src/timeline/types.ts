/**
 * Поля `compile-profile/1`, которые нужны `compose`, и ни одного сверх.
 *
 * ТИПИЗИРОВАННЫЙ ВХОД, А НЕ ЧТЕНИЕ YAML. Образец — `CompileProfileInput` в
 * `media/src/cache/keys.ts` (`M-05`): `@vpe/schema` из `compile` не резолвится вовсе, а чтение
 * профиля — обязанность CLI (`L-01`). Умолчаний нет ни у одного поля: три числа T8 — «принятые
 * величины» решения владельца 7, и подставить их здесь значило бы сделать профиль
 * необязательным ровно там, где C4 требует обратного.
 *
 * ~~`fps` в этом наборе НЕТ, и это следствие решения по вопросу 1: Timeline кадров не знает.~~
 * *(изменено: `CP-02`, решение владельца 2026-08-26, вопрос 7 (а).)* `fps` появился, и решение
 * `CP-01` он НЕ отменяет: кадров в Timeline по-прежнему нет, позиции не квантуются, T3 не
 * задет. Сетка нужна ровно за одним — перевести `captions.minGroupDurationFrames` в сэмплы,
 * то есть измерить ДЛИНУ `n` кадров, а не найти позицию. Разбор — шапка `captions.ts`.
 */
export interface CompileProfileInput {
  /** ADR-0003 T1: источник истины физического времени. */
  readonly projectSampleRate: number;
  /**
   * Кадровая сетка — ТОЛЬКО ради длины порога субтитров (решение владельца, вопрос 7 (а)).
   *
   * Ни одна позиция Timeline от неё не зависит: критерий T11 «число `w:`-якорей не зависит от
   * fps» покрыт тестом на трёх сетках (30/1, 60/1, 30000/1001), и группы при разных fps
   * различаются только тем, какие из них помечены короткими.
   */
  readonly fps: Fps;
  /** Между абзацами внутри сцены (T8). */
  readonly defaultParagraphGapSamples: number;
  /** Между сценами (T8). Инвариант корректности — строго больше нуля. */
  readonly defaultSceneGapSamples: number;
  /** Между главами (T8). */
  readonly defaultChapterGapSamples: number;
  /**
   * Порог длины сегмента в КАДРАХ (`CP-03`; ADR-0008 «Бюджет AC2»).
   *
   * ПОЛЕ ПРОФИЛЯ, А НЕ РЕКОМЕНДАЦИЯ — так это записано в ADR дословно: «компилятор **обязан**
   * объединять соседние сегменты, пока длина меньше порога, и печатать, сколько кандидатов на
   * разрез он отклонил по этой причине». Умолчания нет по той же причине, что у трёх gap'ов
   * T8: 45 — принятая величина решения владельца 7, и подставить её здесь значило бы сделать
   * профиль необязательным ровно там, где C4 требует обратного.
   *
   * В КАДРАХ, А НЕ В СЭМПЛАХ, И ЭТО СОДЕРЖАТЕЛЬНО: порог — эвристика стоимости РЕНДЕРА
   * (старт процесса и Chrome на сегмент, 1.86 с), а рендер считает кадры. Перевод в сэмплы —
   * одной функцией `core-model` (`frameStartSample`), новой точки конверсии времени нет.
   */
  readonly minSegmentDurationFrames: number;
  /**
   * Версия реестра шаблонов (`compile-profile/1`, ADR-0006 §5; **K6**).
   *
   * *(Добавлено: `CP-07`, 2026-08-28.)* Поле появилось в наборе `compile`, потому что у
   * компилятора появился РЕЕСТР: `templateContracts` сверяет `registry.version` с этой
   * строкой до первой записи. До `CP-07` поля здесь не было намеренно — за именем не стояло
   * ничего, что стадия могла бы проверить (`CP-04` §7, «входа в стадию не имеют вовсе»).
   *
   * **K4: хэш IR оно НЕ ДВИГАЕТ.** Расхождение — ошибка компиляции, а совпадение оставляет
   * IR тем же; в `segmentKey` поле входит отдельной строкой (материал долга №114), а не
   * поглощается `segmentIrHash`. Строка K4-матрицы переписана в отчёте `CP-07`.
   *
   * Единственное имя в allowlist'е K6 (`S-02-fix`): версия реестра есть НАМЕРЕНИЕ автора, а
   * не измеренное окружение, и потому живёт в профиле законно.
   */
  readonly templateRegistryVersion: string;
  /** Блок `captions` профиля целиком (`CP-02`). */
  readonly captions: CaptionsProfileInput;
}

/**
 * Числа группировки субтитров (`compile-profile/1 → captions`, ADR-0003 «Субтитры (M6)»).
 *
 * Значения решением владельца 2026-08-23 и 2026-08-26: группа — 1–3 слова, всегда одна строка,
 * потолок 21 символ при кегле 72 (измерено по DejaVu Sans Bold, `CP-02`). Умолчаний нет ни у
 * одного поля — по той же причине, что у трёх gap'ов T8.
 */
export interface CaptionsProfileInput {
  /** Нижняя граница числа СЛОВ в группе. Сильнее правила конца предложения, слабее потолков. */
  readonly tokensPerGroupMin: number;
  /** Верхняя граница числа слов. */
  readonly tokensPerGroupMax: number;
  /**
   * Порог ЗАПИСИ В ОТЧЁТ, а не цель (решение владельца 2026-08-26, вопрос 1, чтение «б»).
   *
   * Группа, которая при максимуме слов всё равно короче него, принимается как есть и попадает
   * в `CaptionReport`: увеличить её нечем — число слов уже максимально, а сдвиг запрещён (T10).
   */
  readonly minGroupDurationFrames: number;
  /** Потолок по числу символов display-текста группы ВМЕСТЕ С ПРОБЕЛАМИ. */
  readonly maxGroupChars: number;
}

// ── Границы и кандидаты на разрез ───────────────────────────────────────────

/**
 * Тип границы, на которой стоит тишина.
 *
 * `intra-paragraph` — граница между частями одного абзаца, разведёнными `[pause:]` (ADR-0002
 * §2: «режет SpeechChunk — да, только на границе предложения»). Дефолта у неё нет: движок
 * внутри абзаца ничего не добавляет.
 *
 * ПОЛЕ ЗАВЕДЕНО НЕ ДЛЯ ОТЧЁТА (поправка владельца П2, 2026-08-26): `CP-03` обязан знать,
 * где стоит **V4** — граница главы обязана быть границей сегмента, а границу главы от границы
 * абзаца по одной длине тишины не отличить (`[pause: 600ms]` между абзацами и
 * `defaultChapterGapSamples` — одно и то же число 14400 при 24 кГц).
 */
export type BoundaryKind = 'intra-paragraph' | 'paragraph' | 'scene' | 'chapter';

/**
 * Точка, где сегментация ВПРАВЕ поставить разрез (ADR-0003 T6).
 *
 * Критерий T6 — «в точке разреза есть тишина ненулевой длины»; какие виды тишины считаются,
 * решено владельцем (2026-08-26, вопрос 10): `author` и `gap`, но не `boundary-correction`
 * (он речь не разделяет, а достраивает хвост сегмента). Кандидат в правку ADR-0003 T6 — в
 * отчёте.
 *
 * ЗДЕСЬ ТОЛЬКО ДАННЫЕ. Отбор кандидатов по `minSegmentDurationFrames`, таблица отклонённых и
 * сами сегменты — `CP-03`; печать таблицы — `L-01`.
 */
export interface CutCandidate {
  /**
   * Сэмпл, с которого начинается клип тишины.
   *
   * ~~Разрез ставится ЗДЕСЬ.~~ *(исправлено: `CP-03`, решение владельца 2026-08-26,
   * наблюдение О1.)* **Разрез ставится в КОНЦЕ этого клипа**, то есть на
   * `atSample + durationSamples`: по ADR-0003 T6 gap принадлежит **предшествующему** сегменту
   * («он его хвост»), значит шов идёт за ним, а не перед ним. На `fixtures/minimal` это
   * разница между 544080 и 551760 — и 551760 есть стык областей `sc:intro`/`sc:turn`,
   * посчитанный `areasOf` независимо. Оба числа печатает таблица `CutTable` (`CP-03`).
   */
  readonly atSample: Samples;
  /** Длина тишины в этой точке. */
  readonly durationSamples: Samples;
  /** `boundary-correction` кандидатом не бывает — см. шапку типа. */
  readonly silenceKind: 'author' | 'gap';
  readonly boundary: BoundaryKind;
  readonly chapterId: string;
  /** `null` — граница глав: тишина принадлежит стыку, а не одной сцене. */
  readonly sceneId: string | null;
}

// ── Клипы ───────────────────────────────────────────────────────────────────

/**
 * Речевой клип: окно в сыром PCM дубля, уложенное на дорожку.
 *
 * `[leadInSamples, numSamples − tailSamples)` — ADR-0003 T7 после `DOC-04`: «на импорте НИЧЕГО
 * не срезается — байты дубля лежат в CAS сырыми, а в take-файл идут ИЗМЕРЕНИЯ. Режет интервал
 * речи тот, кто строит дорожку». Долг №97 читается вместе с этим: `tailSamples` — это ВСЯ
 * хвостовая тишина, включая паузу знака препинания, а не «дрейф провайдера».
 */
export interface PlacedSpeech {
  readonly kind: 'speech';
  /** `speech:<chunkKey>`. Адрес места, не содержимого. */
  readonly clipId: string;
  readonly startSample: Samples;
  readonly endSample: Samples;
  readonly chunkKey: string;
  /** sha256 сырого PCM в CAS; `null` — дубль, собранный не укладкой плана (ADR-0010 §2). */
  readonly pcmSha256: string | null;
  /** Начало окна речи ВНУТРИ сырого PCM: `leadInSamples`. */
  readonly pcmStartSample: Samples;
  /** Конец окна речи внутри сырого PCM: `numSamples − tailSamples`. */
  readonly pcmEndSample: Samples;
}

/**
 * Клип тишины на дорожке речи. Вид и длительность — `TimelineSilence` из `core-model` КАК ЕСТЬ.
 *
 * `boundary`/`chapterId`/`sceneId` — не часть сущности ADR-0001, а физический адрес укладки:
 * ровно то, «чего у `Silence` нет и что Timeline обязан знать» (задание `CP-01` §2.1).
 */
export interface PlacedSilence {
  readonly kind: 'silence';
  /** `silence:<startSample>`. */
  readonly clipId: string;
  readonly silence: TimelineSilence;
  readonly startSample: Samples;
  readonly endSample: Samples;
  readonly boundary: BoundaryKind;
  readonly chapterId: string;
  /** `null` — стык глав. */
  readonly sceneId: string | null;
}

/**
 * Чем заполнен клип режиссуры.
 *
 * ОБЕ ВЕТВИ НЕСУТ `contract` — то, что ОБЪЯВИЛ шаблон (`CP-07`). До этой задачи ассеты знала
 * только порождённая `[img:]`-запись, потому что её alias был единственным, который `compose`
 * разрешал сам (решение владельца `CP-01`, вопрос 8): манифеста у неё нет и быть не может.
 * Теперь манифест есть у ШАБЛОНА, и `still@1` объявляет свой ассет тем же `declareAssets`, что
 * и все прочие, — поэтому особая ветка `resolveAlias` в укладке УДАЛЕНА, а поля `alias` и
 * `assetSha` у порождённой ветви исчезли: alias живёт в `params` (авторская форма, решение
 * владельца `CP-07`, вопрос 2), sha — в `contract.assets` (долг №120).
 */
export type ClipFill =
  | {
      readonly kind: 'record';
      readonly recordId: string;
      readonly filePath: string;
      readonly template: string;
      /**
       * `params` проходят сквозь Timeline ДАННЫМИ и остаются **АВТОРСКИМИ**.
       *
       * *(Решение владельца `CP-07`, вопрос 2, 2026-08-28.)* Alias'ы внутри `params` НЕ
       * подменяются на sha: подмена — это интерпретация шаблона (компилятор решал бы, какое
       * поле есть ссылка на файл), и она ломает AC4-b при переименовании alias'а — сегмент,
       * файлов не менявший, разошёлся бы побайтово. Sha живёт рядом, в `contract.assets`, где
       * у каждого есть РОЛЬ; сопоставить роль/alias с файлом обязан адаптер (`H-01`).
       */
      readonly params: TemplateParams;
      /**
       * Разрешённый scope записи (`readDirection`, `C-05`) — вход формулы seed'а.
       *
       * *(Добавлено: `CP-04`, 2026-08-26, решение владельца 11, вариант «а».)* ADR-0007 §1
       * берёт во вход seed'а `chapterId` и `sceneId` записи; `PlacedRecord.scope` их знает, и
       * до этой строки они терялись при укладке — то есть Timeline терял часть ИДЕНТИЧНОСТИ
       * записи, а `compileIr(timeline, …)` не мог посчитать seed вовсе. Две отвергнутые
       * альтернативы названы ценой: расширить вход `compileIr` списком `PlacedRecord`
       * (форма стадии, названная в задании, разошлась бы с реальной) и выводить scope из
       * `timeline.anchors` (вторая копия резолва scope — хуже любой строки типа).
       *
       * У порождённой `[img:]`-записи scope'а нет: у неё нет и `recordId`, а без него формула
       * не записывается (решение владельца `C-05`, долг №21; `CP-04` решение 1-bis).
       */
      readonly scope: Scope;
      readonly contract: ClipContract;
    }
  | {
      readonly kind: 'generated';
      /** Порождена `expandImg` (`C-04`) из `[img: alias]`; `recordId` у неё нет (ADR-0002 §4). */
      readonly template: 'still@1';
      /** Авторская форма: alias лежит здесь, sha — в `contract.assets` (роль `asset`). */
      readonly params: { readonly asset: string };
      readonly contract: ClipContract;
    };

/**
 * Клип режиссуры: запись `direction/*.yaml` либо порождённая `[img:]`-запись, уложенная в сэмплы.
 *
 * `at`/`duration` — авторское время (`RealizableTimePoint` + `Duration` из `core-model`),
 * `startSample`/`endSample` — физическое. Обе половины лежат рядом намеренно: правки
 * (`O-01`) адресуются к авторской, а рендер читает физическую.
 */
export interface PlacedClip {
  readonly kind: 'clip';
  /** `r:<recordId>` у записи файла, `img:<b:img-alias-n>` у порождённой. */
  readonly clipId: string;
  readonly at: RealizableTimePoint;
  readonly duration: Duration;
  readonly startSample: Samples;
  readonly endSample: Samples;
  readonly z: number;
  /**
   * Позиция якоря `at` в порядке ИСХОДНИКА — авторское поле сортировки (ADR-0007 §5).
   *
   * ПОЧЕМУ НЕ ИНДЕКС ВО ВХОДНОМ МАССИВЕ. Критерий готовности требует, чтобы перестановка
   * входных массивов не меняла Timeline; индекс в массиве от неё зависит по построению.
   * Позиция якоря в прозе — величина ДАННЫХ: она меняется, только когда автор двигает текст,
   * и никогда — от порядка чтения каталога или от измерений дубля.
   */
  readonly sourceOrdinal: number;
  readonly fill: ClipFill;
}

/** Всё, что лежит на дорожке. */
export type TimelineItem = PlacedSpeech | PlacedSilence | PlacedClip;

/**
 * Дорожка Timeline. Семь имён `TRACK_KINDS` (`core-model`), включая директивную `voice`.
 *
 * У `voice` `items` пуст ВСЕГДА, и это не особый случай реализации, а смысл седьмого имени
 * (ADR-0001, RM2 решение владельца 1): запись на ней клипа Timeline не порождает, а питает
 * SpeechPlan.
 */
export interface TimelineTrack {
  readonly kind: TrackKind;
  readonly items: readonly TimelineItem[];
}

// ── Якоря ───────────────────────────────────────────────────────────────────

/** Пространство якоря (ADR-0004 §1). `r:` до Timeline не доезжает: он резолвится в чужой `at`. */
export type AnchorSpace = 'w' | 'b' | 'sc' | 'ch';

/**
 * Момент якоря в сэмплах — ЕДИНСТВЕННЫЙ выход разрешения `anchorId` во время.
 *
 * `startSample === endSample` у бита: бит — это ТОЧКА, а не интервал (ADR-0002 §2: маркер
 * `[beat:]` текста не несёт). У `w:` интервал — объединение интервалов произнесённых слов
 * токена (ADR-0004 §5). У `sc:`/`ch:` — область, и её конец есть то, что означает `until`
 * на scope-якоре (ADR-0004 §7).
 */
export interface AnchorTime {
  readonly anchorId: AnchorId;
  readonly space: AnchorSpace;
  readonly startSample: Samples;
  readonly endSample: Samples;
}

// ── Субтитры ────────────────────────────────────────────────────────────────

/**
 * Слово внутри группы субтитров: то, что рисуется, и то, что подсвечивается.
 *
 * `surface`, а не `spoken`: в субтитр идёт display-форма (ADR-0004 §5, `TokenNode`), поэтому
 * `[say: 200 | two hundred]` показывает `200`, а произносит «two hundred».
 *
 * Подсветке РАЗРЕШЕНО схлопнуться в 0 сэмплов (ADR-0003 «Субтитры»: «33 мс при 30 fps
 * физически незаметны») — минимума у неё нет, в отличие от группы.
 */
export interface CaptionGroupToken {
  readonly anchorId: AnchorId;
  /**
   * Display-форма токена. Может нести приклеенный непроизносимый `absent`-сосед справа
   * (решение владельца 2026-08-26, вопрос 4 (г)): `«waiting»` + `.` печатается одной строкой.
   */
  readonly surface: string;
  readonly startSample: Samples;
  readonly endSample: Samples;
  /**
   * Токен помечен `[emph]` (ADR-0002 §2 — чисто визуальный маркер).
   *
   * SCOPE МАРКЕРА ВРЕМЕННЫЙ, и это единственное место, где он назван: «следующий токен того же
   * чанка» (решение владельца 2026-08-26, вопрос 6). Настоящий scope выбирает `CP-05` —
   * дрейф roadmap §11.2 строка 16, решение `C-02` («в AST scope у `[emph]` нет»); долг №128.
   */
  readonly emph: boolean;
}

/**
 * Группа субтитров — единица caption-трека (ADR-0001: «привязки → группы»).
 *
 * `startSample`/`endSample` — края ПЕРВОГО и ПОСЛЕДНЕГО токена группы, буквально (**T10**).
 * Ни сдвига, ни растяжения, ни интерполяции: компилятор не выдумывает время (норма `V-05`).
 */
export interface CaptionGroup {
  readonly startSample: Samples;
  readonly endSample: Samples;
  readonly tokens: readonly CaptionGroupToken[];
  /** ОДНА строка, слова через пробел, без переносов (решение владельца 2026-08-23). */
  readonly text: string;
  /** Речевой клип, внутри которого группа лежит целиком. Границу клипа она не пересекает. */
  readonly chunkKey: string;
  readonly sceneId: string;
  /** Группа короче `minGroupDurationFrames` при максимуме слов: принята, но записана в отчёт. */
  readonly belowMinimum: boolean;
}

/** Строка отчёта о группе короче минимума. Печатает `L-01`; компиляцию она не роняет. */
export interface CaptionShortGroup {
  readonly startSample: Samples;
  readonly endSample: Samples;
  readonly text: string;
  readonly tokens: number;
  /** Длина группы в сэмплах и порог, с которым она сравнивалась, — рядом, чтобы не считать. */
  readonly durationSamples: Samples;
  readonly minDurationSamples: Samples;
}

/**
 * Отчёт стадии субтитров (ADR-0003 «Субтитры»: «с записью в отчёт сборки, а не сдвигает
 * соседей»). Печатает `L-01`.
 */
export interface CaptionReport {
  readonly short: readonly CaptionShortGroup[];
  /**
   * Сколько клипов кончилось ОДНОСЛОВНЫМ огрызком (набивка 3 + 1), поправка владельца П2.
   *
   * Данные для чтения (в) — балансировки хвоста (`3 + 1` → `2 + 2`), отложенной решением
   * владельца до пересмотра после первого ролика (**X3**, долг №124). Само число компиляцию
   * не меняет: это счётчик, а не порог.
   */
  readonly tailSingletons: number;
}

// ── Сегменты и таблица разрезов ─────────────────────────────────────────────

/**
 * Клип, пересекающий точку разреза: то, что печатает таблица и называет ошибка **R6**.
 *
 * `at` ЛЕЖИТ СТРОКОЙ, А НЕ `RealizableTimePoint`, И ЭТО НЕ ПОТЕРЯ ТИПА. Величина здесь одна
 * работа — быть прочитанной человеком в отчёте сборки: автору, у которого сегментов меньше,
 * чем он ждал, нужно имя якоря (`b:reveal`), а не разбор объединения. Форма ровно та же, что
 * печатает `dumpTimeline` для клипа, и берётся она одной функцией (`atLabel`, `dump.ts`), а не
 * второй копией правила.
 */
export interface CrossingClip {
  readonly clipId: string;
  readonly track: TrackKind;
  /** Авторское время `at` в форме дампа: `b:reveal` либо `mediaTime:<sha>`. */
  readonly at: string;
  readonly startSample: Samples;
  readonly endSample: Samples;
}

/**
 * Почему кандидат стал разрезом или не стал. ЗАКРЫТЫЙ union — пятая причина невыразима.
 *
 * Порядок проверок ФИКСИРОВАН (ADR-0008): (а) ничто не пересекает → (б) тишина ненулевой длины
 * → (в) обе части не короче порога. Поэтому у отклонённого кандидата причина ровно одна и
 * всегда ПЕРВАЯ несошедшаяся: «пересечён И короток» в таблице не появляется, и автор чинит по
 * одной причине за раз.
 *
 * `chapter-forced` — причина РАЗРЕЗА, а не отказа: граница главы режет безусловно (**V4**),
 * проверка (в) на ней не применяется (решение владельца 2026-08-26, вопрос 2 (а)). Порог —
 * эвристика стоимости рендера, глава — авторская единица, и сегмент дешевле 1.86 с на сборку
 * — цена, названная явно.
 */
export type CutReason =
  /** Кандидат `CP-01` на границе абзаца или внутри него: по ADR-0008 кандидат — граница СЦЕНЫ. */
  | 'not-scene-boundary'
  /** (а) через точку разреза идёт клип визуальной дорожки. Список — в `crossedBy`. */
  | 'crossed-by-clips'
  /** (в) закрываемый сегмент короче `minSegmentDurationFrames`. */
  | 'left-too-short'
  /** (в) остаток до следующей границы главы (или до конца дорожки) короче порога. */
  | 'right-too-short'
  /** Разрез на границе главы: безусловен по **V4**, проверка (в) не применялась. */
  | 'chapter-forced';

/** Причины, по которым кандидат МОЖЕТ быть отклонён. `chapter-forced` среди них нет. */
export type RejectReason = Exclude<CutReason, 'chapter-forced'>;

/**
 * Строка таблицы «кандидат → что с ним стало» (ADR-0003 T8: «отчёт сборки печатает таблицу
 * кандидатов на разрез / стало разрезами / почему отклонён»).
 *
 * ОТКЛОНЁННЫЕ НЕ ИСЧЕЗАЮТ. В таблице лежат ВСЕ кандидаты `CP-01`, включая абзацные: «сегментов
 * оказалось меньше, чем я ждал» — вопрос, на который обязан отвечать отчёт, а не чтение кода.
 */
export interface CutRow {
  /** Начало клипа тишины — тот же сэмпл, что у `CutCandidate.atSample`. */
  readonly atSample: Samples;
  /** Где встал (или встал бы) разрез: `atSample + durationSamples`, конец gap'а (**T6**). */
  readonly cutSample: Samples;
  readonly boundary: BoundaryKind;
  readonly silenceKind: 'author' | 'gap';
  readonly durationSamples: Samples;
  readonly decision: 'cut' | 'rejected';
  /** `null` — обычный сценный разрез: он состоялся, потому что все три проверки сошлись. */
  readonly reason: CutReason | null;
  /** Клипы, идущие СКВОЗЬ разрез. Непуст только при `crossed-by-clips` и при ошибке R6. */
  readonly crossedBy: readonly CrossingClip[];
  /**
   * Длина закрываемого сегмента: от начала текущего сегмента до разреза.
   *
   * `null` у кандидатов `not-scene-boundary`: проверка (в) на них не выполнялась вовсе, и
   * напечатать число значило бы сделать вид, что его сравнивали с порогом.
   */
  readonly leftSamples: Samples | null;
  /**
   * Длина правой части: от разреза до **следующей границы ГЛАВЫ**, а если её нет — до конца
   * дорожки (поправка владельца П1, 2026-08-26).
   *
   * ПОЧЕМУ НЕ «ДО КОНЦА ДОРОЖКИ» ВСЕГДА. Граница главы — разрез по построению (**V4**), и
   * мерить правую часть сквозь неё значило бы отвергать законные сценные разрезы перед
   * короткой главой: остаток «до конца ролика» у них велик, а реальный сегмент справа кончится
   * на ближайшей главе. Инвариант от поправки не меняется — «каждый сегмент ≥ порога, кроме
   * вынужденных главой», — и новых причин отказа не появляется.
   */
  readonly rightSamples: Samples | null;
}

/**
 * Итог сегментации в форме, которую печатает отчёт сборки (`L-01`) и читает зонд владельца.
 *
 * `minSegmentSamples` ЛЕЖИТ ЗДЕСЬ ОДИН РАЗ, а не в каждой строке: величина одна на прогон, и
 * второй её копии в репозитории быть не должно. В дампе она печатается и в шапке блока, и в
 * строках `*-too-short` — там, где автор сравнивает её с двумя длинами (поправка владельца П3).
 */
export interface CutTable {
  /** Все кандидаты `CP-01` в порядке дорожки. */
  readonly rows: readonly CutRow[];
  /** Сколько сегментов получилось. Всегда `cutsAccepted + 1`. */
  readonly segments: number;
  readonly cutsAccepted: number;
  /** Сколько кандидатов отклонено по каждой причине. Ключи закрыты типом. */
  readonly rejectedByReason: Readonly<Record<RejectReason, number>>;
  /** `minSegmentDurationFrames` в сэмплах: `frameStartSample(grid, n)` — ДЛИНА, не позиция. */
  readonly minSegmentSamples: Samples;
}

/**
 * Сегмент — производная единица рендера и кэша (ADR-0008): максимальный пробег подряд идущих
 * сцен, между которыми ничто не пересекает границу.
 *
 * КАДРОВ ЗДЕСЬ НЕТ, И ЭТО ТО ЖЕ РЕШЕНИЕ, ЧТО У `CP-01` (вопрос 1 (в)). `d_i`, `A_i`, `δ_i`
 * (ADR-0003 T6) считает `CP-04`: они требуют квантования, а T3 велит квантовать «всегда
 * относительно начала своего сегмента» — то есть сначала должен существовать сегмент. Здесь
 * он и появляется, но как РАЗБИЕНИЕ ДОРОЖКИ В СЭМПЛАХ плюс `L_i`, из которого `CP-04` посчитает
 * остальные три величины.
 *
 * ВТОРОГО `Segment` В РЕПОЗИТОРИИ НЕТ. `SegmentBounds`/`SegmentPlacement`
 * (`core-model/time/interval.ts`, `C-01`) — это КАДРЫ и квантор T4 на паре «сегмент, клип»,
 * то есть вход `CP-04`; пересечения по полям у них нет ни одного.
 */
export interface Segment {
  /**
   * `seg:<id первой сцены сегмента>` (решение владельца 2026-08-26, вопрос 1).
   *
   * ПОРЯДКОВЫЙ НОМЕР ЗАПРЕЩЁН ПО СМЫСЛУ: добавление сцены выше по тексту переименовало бы все
   * сегменты ниже, то есть дало бы промах кэша «из ниоткуда» — ровно то, что запрещают T6 и
   * AC3. Имя первой сцены от текста ниже не зависит и меняется только вместе с ГОЛОВОЙ
   * сегмента, а у сегмента со сменившейся головой и содержимое другое: промах честный.
   *
   * УНИКАЛЬНОСТЬ НЕ ПРЕДПОЛОЖЕНА, А ПРОВЕРЕНА: `parseSource` регистрирует `sc:<id>` в
   * общедокументном реестре якорей и падает на повторе («живые id уникальны», ADR-0004 §4),
   * а сегменты — непересекающиеся пробеги сцен, значит первая сцена у каждого своя.
   * `chapterId/sceneId` в имени поэтому не нужен.
   */
  readonly segmentId: string;
  readonly startSample: Samples;
  readonly endSample: Samples;
  /** Глава, которой сегмент принадлежит ЦЕЛИКОМ (`границы сегментов ⊇ границы глав`, V4). */
  readonly chapterId: string;
  /** Id сцен пробега, подряд и в порядке прозы. Пуст не бывает. */
  readonly sceneIds: readonly string[];
  /**
   * `L_i` по ADR-0003 T6: сумма НОМИНАЛЬНЫХ длин клипов дорожки речи внутри сегмента —
   * речь + `[pause:]` + gap, **БЕЗ поправки** `δ`.
   *
   * СЧИТАЕТСЯ СУММИРОВАНИЕМ, А НЕ ВЫЧИТАНИЕМ `endSample − startSample`, хотя сегодня эти два
   * числа равны: `boundary-correction` в `CP-01`/`CP-03` не порождается, и разность совпадает
   * с суммой. Ассерт `Σ nominalSamples == durationSamples` содержателен только у суммы —
   * у разности он был бы тавтологией. Когда `CP-04` допишет клипы поправки, равенство
   * перестанет быть тождеством, а формула останется той же.
   */
  readonly nominalSamples: Samples;
  /**
   * Хвостовой gap сегмента — ТОТ ЖЕ объект, что лежит на дорожке, а не его копия.
   *
   * `null` только у последнего сегмента: по T6 gap принадлежит предшествующему сегменту, то
   * есть «у каждого сегмента, кроме последнего, есть непустой хвостовой gap».
   */
  readonly tailGap: PlacedSilence | null;
}

// ── Timeline ────────────────────────────────────────────────────────────────

/** Физическая модель произведения (ADR-0001). Всё время — в сэмплах. */
export interface Timeline {
  readonly projectSampleRate: number;
  /** `L` — длина дорожки речи. Она же длина ролика до добивки T5 (`CP-05`). */
  readonly durationSamples: Samples;
  /** Семь дорожек в порядке `TRACK_KINDS`. */
  readonly tracks: readonly TimelineTrack[];
  /** Точки, где сегментация вправе поставить разрез (T6). Отбор — `CP-03`. */
  readonly cutCandidates: readonly CutCandidate[];
  /**
   * Тотальное разбиение `[0, L)` на сегменты (`CP-03`, ADR-0008). Пусто не бывает: в дорожке
   * без единого речевого клипа `compose` не доходит сюда — падает `speechTrack`.
   */
  readonly segments: readonly Segment[];
  /** Таблица «кандидат → разрез либо причина отказа» (`CP-03`). Печатает `L-01`. */
  readonly cutTable: CutTable;
  /** Якорь → сэмпл, в порядке исходника. Вход субтитров (`CP-02`) и правок (`O-01`). */
  readonly anchors: readonly AnchorTime[];
  /**
   * Группы субтитров в порядке исходника (`CP-02`).
   *
   * ОТДЕЛЬНОЕ ПОЛЕ, А НЕ ЭЛЕМЕНТЫ ТРЕКА `caption` (решение владельца 2026-08-26, вопрос 2):
   * группа — производное от ПРИВЯЗОК (ADR-0001, «привязки → группы»), а не режиссура. На треке
   * `caption` лежат клипы шаблонов (`captionEmphasis@1`) с порядком `(z, sourceOrdinal,
   * clipId)`; у группы нет ни `z`, ни `sourceOrdinal`, и подмешивание её туда обессмыслило бы
   * сортировку трека. Цена решения названа: субтитры живут в двух местах.
   */
  readonly captionGroups: readonly CaptionGroup[];
  /** Отчёт стадии субтитров: короткие группы и хвостовые огрызки. Печатает `L-01`. */
  readonly captionReport: CaptionReport;
}

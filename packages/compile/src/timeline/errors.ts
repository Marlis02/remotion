// Ошибка компиляции Timeline (`CP-01`).
//
// ОШИБКА НАЗЫВАЕТ ПРАВИЛО, А НЕ СЛЕДСТВИЕ — то же решение, что у `TimeModelError` (`C-01`),
// `ModelError` (`C-05`), `AudioError` (`M-03`) и `VoiceError` (`V-01`).
//
// ОШИБКА НЕСЁТ ПЕРЕЧЕНЬ, А НЕ ПЕРВУЮ НАХОДКУ. Довод — тот же, что у `AssetCatalogError`
// (`M-02`): проблемы компиляции приходят пачками (не сгенерированы дубли целой главы — это
// десяток `chunkKey`, а не один), и отказ на первой заставлял бы чинить их по одной,
// перезапуская сборку. Список лежит ПОЛЕМ, потому что печатает его CLI, а не разбирает
// обратно из текста сообщения.

/** Правила, на которые ссылаются ошибки компиляции Timeline. */
export type CompileRule =
  /**
   * Источник истины физического времени — сэмплы `projectSampleRate` (ADR-0003 T1).
   *
   * Под этим именем ходит ровно одно нарушение: дубль снят на частоте, не равной частоте
   * проекта. Ресемплировать его компилятор не вправе — байты в CAS сырые и оплачены.
   */
  | 'ADR-0003 T1'
  /**
   * Дорожка речи непрерывна и разбита тотально (`Σ клипов == L`, стыки без дыр и перекрытий).
   *
   * Под этим именем ходит и вторая половина строки **T7** реестра: «после импорта дубля ВСЯ
   * межчанковая тишина — явные клипы `Silence`». Проверяется это одним и тем же ассертом:
   * если между речевыми клипами осталась неучтённая тишина, разбиение перестаёт быть тотальным.
   */
  | 'ADR-0003 T5'
  /**
   * Кандидат на разрез — точка, где стоит клип тишины ненулевой длины.
   *
   * *(Решение владельца 2026-08-26, вопрос 10: вида `author` ИЛИ `gap`. Буква T6 называет
   * только `gap`; кандидат в правку ADR — в отчёте `CP-01` §«Кандидаты в правку ADR».)*
   */
  | 'ADR-0003 T6'
  /**
   * Интервал речи дубля — `[leadInSamples, numSamples − tailSamples)` (`V-04`, долг №97).
   *
   * Под этим именем ходит весь-тихий дубль: `leadIn + tail ≥ numSamples` (решение владельца
   * 2026-08-26, вопрос 4 — долг №99).
   */
  | 'ADR-0003 T7'
  /** `[pause: Nms]` переопределяет дефолт движка в своей точке, а не складывается с ним. */
  | 'ADR-0003 T8'
  /**
   * Граница главы обязана быть границей сегмента (Charter **V4**).
   *
   * Разрез по T6 требует тишины **ненулевой** длины, поэтому авторская пауза нулевой длины на
   * границе главы делает V4 невыполнимым (решение владельца 2026-08-26, поправка П1).
   */
  | 'Charter V4'
  /** Ссылка на якорь не разрешается: такого живого якоря нет. */
  | 'ADR-0004 §9'
  /**
   * Компилятор не выдумывает время: `absent`-привязка под якорем, на который ссылается
   * запись, — ошибка компиляции, а не ноль и не интерполяция (**V8**, ADR-0010 §5).
   */
  | 'ADR-0010 §5 (V8)'
  /** Форма take-файла: строгий читатель компиляции (ADR-0010 §2). */
  | 'ADR-0010 §2'
  /** `[img: alias]` и его ассет: неизвестный alias — ошибка (ADR-0002 §4). */
  | 'ADR-0002 §4'
  /**
   * Субтитры (`CP-02`): группа из 1–3 слов одной строкой, время — края крайних токенов.
   *
   * Под этим именем ходят три нарушения: `absent` под ПРОИЗНОСИМЫМ словом (показать нечего, а
   * выдумать время нельзя — **V8**), непроизносимый `absent` первым в чанке (приклеивать не к
   * чему) и токен, чей интервал не лежит целиком ни в одном речевом клипе.
   */
  | 'ADR-0003 «Субтитры (M6)»'
  /**
   * Сегментация (`CP-03`): кандидат — граница СЦЕНЫ, разрез — там, где ничто не пересекает.
   *
   * Под этим именем ходит одно нарушение, и оно про сам сегментатор, а не про исходник:
   * структурный кандидат не совпал ни с одним стыком областей сцен, то есть выпал бы из
   * таблицы молча. Нарушения ПРОИЗВЕДЕНИЯ ходят под своими именами: пересечение границы главы
   * — `Charter V4` (**R6**), нулевая тишина на структурной границе — `ADR-0003 T8`.
   */
  | 'ADR-0008 «Сегментация (механика V4)»'
  /**
   * Контракт шаблона (`CP-07`): вызов обязан разобраться, найтись в реестре и пройти схему.
   *
   * Под этим именем ходят ШЕСТЬ нарушений — все с одним свойством: компилятор НЕ ВЫДУМЫВАЕТ.
   * Имя вызова не разбирается; шаблона нет в реестре; `params` не проходят `paramsSchema`
   * спека; объявленный `declareAssets` alias не имеет записи в каталоге; объявленной
   * `declareFonts` роли не находится шрифт; у записи есть И `until`, И объявленная
   * длительность (решение владельца `CP-07`, вопрос 4: автор противоречит сам себе).
   *
   * ОТДЕЛЬНОЕ ИМЯ ОТ `ADR-0002 §4`, хотя alias порождённой `[img:]`-записи теперь ходит
   * здесь же: §4 говорит про САХАР (во что разворачивается `[img:]`), а это правило — про
   * КОНТРАКТ (что шаблон обязан предъявить). После `CP-07` alias `[img:]` разрешается тем же
   * путём, что все прочие, — через `declareAssets` спека `still@1`, — и особой ветки больше нет.
   */
  | 'ADR-0008 «Декларация ресурсов шаблона»'
  /**
   * Версия реестра шаблонов в профиле разошлась с реестром, поданным на вход (**K6**).
   *
   * `templateRegistryVersion` — единственное имя в allowlist'е K6 (`S-02-fix`): версия реестра
   * есть намерение автора, а не измеренное окружение. До `CP-07` за этим именем не стояло
   * ничего проверяемого — профиль адресовал содержимое, которого стадия не видела. Теперь
   * стоит: расхождение — ошибка ДО первой записи, потому что все дальнейшие ответы («какой
   * шаблон», «какая схема», «какие purposes») давал бы не тот реестр, который назвал автор.
   */
  | 'ADR-0006 §5 (K6)';

/** Одна проблема компиляции: куда идти чинить и что именно не сошлось. */
export interface CompileProblem {
  /** Адрес: `chunkKey`, якорь, `recordId` с файлом — то, что человек найдёт глазами. */
  readonly address: string;
  readonly message: string;
}

/** Нарушение правила компиляции Timeline: несёт имя правила и ПЕРЕЧЕНЬ проблем. */
export class CompileError extends Error {
  readonly rule: CompileRule;
  readonly problems: readonly CompileProblem[];

  constructor(rule: CompileRule, context: string, problems: readonly CompileProblem[]) {
    const list = problems.map((problem) => `  ${problem.address}: ${problem.message}`).join('\n');
    super(`${rule}: ${context}, проблем — ${String(problems.length)}:\n${list}`);
    this.name = 'CompileError';
    this.rule = rule;
    this.problems = problems;
  }
}

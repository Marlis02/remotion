// Ошибка IR-стороны (`CP-04`).
//
// ПОЧЕМУ НЕ `CompileError`. Он живёт в `timeline/errors.ts`, а зона `render-ir/**` не
// импортирует `timeline/**` (**M5**, ADR-0009). Это не обход правила, а его смысл: «IR не
// знает Timeline» обязано держаться на границе, а не на честном слове, и ради общего класса
// ошибок границу не открывают.
//
// ПОЧЕМУ НЕ `TimeModelError`. Он бы подошёл — правила здесь ровно те же, ADR-0003, — но его
// перечень `TimeRule` не содержит T6, а дописать строку значило бы править `core-model`
// сверх разрешённого этой задачей (один новый файл типов, ADR-0009 стрелка рендерера).
//
// ОШИБКА НАЗЫВАЕТ ПРАВИЛО, А НЕ СЛЕДСТВИЕ — то же решение, что у `TimeModelError` (`C-01`),
// `ModelError` (`C-05`), `CompileError` (`CP-01`), `AudioError` (`M-03`), `VoiceError` (`V-01`).

/** Правила, на которые ссылаются ошибки IR-стороны. */
export type RenderIrRule =
  /**
   * Квантование позиций — segment-relative (ADR-0003 T3).
   *
   * Под этим именем ходят: клип вне границ своего сегмента (он не мог там оказаться —
   * `CP-03` режет только там, где ничто не пересекает границу) и группа субтитров,
   * пересекающая границу сегмента.
   */
  | 'ADR-0003 T3'
  /**
   * Замкнутая арифметика `S`/`L_i`/`d_i`/`A_i`/`δ_i` (ADR-0003 T6).
   *
   * Под этим именем ходят все четыре свойства T6: `d_i ≥ 1`, `δ_i ∈ [0, S)`,
   * `Σ A_i ≤ frameStartSample(F)` с разницей `< n`, а также рекурренты `f_{i+1} = f_i + d_i`
   * и `a_{i+1} = a_i + A_i`.
   */
  | 'ADR-0003 T6'
  /**
   * `minSegmentDurationFrames` — поле `compileProfile`, а не рекомендация (ADR-0008, M10).
   *
   * Долг №132: порог предъявляется сегментацией в СЭМПЛАХ, а рендер считает КАДРЫ. Здесь
   * стоит проверка в кадрах — там, где `d_i` наконец существует.
   */
  | 'ADR-0008 minSegmentDurationFrames'
  /**
   * Список файлов запроса совпадает с тем, что объявили спеки клипов (**R3**, `CP-07`).
   *
   * Под этим именем ходит ОДНО нарушение и оно про сборку, а не про проект: `assets`/`fonts`
   * сегмента разошлись с объединением тех же полей его клипов — в любую из двух сторон
   * (поправка владельца П2: односторонний ассерт пропустил бы «лишний файл в запросе»).
   * Ошибки ПРОИЗВЕДЕНИЯ — alias без записи, шрифт роли — ходят под `ADR-0008 «Декларация
   * ресурсов шаблона»` в `CompileError`, со списком и адресом записи.
   */
  | 'ADR-0008 «Декларация ресурсов шаблона»';

/** Нарушение правила IR-стороны: несёт имя правила, а не только текст. */
export class RenderIrError extends RangeError {
  readonly rule: RenderIrRule;

  constructor(rule: RenderIrRule, reason: string) {
    super(`${rule}: ${reason}`);
    this.name = 'RenderIrError';
    this.rule = rule;
  }
}

// Синтетические спеки шаблонов для тестов `compile` (`CP-07`).
//
// ЗАЧЕМ ОНИ ВООБЩЕ НУЖНЫ. Пять шаблонов `fixtures/minimal` не требуют случайности — у всех
// `purposes: []` (измерение `TS-01` §5 п. 2). Значит на фикстуре карта `seeds` ПУСТА у каждого
// клипа, и утверждение **D1** («ни один вход seed'а не зависит от позиции, `params` и
// сегментации») осталось бы без предмета: пустое множество не меняется ни от чего. Подогнать
// прежнее ожидание «четыре seed'а» под «ноль seed'ов» значило бы объявить охранника зелёным
// ровно там, где он перестал что-либо охранять (`TS-01`, находка 9: «D1 обязан быть ПЕРЕЧИТАН,
// а не подогнан»). Поэтому D1 и D2 проверяются на спеке, который случайность ПРОСИТ.
//
// СПЕКИ СТРОЯТСЯ ИЗ НАСТОЯЩИХ, А НЕ ПИШУТСЯ ЗАНОВО. `zod` в `compile` не резолвится (пакет
// его не объявляет), да и второй экземпляр схемы `params` был бы вторым контрактом того же
// шаблона. Поэтому берётся спек `templates-spec` и меняется РОВНО ТО, ради чего он здесь:
// имя и `purposes`. Схема, декларации и остальной манифест — те же объекты.
//
// ФИКСТУРА НЕ ТРОГАЕТСЯ НИ СИМВОЛОМ: синтетическая режиссура пишется во временный каталог
// прогона (`ProjectExtra.direction`), реестр подаётся входом (`ProjectExtra.specs`).

import { still1, type AnyTemplateSpec, type TemplateManifest } from '@vpe/templates-spec';

/**
 * Копия спека под другим именем и с другими `purposes`.
 *
 * @param source спек-донор: его `paramsSchema` и обе декларации переиспользуются как есть.
 * @param templateId новое имя — реестр отвергает вторую регистрацию той же пары (id, версия).
 * @param purposes перечень seed'ов узла (ADR-0007 §1), которого донор не объявляет.
 */
export function specWithPurposes(
  source: AnyTemplateSpec,
  templateId: string,
  purposes: readonly string[],
): AnyTemplateSpec {
  const manifest: TemplateManifest = {
    ...source.manifest,
    templateId,
    purposes: [...purposes],
  };
  return { ...source, templateId, manifest };
}

/**
 * `jitter@1` — `still@1` с одним объявленным `purpose`.
 *
 * Схема `params` донора (`{asset, fit?}`) переиспользуется намеренно: тесту нужен ЗАКОННЫЙ
 * вызов, отличающийся от фикстурного только тем, что шаблон просит случайность. Значит
 * запись фикстуры превращается в него подменой ОДНОЙ строки — `template: "still@1"` →
 * `"jitter@1"`, — и всё остальное в проекте остаётся дословно тем же.
 */
export const jitter1: AnyTemplateSpec = specWithPurposes(still1, 'jitter', ['jitter']);

/**
 * `still@1`, который ПРОСИТ случайность, — негативная фикстура для порождённой `[img:]`.
 *
 * Такой шаблон поставить на `[img:]`-запись нельзя: у неё нет `recordId` (ADR-0007 §1 — id
 * выдаёт CLI и записывает в `direction/*.yaml`), а формула seed'а без него не записывается.
 * Компилятор обязан ОТКАЗАТЬ, а не выдумать `recordId` (долг №136, условие открытия).
 */
export const stillWithPurposes: AnyTemplateSpec = specWithPurposes(still1, 'still', ['jitter']);

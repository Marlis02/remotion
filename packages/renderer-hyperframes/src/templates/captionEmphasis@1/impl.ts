// Реализация `captionEmphasis@1` — ВИД ПОЛОСЫ СУБТИТРОВ и эмфаза активного слова.
// Спек: `templates-spec/src/templates/captionEmphasis@1/spec.ts`.
//
// ═══ ЧТО ЭТОТ ШАБЛОН ПЕРЕСТАЛ ДЕЛАТЬ В `H-07` (2026-08-31, решение владельца) ═══
// ~~Он оформлял ВСЮ полосу: плашку, позицию, кегль, межстрочный, цвет текста.~~ Раскладка
// полосы переехала в [`composition/runtime.js`](../composition/runtime.js) и стала свойством
// ТРЕКА субтитров — той же логикой, что и видимость групп (долг №185). Причина названа
// владельцем по картинке `H-06`: клип эмфазы есть в МЕНЬШИНСТВЕ сегментов, и там, где его
// нет, полоса рисовалась браузерным умолчанием — мелко, чёрным, в левом верхнем углу. Держать
// вид всей полосы на клипе значило держать его на исключении.
//
// ═══ И ЧТО ОН СНОВА ДЕЛАЕТ ПОСЛЕ `CAPTION-01` (2026-09-11) — НО ИНАЧЕ ═══
// Владелец захотел настраиваемые субтитры: шрифт, кегль, фон (плашка / полупрозрачная / без
// плашки), цвет текста, цвет активного слова, обводку, тень, положение. Всё это — раскладка
// полосы, то есть то, что `H-07` отсюда увёз. **Решение, сохраняющее оба требования:
// ЗНАЧЕНИЯ подаёт клип, а ПРАВИЛА по-прежнему строит трек.** Шаблон кладёт в
// `window.__VPE_CAPTION_BAND` плоский набор своих `params`, а `runtime.js` накладывает его
// поверх УМОЛЧАНИЯ КАНАЛА, которое там и осталось. Сегмент без клипа получает ровно то, что
// получал до этой задачи, — то есть решение `H-07` не отменено ни в одну сторону.
//
// **ПОЧЕМУ ЭТО РАБОТАЕТ БЕЗ ЕДИНОГО ДОГОВОРА О ПОРЯДКЕ.** `mount` клипов исполняется в цикле
// `IR.clips`, а слой `#captions` и его правила `runtime.js` строит ПОСЛЕ цикла — то есть
// объект настроек заведомо на месте к моменту, когда его читают. Это то же самое свойство
// порядка, из-за которого шаблон не вправе трогать узлы `#captions` руками (ниже), только с
// обратным знаком: данные положить МОЖНО, узлы найти — НЕТ.
//
// **ЗА ШАБЛОНОМ ОСТАЛОСЬ ТРИ ПУНКТА, И ТРЕТИЙ — ВЫНУЖДЕННО.**
//   1. **ЭМФАЗА АКТИВНОГО СЛОВА** — начертание (ось `wght` вариативного шрифта, `params.weight`)
//      плюс акцентный цвет (`params.activeColor`). Не только жирность: `PRACTICE` (решение
//      владельца `H-07`) — на телефоне жирность одна не читается.
//   2. **ЗНАЧЕНИЯ РАСКЛАДКИ ПОЛОСЫ** — `CAPTION_BAND_KEYS` ниже, подаются данными.
//   3. **`font-family` полосы.** Семейство знает ТОЛЬКО тот, у кого есть ссылка на шрифт
//      (`ctx.fonts` + `ctx.fontOf`), а у трека субтитров канала шрифта нет ни в IR, ни в
//      профиле. Отсюда следствие, названное вслух: сегмент БЕЗ клипа эмфазы получает полосу
//      на месте, в нужном кегле и на плашке, но системным шрифтом. Долг **№207**, адрес —
//      «поле роли шрифта в профиле».
//
// **ЭТОТ ШАБЛОН ОФОРМЛЯЕТ `#captions`, А НЕ СВОЙ `host`** (решение владельца `H-06`, развилка
// «о», вариант о1). Основание — `runtime.js` дословно: субтитры он рисует САМ, отдельным
// слоем. Рисовать свою вторую полосу поверх уже нарисованной значило бы две полосы в кадре;
// поэтому шаблон дотягивается до чужого слоя — поимённо, до одного, и это записано охранником
// формы DOM в `test/templates.test.ts` (поправка владельца П1-а).
//
// **ОФОРМЛЕНИЕ — ИНЪЕКЦИЕЙ `<style>`, И ЭТО НЕ УКРАШЕНИЕ, А ЕДИНСТВЕННАЯ ИСПОЛНИМАЯ ФОРМА.**
// ИЗМЕРЕНО (`H-06`, живой гейт): `mount` клипа исполняется в цикле клипов `runtime.js`, а слой
// `#captions` тот же файл создаёт ПОСЛЕ цикла — то есть на момент монтирования элемента ещё
// нет, и императивная простановка стилей падала «оформлять нечего». Правила CSS от порядка не
// зависят: они применятся к элементам, которые появятся позже. Это и есть причина, по которой
// шаблон не трогает узлы руками.
//
// **ВИДИМОСТЬ ГРУПП — НЕ ЗДЕСЬ** *(решение владельца `H-06`, вариант R2).* Её держит сам
// рендерер по атрибутам `data-*`, которые ставит `runtime.js` (измерение `H-06`, находка Н6,
// долг №185 закрыт `FIX-01`). Шаблон отвечает за ВНЕШНИЙ ВИД эмфазы, трек — за ВРЕМЯ.
//
// **ДВА ОКНА, А НЕ ОДНО, И В ЭТОМ ВСЯ РАЗВЯЗКА `H-07`.** Шаблон кладёт ПАЛИТРУ на корень
// документа на СВОЁ окно `[frameStart, frameEnd)`; трек на окно `token.highlight` каждого
// слова подменяет слову обе переменные на `inherit`, то есть открывает его наследованию.
// Красится ровно пересечение: активное слово в кадре, где клип эмфазы жив. Ни одна из сторон
// не знает чужих чисел — общий у них только ПАРА ИМЁН переменных, и она объявлена здесь и
// прочитана правилом полосы в `runtime.js`.
//
// **РАЗНИЦА МЕЖДУ ПАЛИТРОЙ И НАБОРОМ ПОЛОСЫ — В ОКНЕ, И ОНА НАЗВАНА.** Палитра едет ТАЙМЛАЙНОМ
// и живёт ровно на окне клипа. Набор полосы кладётся ОДИН РАЗ при монтировании и действует на
// ВЕСЬ сегмент: полоса одна, и менять её кегль в середине сегмента нечем — правило `<style>`
// у трека одно. Это ограничение, а не оплошность; оно записано долгом.
//
// ИДЕМПОТЕНТНОСТЬ ОБЯЗАТЕЛЬНА (поправка владельца П4): клипов `captionEmphasis@1` в сегменте
// может быть несколько (у каждого своё окно эмфазы), а полоса одна. Признак — `id` самого
// элемента `<style>`: вторая инъекция нашла бы его и не стала бы удваивать правила. Набор
// полосы подчиняется тому же правилу и по той же причине: ПЕРВЫЙ клип побеждает.
//
// **СЕМЕЙСТВО ШРИФТА НЕ НАЗЫВАЕТСЯ ЗДЕСЬ** — ровно по той же причине, что и в спеке: шрифт
// канала выбирает владелец (долг №13). Шаблон спрашивает РОЛЬ (`params.font`, умолчание —
// `caption`) у `ctx.fonts` и берёт семейство у `ctx.fontOf` — то есть у проекта. Вписанное
// сюда семейство уехало бы в `engineFingerprint` с первым же гейтом.
//
// ЧИСЛА УМОЛЧАНИЯ РАСКЛАДКИ ЗДЕСЬ ПО-ПРЕЖНЕМУ НЕ ЖИВУТ: они в `runtime.js`. Здесь живут
// только два умолчания, принадлежащие САМОЙ ЭМФАЗЕ, — начертание и акцентный цвет.

import { canonicalJson } from '@vpe/core-model';

import type { RendererTemplate } from '../index.js';

/** Роль шрифта по умолчанию — та же строка, что в `declaredFonts` спека. */
const FONT_ROLE = 'caption';

/**
 * Начертание эмфазы — **КЛЮЧЕВЫМ СЛОВОМ, А НЕ ЧИСЛОМ, И ЭТО ИЗМЕРЕНИЕ.**
 *
 * `bold` = 700, `normal` = 400 — те же значения, и на вариативном шрифте это ровно ось
 * `wght`: Chrome отображает `font-weight` на неё сам. Но числом их сюда класть нельзя: gsap
 * дописывает единицу к ЧИСЛОВОМУ значению свойства, которого не знает, и кастомное свойство
 * получало бы `700px`. Подставленное в `font-weight`, оно невалидно, объявление отбрасывается
 * целиком, и начертание молча остаётся базовым. Проверено делом: кадры внутри и вне окна
 * эмфазы совпадали побайтово, пока значения были числами.
 *
 * `CAPTION-01`: ключей стало два. `regular` схемы — это CSS-`normal`, и ИМЕННО ОНО, а не
 * `initial`: `initial` снял бы палитру целиком, то есть выключил бы заодно и акцентный цвет.
 */
const WEIGHT = { bold: 'bold', regular: 'normal' } as const;

/**
 * Умолчание начертания эмфазы. `bold` — то единственное значение, которым шаблон звался до
 * `CAPTION-01` (`style: 'bold'` был enum из одного элемента).
 */
const DEFAULT_WEIGHT = WEIGHT.bold;

/**
 * Тёплый акцентный цвет активного слова — УМОЛЧАНИЕ, а не константа (`CAPTION-01`).
 *
 * ПЕРЕНОС ИЗ `sp3f` (`.cw .hot`, строка 98 `docs/spikes/sp3f/src/index.html`) — там он был
 * караоке-подсветкой, и `H-06` его НЕ переносил с формулировкой «цвет и свечение — решение,
 * которого никто не принимал». В `H-07` решение принято владельцем дословно: «вес по оси
 * вариативного шрифта + тёплый акцентный цвет». Свечение (`text-shadow` на 26 px) не
 * перенесено и здесь: мягкую тень несёт вся полоса, а второй ореол поверх неё — украшение,
 * которого никто не просил.
 */
const ACCENT_COLOR = '#ffb347';

/**
 * `initial` — СНЯТИЕ палитры, а не «базовое значение».
 *
 * Кастомное свойство со значением `initial` становится guaranteed-invalid, наследование его
 * не переносит, и `var()` в правиле полосы уходит в свой fallback — то есть в базовый вид,
 * который назначил ТРЕК. Написать здесь `normal` и белый цвет значило бы завести второе место,
 * где живёт база полосы, и разъехаться с первым при первой же правке чисел.
 */
const UNSET = 'initial';

/**
 * Имена канала эмфазы. Вторая половина пары объявлена в `composition/runtime.js` — правилом
 * `#captions .caption-word`, которое эти переменные читает. Их две, и они здесь единственное,
 * что шаблон знает про полосу.
 *
 * Свойства, а не класс и не атрибут: класс менял бы `className` (у gsap для этого нужен
 * плагин, которого в завендоренном ядре нет), атрибут — `AttrPlugin` (его там тоже нет).
 * Кастомное свойство ядро ставит само, и оно НАСЛЕДУЕТСЯ — значит цель может быть корнем
 * документа, который существует уже на монтировании.
 */
const WEIGHT_VAR = '--vpe-caption-weight';
const COLOR_VAR = '--vpe-caption-color';

/** `id` элемента правил. По нему же проверяется идемпотентность (поправка владельца П4). */
const STYLE_ID = 'vpe-caption-emphasis';

/**
 * **ДОГОВОР ШАБЛОНА С ТРЕКОМ — ЗАКРЫТЫЙ СПИСОК ИМЁН** (`CAPTION-01`).
 *
 * Вторая его половина — массив `KEYS` в `composition/runtime.js`. Списка два, и они обязаны
 * совпадать: имя, которого нет у трека, молча не подействует; имя, которого нет здесь,
 * никогда не будет подано. Совпадение стоит охранником в `test/templates.test.ts` — грепом по
 * обоим файлам, потому что между ними граница процесса, а не импорта.
 *
 * ЧЕГО В СПИСКЕ НЕТ И ЭТО НАМЕРЕННО: `font`, `weight`, `activeColor`. Первое — роль шрифта,
 * она превращается в `font-family` ЗДЕСЬ (у трека нет ссылки на шрифт); два других —
 * палитра эмфазы, она едет таймлайном на окно клипа, а не правилом на весь сегмент.
 */
const CAPTION_BAND_KEYS = [
  'widthPct',
  'position',
  'marginPx',
  'sizePx',
  'textColor',
  'shadow',
  'outline',
  'bg',
  'plateColor',
  'plateOpacity',
] as const;

const CAPTION_EMPHASIS_MOUNT = `function (host, ctx) {
        var role = ctx.params.font === undefined ? ${canonicalJson(FONT_ROLE)} : ctx.params.font;
        var ref = null;
        for (var i = 0; i < ctx.fonts.length; i++) {
          if (ctx.fonts[i].role === role) { ref = ctx.fonts[i]; break; }
        }
        if (ref === null) {
          throw new Error(
            'captionEmphasis@1: в клипе нет шрифта с ролью \\'' + role + '\\'. Спек объявляет ' +
            'его на любых params (шаблон рисует текст всегда), поэтому пустой список — ' +
            'разъехавшийся вход. Рисовать системным шрифтом значило бы увезти в кадры шрифт, ' +
            'которого нет ни в одной записи provenance (V10)'
          );
        }
        var family = ctx.fontOf(ref.sha256).family;

        // ИДЕМПОТЕНТНОСТЬ (П4): второй клип эмфазы в том же сегменте правил не удваивает, и
        // НАБОР ПОЛОСЫ тоже кладётся один раз — ПЕРВЫМ клипом. Полоса в сегменте одна;
        // «последний победил» означало бы, что вид субтитров зависит от порядка записей
        // режиссуры, то есть от того, что автор не писал.
        if (document.getElementById(${canonicalJson(STYLE_ID)}) === null) {
          var style = document.createElement('style');
          style.id = ${canonicalJson(STYLE_ID)};
          // ЕДИНСТВЕННОЕ ПРАВИЛО ШАБЛОНА — СЕМЕЙСТВО. Всё остальное про вид полосы ставит
          // трек в runtime.js ПО ЗНАЧЕНИЯМ, поданным ниже: долг №207 объясняет, почему
          // семейство осталось здесь, а не уехало туда же.
          style.textContent = [
            '#captions {',
            '  font-family: \\'' + family + '\\';',
            '}'
          ].join('\\n');
          document.head.appendChild(style);

          // НАБОР ПОЛОСЫ — ДАННЫМИ, ПО ЗАКРЫТОМУ СПИСКУ ИМЁН. Копировать ctx.params целиком
          // нельзя: туда попали бы и палитра эмфазы, и роль шрифта, то есть трек получил бы
          // ключи, которых не знает, — а молча проигнорированная ручка выглядит как
          // сломанная. Не заданное автором поле НЕ КЛАДЁТСЯ вовсе (undefined), и тогда
          // действует умолчание канала из runtime.js.
          var keys = ${canonicalJson([...CAPTION_BAND_KEYS])};
          var band = {};
          for (var k = 0; k < keys.length; k++) {
            if (ctx.params[keys[k]] !== undefined) band[keys[k]] = ctx.params[keys[k]];
          }
          window.__VPE_CAPTION_BAND = band;
        }

        // ЭМФАЗА — ПАЛИТРОЙ НА КОРНЕ ДОКУМЕНТА. Две вещи измерены, и каждая закрывает
        // по одному соблазну:
        //   * ТВИН ПО СЕЛЕКТОРУ НЕ ГОДИТСЯ: gsap резолвит строку в МОМЕНТ СОЗДАНИЯ твина
        //     (toArray), а слоя #captions на монтировании клипа ещё нет — целей вышло бы НОЛЬ,
        //     и эмфаза не применилась бы молча;
        //   * ATTR-ПЛАГИН НЕ ГОДИТСЯ ТОЖЕ: в завендоренном gsap.min.js 3.15.0 AttrPlugin
        //     ОТСУТСТВУЕТ (проверено грепом по файлу), и {attr: …} игнорируется БЕЗ ошибки —
        //     то есть эмфаза не применилась бы молча. Кадры внутри и вне окна совпадали
        //     побайтово, пока стоял он.
        // Кастомное свойство ядро умеет (setProperty с детекцией префикса), наследуется от
        // html вниз до слова, а цель — document.documentElement — существует всегда.
        //
        // ПАЛИТРА НЕ КРАСИТ ВСЮ ПОЛОСУ: правило трека закрывает каждое слово от наследования,
        // и открывает его ровно на окне token.highlight (runtime.js). Поэтому две строки
        // ниже — это «когда эмфаза РАЗРЕШЕНА», а не «что покрашено».
        var weights = ${canonicalJson({ ...WEIGHT })};
        var emph = {};
        emph[${canonicalJson(WEIGHT_VAR)}] = ctx.params.weight === undefined
          ? ${canonicalJson(DEFAULT_WEIGHT)}
          : weights[ctx.params.weight];
        emph[${canonicalJson(COLOR_VAR)}] = ctx.params.activeColor === undefined
          ? ${canonicalJson(ACCENT_COLOR)}
          : ctx.params.activeColor;
        var base = {};
        base[${canonicalJson(WEIGHT_VAR)}] = ${canonicalJson(UNSET)};
        base[${canonicalJson(COLOR_VAR)}] = ${canonicalJson(UNSET)};
        document.documentElement.style.setProperty(${canonicalJson(WEIGHT_VAR)}, ${canonicalJson(UNSET)});
        document.documentElement.style.setProperty(${canonicalJson(COLOR_VAR)}, ${canonicalJson(UNSET)});
        ctx.timeline.set(document.documentElement, emph, ctx.toSeconds(ctx.frames.frameStart));
        ctx.timeline.set(document.documentElement, base, ctx.toSeconds(ctx.frames.frameEnd));
      }`;

/** `captionEmphasis@1` — реализация шаблона фикстуры; единственный, кто просит шрифт. */
export const captionEmphasis1Impl: RendererTemplate = Object.freeze({
  templateId: 'captionEmphasis',
  templateVersion: 1,
  mountSource: CAPTION_EMPHASIS_MOUNT,
});

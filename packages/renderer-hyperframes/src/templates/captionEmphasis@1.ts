// Реализация `captionEmphasis@1` — оформление полосы субтитров и визуальная эмфаза внутри
// неё. Спек: `templates-spec/src/templates/captionEmphasis@1.ts`.
//
// **ЭТОТ ШАБЛОН ОФОРМЛЯЕТ `#captions`, А НЕ СВОЙ `host`** (решение владельца `H-06`, развилка
// «о», вариант о1). Основание — `runtime.js` дословно: субтитры он рисует САМ, отдельным
// слоем, и стилей туда не ставит намеренно — «оформление субтитров — `captionEmphasis@1`
// (`H-06`)». Рисовать свою вторую полосу поверх уже нарисованной значило бы две полосы в
// кадре; поэтому шаблон дотягивается до чужого слоя — поимённо, до одного, и это записано
// охранником формы DOM в `test/templates.test.ts` (поправка владельца П1-а).
//
// **ОФОРМЛЕНИЕ — ИНЪЕКЦИЕЙ `<style>`, И ЭТО НЕ УКРАШЕНИЕ, А ЕДИНСТВЕННАЯ ИСПОЛНИМАЯ ФОРМА.**
// ИЗМЕРЕНО (`H-06`, живой гейт): `mount` клипа исполняется в цикле клипов `runtime.js`, а слой
// `#captions` тот же файл создаёт ПОСЛЕ цикла — то есть на момент монтирования элемента ещё
// нет, и императивная простановка стилей падала «оформлять нечего». Правила CSS от порядка не
// зависят: они применятся к элементам, которые появятся позже. Это и есть причина, по которой
// шаблон не трогает узлы руками.
//
// **ВИДИМОСТЬ ГРУПП — НЕ ЗДЕСЬ** *(решение владельца `H-06`, вариант R2).* Её ставит
// `runtime.js` двумя строками из уже посчитанных им `group.frames`: субтитры приходят ТРЕКОМ
// `IR.captions`, а не вызовом шаблона (V3), и в сегменте без клипа эмфазы — а таких
// большинство — они обязаны показываться так же. Шаблон отвечает за ВНЕШНИЙ ВИД, трек — за
// ВРЕМЯ. Долг №168 не задевается: `clip.frames` здесь не читается ни разу, окно клипа берётся
// из `ctx.frames`.
//
// **ОФОРМЛЕНИЕ — НА ВЕСЬ СЕГМЕНТ, ЭМФАЗА — НА СВОЁ ОКНО, И ЭТО ДВЕ РАЗНЫЕ ВЕЩИ.** Условие
// применимости **R13** («полоса лежит на непрозрачной плашке») обязано держаться на КАЖДОМ
// кадре, где полоса видна, иначе прибор `H-02` меряет движущийся фон вместо смены строки.
// А `style: bold` — свойство КЛИПА, у которого есть окно `[start, end)`. Отсюда: плашка,
// шрифт, кегль и раскладка живут в CSS, начертание переключается таймлайном.
//
// ИДЕМПОТЕНТНОСТЬ ОБЯЗАТЕЛЬНА (поправка владельца П4): клипов `captionEmphasis@1` в сегменте
// может быть несколько (у каждого своё окно эмфазы), а полоса одна. Признак — `id` самого
// элемента `<style>`: вторая инъекция нашла бы его и не стала бы удваивать правила.
//
// **СЕМЕЙСТВО ШРИФТА НЕ НАЗЫВАЕТСЯ ЗДЕСЬ** — ровно по той же причине, что и в спеке: шрифт
// канала не выбран (долг №13, за владельцем), `DejaVu Sans Bold` объявлен ВРЕМЕННЫМ. Шаблон
// спрашивает РОЛЬ `caption` у `ctx.fonts` и берёт семейство у `ctx.fontOf` — то есть у
// проекта. Вписанное сюда семейство уехало бы в `engineFingerprint` с первым же гейтом.
//
// ЧИСЛА РАСКЛАДКИ — ВРЕМЕННЫЕ, И ЭТО СКАЗАНО ВСЛУХ. Кегль 72 и потолок 21 символ —
// величины №125, они НЕ пересматриваются здесь (адрес — `H-07`, решение владельца). Позиция
// полосы и высота плашки числами не названы ни одним документом, а без них условие **R13**
// невыразимо; выбраны так, чтобы две строки кегля 72 умещались в плашку целиком. Долг заведён
// с адресом `H-02`/`H-07`.

import { canonicalJson } from '@vpe/core-model';

import type { RendererTemplate } from './index.js';

/** Роль шрифта — та же строка, что в `declaredFonts` спека. */
const FONT_ROLE = 'caption';

/**
 * Геометрия полосы в координатах КОМПОЗИЦИИ (`baseWidth × baseHeight`, то есть
 * `compileProfile`). `scale` профиля раскрыт на `#root` и слоя не касается (**K4**), поэтому
 * числа одни на все три профиля.
 */
const BAND = {
  /** Ширина полосы и отступ слева: 960 при 1080 ⇒ поля по 60. Перенос из `sp3f` `.capPage`. */
  widthPx: 960,
  leftPx: 60,
  /** Низ полосы над краем кадра. */
  bottomPx: 240,
  /** Кегль — величина №125, не пересматривается (`H-07`). */
  fontSizePx: 72,
  lineHeight: 1.25,
  /** Высота плашки: `bottomPx` + две строки кегля с межстрочным + запас. */
  plateHeightPx: 480,
} as const;

/** Непрозрачная плашка — условие применимости **R13**. Цвет перенесён из `sp3f` `#capPlate`. */
const PLATE_COLOR = '#05070c';

/** Цвет текста полосы. Перенесён из `sp3f` `.cw .dim`, приведён к непрозрачному. */
const TEXT_COLOR = '#dff3ff';

/**
 * Начертания — **КЛЮЧЕВЫМИ СЛОВАМИ, А НЕ ЧИСЛАМИ, И ЭТО ИЗМЕРЕНИЕ.**
 *
 * `bold` = 700, `normal` = 400 — те же значения. Но числом их сюда класть нельзя: gsap
 * дописывает единицу к ЧИСЛОВОМУ значению свойства, которого не знает, и кастомное свойство
 * получало бы `700px`. Подставленное в `font-weight`, оно невалидно, объявление отбрасывается
 * целиком, и начертание молча остаётся базовым. Проверено делом: кадры внутри и вне окна
 * эмфазы совпадали побайтово, пока значения были числами.
 */
const WEIGHT = { base: 'normal', bold: 'bold' } as const;

/**
 * Имя кастомного свойства, которым переключается начертание.
 *
 * Свойство, а не класс и не атрибут: класс менял бы `className` (у gsap для этого нужен
 * плагин, которого в завендоренном ядре нет), атрибут — `AttrPlugin` (его там тоже нет).
 * Кастомное свойство ядро ставит само, и оно НАСЛЕДУЕТСЯ — значит цель может быть корнем
 * документа, который существует уже на монтировании.
 */
const WEIGHT_VAR = '--vpe-caption-weight';

/** `id` элемента правил. По нему же проверяется идемпотентность (поправка владельца П4). */
const STYLE_ID = 'vpe-caption-band';

const CAPTION_EMPHASIS_MOUNT = `function (host, ctx) {
        var ref = null;
        for (var i = 0; i < ctx.fonts.length; i++) {
          if (ctx.fonts[i].role === ${canonicalJson(FONT_ROLE)}) { ref = ctx.fonts[i]; break; }
        }
        if (ref === null) {
          throw new Error(
            'captionEmphasis@1: в клипе нет шрифта с ролью \\'${FONT_ROLE}\\'. Спек объявляет ' +
            'его на любых params (шаблон рисует текст всегда), поэтому пустой список — ' +
            'разъехавшийся вход. Рисовать системным шрифтом значило бы увезти в кадры шрифт, ' +
            'которого нет ни в одной записи provenance (V10)'
          );
        }
        var family = ctx.fontOf(ref.sha256).family;

        // ИДЕМПОТЕНТНОСТЬ (П4): второй клип эмфазы в том же сегменте правил не удваивает.
        if (document.getElementById(${canonicalJson(STYLE_ID)}) === null) {
          var style = document.createElement('style');
          style.id = ${canonicalJson(STYLE_ID)};
          style.textContent = [
            // Плашка — ФОН САМОГО СЛОЯ, а не отдельный узел: фон элемента всегда лежит под его
            // детьми, и порядок вставки узлов на это не влияет. Это же снимает вопрос «куда
            // положить плашку, если групп ещё нет».
            '#captions {',
            '  font-weight: var(' + ${canonicalJson(WEIGHT_VAR)} + ', ' + ${canonicalJson(WEIGHT.base)} + ');',
            '  font-family: \\'' + family + '\\';',
            '  background: linear-gradient(to top, ' + ${canonicalJson(PLATE_COLOR)} + ' 0px, ' +
              ${canonicalJson(PLATE_COLOR)} + ' ${String(BAND.plateHeightPx)}px, ' +
              'rgba(0,0,0,0) ${String(BAND.plateHeightPx)}px);',
            '}',
            // Полоса: раскладка и типографика. Начертание наследуется от блока выше.
            '#captions .caption-group {',
            '  position: absolute;',
            '  left: ${String(BAND.leftPx)}px;',
            '  width: ${String(BAND.widthPx)}px;',
            '  bottom: ${String(BAND.bottomPx)}px;',
            '  text-align: center;',
            '  font-size: ${String(BAND.fontSizePx)}px;',
            '  line-height: ${String(BAND.lineHeight)};',
            '  color: ' + ${canonicalJson(TEXT_COLOR)} + ';',
            '}'
          ].join('\\n');
          document.head.appendChild(style);
        }

        // ЭМФАЗА — CSS-ПЕРЕМЕННОЙ НА КОРНЕ ДОКУМЕНТА. Две вещи измерены, и каждая закрывает
        // по одному соблазну:
        //   * ТВИН ПО СЕЛЕКТОРУ НЕ ГОДИТСЯ: gsap резолвит строку в МОМЕНТ СОЗДАНИЯ твина
        //     (toArray), а слоя #captions на монтировании клипа ещё нет — целей вышло бы НОЛЬ,
        //     и эмфаза не применилась бы молча;
        //   * ATTR-ПЛАГИН НЕ ГОДИТСЯ ТОЖЕ: в завендоренном gsap.min.js 3.15.0 AttrPlugin
        //     ОТСУТСТВУЕТ (проверено грепом по файлу), и {attr: …} игнорируется БЕЗ ошибки —
        //     то есть эмфаза не применилась бы молча. Кадры внутри и вне окна совпадали
        //     побайтово, пока стоял он.
        // Кастомное свойство ядро умеет (setProperty с детекцией префикса), наследуется от
        // html вниз до полосы, а цель — document.documentElement — существует всегда.
        var weight = ctx.params.style === 'bold'
          ? ${canonicalJson(WEIGHT.bold)}
          : ${canonicalJson(WEIGHT.base)};
        var base = {};
        base[${canonicalJson(WEIGHT_VAR)}] = ${canonicalJson(WEIGHT.base)};
        var emph = {};
        emph[${canonicalJson(WEIGHT_VAR)}] = weight;
        document.documentElement.style.setProperty(${canonicalJson(WEIGHT_VAR)}, ${canonicalJson(WEIGHT.base)});
        ctx.timeline.set(document.documentElement, emph, ctx.toSeconds(ctx.frames.frameStart));
        ctx.timeline.set(document.documentElement, base, ctx.toSeconds(ctx.frames.frameEnd));
      }`;

/** `captionEmphasis@1` — реализация шаблона фикстуры; единственный, кто просит шрифт. */
export const captionEmphasis1Impl: RendererTemplate = Object.freeze({
  templateId: 'captionEmphasis',
  templateVersion: 1,
  mountSource: CAPTION_EMPHASIS_MOUNT,
});

// Реализация `bed@1` — музыкальная подложка. Спек:
// `templates-spec/src/templates/bed@1.ts`.
//
// **ЭТО РЕАЛИЗАЦИЯ-ОТКАЗ, И ЭТО РЕШЕНИЕ ВЛАДЕЛЬЦА** (`H-06`, развилка «б», вариант б3).
//
// ИЗМЕРЕНО, ПОЧЕМУ ОНА НЕ МОЖЕТ БЫТЬ ВЫЗВАНА. `compile/src/compile-ir.ts`, шапка: в видео-IR
// идут ТОЛЬКО три дорожки — `caption`, `visual`, `effect` (`CROSSING_TRACKS`, `CP-03`);
// `music`/`sfx` — аудио-домен, звук не режется вообще, сегменты немые (**R5**), и «клип
// `bed@1` на всю сцену просто не имеет сегмента, которому бы принадлежал. Он уезжает в
// `AudioPlan` (`CP-05`)». Значит `bed@1` не появляется в `RenderIR.clips` НИКОГДА, и
// `resolveTemplate('bed@1')` в продакшне не будет вызван ни разу.
//
// ПОЧЕМУ НЕ NO-OP. Пустая функция дала бы `vpe template gate bed@1` класс **PASS на чёрных
// кадрах** — ровно ложно-зелёный долга №164, и запись «шаблон детерминирован» описывала бы
// пустой слой. Запись гейта — это измерение, и измерение пустоты не является измерением
// шаблона.
//
// ПОЧЕМУ НЕ «НЕ РЕГИСТРИРОВАТЬ». Реестр реализаций сверяется со спеками (`L-01`), а спек у
// `bed@1` есть и обязан быть: манифест — свойство ШАБЛОНА, а не проекта. Пропуск сделал бы
// отсутствие реализации неотличимым от «забыли написать».
//
// ЦЕНА, ПРИНЯТАЯ ОСОЗНАННО И НАЗВАННАЯ ВСЛУХ: критерий готовности roadmap `H-06` «каждый
// прошёл гейт на `final` (10) и `draftHalf` (3)» на `bed@1` **неисполним по построению** —
// гейт на нём даёт `error` («гейта не было»), а не PASS. Долг заведён с этой формулировкой,
// а не заметён.
//
// `msPerFrameBudget: 0` СПЕКА — ТА ЖЕ МЫСЛЬ С ДРУГОЙ СТОРОНЫ ГРАНИЦЫ: «Ноль — измерение по
// построению, а не оценка».

import type { RendererTemplate } from './index.js';

const BED_MOUNT = `function (host, ctx) {
        throw new Error(
          'bed@1 — шаблон АУДИО-домена: кадров он не рисует. В RenderIR.clips он не попадает ' +
          'по построению (compile/src/compile-ir.ts: видео-IR несёт только caption, visual и ' +
          'effect; music и sfx уезжают в AudioPlan, CP-05), поэтому вызов mount означает, что ' +
          'клип аудио-дорожки доехал до видео-сегмента, — ошибку компилятора, а не сцену без ' +
          'музыки. Пустой слой вместо отказа дал бы гейту PASS на чёрных кадрах, то есть ' +
          'запись «шаблон детерминирован» про пустоту (долг №164)'
        );
      }`;

/** `bed@1` — реализация-отказ; единственный из пяти в аудио-домене. */
export const bed1Impl: RendererTemplate = Object.freeze({
  templateId: 'bed',
  templateVersion: 1,
  mountSource: BED_MOUNT,
});

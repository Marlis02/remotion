// состоит нарушение Н4 протокола `FIX-01`.
//
// ГРАНИЦА ОТВЕТСТВЕННОСТИ НАЗВАНА ВСЛУХ: поведение вендора мы не контролируем и обещать его
// не можем. Поэтому здесь не «мы гарантируем видимость», а «мы ИЗМЕРЯЕМ, что она есть» — и
// перестанет быть, узнаём от теста, а не от готового ролика.
//
// **ФОРМА АССЕРТА ВЫБРАНА ПО ЦЕНЕ** (владелец оставил выбор): сравниваются БАЙТЫ готовых PNG
// соседних кадров, а не пиксели и не MAD. Причины две. Первая — цена: один рендер на 12 кадров

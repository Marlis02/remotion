// `normal`, а синтетическое утолщение Chrome поверх уже жирных глифов не накладывает. Тест
// был закреплён на ФАКТЕ — `eq(0, 3)` ожидалось `true` — с прямой инструкцией: «когда у
// проекта появится гарнитура с настоящими начертаниями (№13), эта строка покраснеет».
//
// **ЧТО СТАЛО (`H-07`), И ЧЕМ ИМЕННО ПОКРАСНЕЛО — НАЗВАНО ЧЕСТНО.** `eq(0, 3)` теперь
// **`false`**, но гарнитура прибора НЕ изменилась: `makeTemplateFixture` по-прежнему берёт
// `DejaVuSans-Bold.ttf` прямо с машины (долг **№187**), вариативной оси у неё нет, и

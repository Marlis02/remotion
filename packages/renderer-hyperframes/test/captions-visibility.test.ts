//
// **И ЭТО САМО ПО СЕБЕ ИЗМЕРЕНИЕ В ПОЛЬЗУ ТОГО РЕШЕНИЯ.** Владелец назвал причину словами —
// «на телефоне жирность одна не читается», — и прибор её подтверждает предельным случаем:
// на гарнитуре без оси весов эмфаза, сделанная ТОЛЬКО весом, не меняет ни одного пикселя.
// Настоящая ось `wght` приедет с вариативным шрифтом проекта (№13, демо `H-07`), а этот файл
// продолжит краснеть на разрыве канала, а не на выборе шрифта.
//
// Механизм при этом не оставлен без охраны и с той стороны: его стережёт юнит в
// `templates.test.ts` (палитра — на корне документа таймлайном, база — правилом трека).
//
// ~~ЧЕТВЁРТОЕ УТВЕРЖДЕНИЕ — ПРО ИНЪЕКЦИЮ `<style>`: тот же сегмент БЕЗ клипа эмфазы даёт
// другие кадры.~~ *(изменено: `H-07` — предмет уехал.)* После переноса раскладки в трек
// «полоса оформлена» больше не есть свойство клипа: она обязана стоять на месте и БЕЗ него.
// Поэтому вместо разности двух прогонов здесь стоит ПРЯМОЕ измерение геометрии — где в кадре
// лежит белый текст (см. второй `it`). Разность двух прогонов на этот вопрос не отвечала
// вовсе: она краснела бы одинаково и от съехавшей полосы, и от пропавшей.
//
// **ПОЧЕМУ `scale: 1`, А НЕ ДЕШЁВЫЙ `0.25`.** ~~ИЗМЕРЕНО (`H-06`, находка, долг заведён): при
// `scale < 1` адаптер сжимает композицию в ЛЕВУЮ ВЕРХНЮЮ ЧЕТВЕРТЬ кадра, остальное остаётся
// прозрачным, — то есть масштаб применяется дважды.~~ *(изменено: `FIX-01`, 2026-08-29 — долг
// №182 ЗАКРЫТ, дефекта больше нет: охранник [`scale-render.test.ts`](./scale-render.test.ts).)*
//
// ПРИЧИНА ОСТАЛАСЬ, НО ОНА ДРУГАЯ, И ЭТО НЕ ТА ЖЕ ФРАЗА ДРУГИМИ СЛОВАМИ. Дело больше не в
// кривой картинке, а в РАЗРЕШЕНИИ прибора: этот тест сравнивает БАЙТЫ кадров, а при `0.25`
// полоса субтитров занимает несколько пикселей высоты, и «кадры различаются» перестаёт
// означать «строка сменилась» — различие такого размера неотличимо от шума кодека. Цена
// прежняя: 1080×1920 вместо 270×480, измерено ~2 с на рендер.

import { readFileSync, readdirSync } from 'node:fs';
import path from 'node:path';

import { describe, expect, it } from 'vitest';

import { renderSegment } from '../src/run.js';
import { rendererTemplates } from '../src/templates/index.js';
import { decodeRgb, pngSize } from '../src/where.js';
import { FIXTURE_PARAMS, makeTemplateFixture, readyRequest } from './fixture.js';

const FRAMES = 12;
/** Измерено: одиночный рендер 12 кадров 1080×1920 на этой машине — 2–3 с. Запас ×100. */
const TIMEOUT = 300_000;

const realClock = (): (() => number) => () => performance.now();

/** Кадры прогона по номеру, отсортированные по имени: порядок не зависит от ФС. */
function framesOf(dir: string): Buffer[] {
  return readdirSync(dir)
    .filter((n) => n.endsWith('.png'))
    .sort()
    .map((n) => readFileSync(path.join(dir, n)));
}

/**
 * Прибор геометрии полосы: где в кадре лежит ПЛАШКА и есть ли на ней белый текст.
 *
 * **ПОЧЕМУ ИЩЕТСЯ ТЁМНОЕ, А НЕ ТЕКСТ.** Измерено этим же прибором на первом прогоне: фон
 * кадра БЕЛЫЙ (умолчание страницы; слоёв под субтитрами в этой пробе нет), и «белых
 * пикселей» в кадре 1 975 966 из 2 073 600 — то есть почти всё. Белый текст на белом фоне не
 * локализуется в принципе. Локализуется ПЛАШКА: она непрозрачна и тёмная (`BAND.plateColor`
 * = `#05070c`, решение владельца `H-07`, вариант «б»), и в этом кадре тёмное ровно одно.
 *
 * ЭТО НЕ ОБХОД, А ТОТ ЖЕ ПРЕДМЕТ С ПРАВИЛЬНОЙ СТОРОНЫ: вопрос «где полоса» и есть «где
 * плашка», а «текст на плашке» — условие применимости **R13**, и оно проверяется вторым
 * числом (`white` — белые пиксели ВНУТРИ рамки плашки).
 *
 * ПОРОГИ НАЗВАНЫ ЧИСЛАМИ. Тёмное — все три канала < 64 (плашка 5/7/12; растушёвка края даёт
 * промежуточные значения того же диапазона и считается плашкой — она ею и является). Белое —
 * все три канала ≥ 200: берёт и сглаженные края глифов.
 *
 * ВТОРОГО PNG-ДЕКОДЕРА НЕ ЗАВОДИТСЯ: `decodeRgb` — тот же, которым `where` считает PSNR.
 */
export function bandInk(
  rgb: Uint8Array,
  width: number,
  height: number,
): {
  dark: number;
  cx: number;
  cy: number;
  top: number;
  bottom: number;
  left: number;
  right: number;
  corner: number;
  white: number;
} {
  let dark = 0;
  let sx = 0;
  let sy = 0;
  let top = height;
  let bottom = -1;
  let left = width;
  let right = -1;
  let corner = 0;
  const isDark = (i: number): boolean =>
    (rgb[i] ?? 0) < 64 && (rgb[i + 1] ?? 0) < 64 && (rgb[i + 2] ?? 0) < 64;
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      if (!isDark((y * width + x) * 3)) continue;
      dark += 1;
      sx += x;
      sy += y;
      if (y < top) top = y;
      if (y > bottom) bottom = y;
      if (x < left) left = x;
      if (x > right) right = x;
      if (y * 2 < height && x * 2 < width) corner += 1;
    }
  }
  let white = 0;
  for (let y = Math.max(top, 0); y <= bottom; y++) {
    for (let x = Math.max(left, 0); x <= right; x++) {
      const i = (y * width + x) * 3;
      if ((rgb[i] ?? 0) >= 200 && (rgb[i + 1] ?? 0) >= 200 && (rgb[i + 2] ?? 0) >= 200) white += 1;
    }
  }
  return {
    dark,
    cx: dark === 0 ? 0 : sx / dark,
    cy: dark === 0 ? 0 : sy / dark,
    top,
    bottom,
    left,
    right,
    corner,
    white,
  };
}

/** Один рендер: с клипом эмфазы или без него. Возвращает КАТАЛОГ кадров. */
async function renderDir(withEmphasis: boolean): Promise<string> {
  const clips = withEmphasis
    ? [
        {
          template: 'captionEmphasis@1',
          params: FIXTURE_PARAMS.captionEmphasis,
          z: 30,
          withFont: true,
          window: { frameStart: 0, frameEnd: 3 },
        },
      ]
    : [{ template: 'flash@1', params: { strengthPct: 1, durationSamples: 1 }, z: 20 }];

  const fixture = makeTemplateFixture(clips, {
    frames: FRAMES,
    scale: 1,
    workers: 4,
    withCaptions: true,
    captionWindows: [
      [0, 6],
      [6, FRAMES],
    ],
  });
  const request = await readyRequest(fixture.request);
  const response = await renderSegment(request, {
    clock: realClock(),
    registry: rendererTemplates,
    parentEnv: process.env,
    gate: { mode: 'skip', why: 'проба видимости субтитров `H-06`: гейт здесь не снимается' },
  });
  if (!response.ok) throw new Error(`${response.error.rule}: ${response.error.message}`);
  expect(response.frames.frameCount).toBe(FRAMES);
  return response.frames.dir;
}

/** Тот же рендер, но байтами кадров: форма ассерта первого утверждения не менялась. */
async function render(withEmphasis: boolean): Promise<Buffer[]> {
  return framesOf(await renderDir(withEmphasis));
}

describe('**№185** — видимость групп держит рендерер по `data-*`, и это ИЗМЕРЯЕТСЯ', () => {
  it(
    'кадры меняются на границе групп и на границе эмфазы, и не меняются внутри окна',
    async () => {
      const f = await render(true);
      expect(f).toHaveLength(FRAMES);

      const eq = (a: number, b: number): boolean => f[a]!.equals(f[b]!);

      // Группа сменилась на кадре 6. Совпадение здесь означает, что видимость групп не
      // переключается вовсе, — а её единственный канал сегодня один: атрибуты
      // `data-start`/`data-duration`, которые читает сам `hyperframes@0.8.5`.
      expect(
        eq(3, 6),
        'кадр 3 и кадр 6 совпали: видимость групп не переключается. Причин ровно две, и обе ' +
          'проверяемы — либо `runtime.js` перестал ставить `data-start`/`data-duration` на ' +
          '`.caption-group`, либо обновившийся рендерер перестал их читать (пришпилено ' +
          '`hyperframes@0.8.5`; второе — сигнал о вендоре, а не поломка теста)',
      ).toBe(false);
      // Внутри одного окна ничего не движется: субтитры не анимированы, эмфаза постоянна.
      expect(eq(3, 4)).toBe(true);
      expect(eq(4, 5)).toBe(true);
      expect(eq(6, 7)).toBe(true);
      // ИЗМЕРЕНИЕ, ЗАПИСАННОЕ УТВЕРЖДЕНИЕМ (см. шапку). ~~На шрифте проекта эмфаза пикселей
      // не меняет.~~ *(перевёрнуто: `H-07`, 2026-08-31.)* Эмфаза РАЗЛИЧИМА: кадр 0 внутри
      // окна клипа `[0,3)` несёт активное слово тяжелее и тёплого цвета, кадр 3 — базовое.
      // Совпадение здесь значит, что канал «палитра на корне → `inherit` у слова → правило
      // полосы» где-то разорван, и эмфаза стала тихим no-op — тем самым, от которого
      // `H-06` защищался юнитом, потому что пикселя тогда не было.
      expect(
        eq(0, 3),
        'кадры внутри и вне окна эмфазы СОВПАЛИ: эмфаза не доехала до пикселей. Проверяемых ' +
          'причин три — палитра не встала на корень (`captionEmphasis@1`), слово не открыто ' +
          'наследованию на своём окне (`runtime.js`, `inherit`), либо у гарнитуры нет живой ' +
          'оси `wght` (тогда это снова долг №13, а не поломка теста)',
      ).toBe(false);
    },
    TIMEOUT,
  );

  it(
    '**H-07** — полоса стоит внизу по центру И БЕЗ клипа эмфазы: измерено по пикселям',
    async () => {
      // Предмет — РАСКЛАДКА, а не разность двух прогонов: раскладка теперь свойство ТРЕКА и
      // обязана держаться там, где клипа эмфазы нет вовсе. Прогон поэтому ровно один, и в
      // нём нет ни одного `captionEmphasis@1`.
      const dir = await renderDir(false);
      const first = readdirSync(dir)
        .filter((n) => n.endsWith('.png'))
        .sort()[4];
      if (first === undefined) throw new Error('кадров на диске нет');
      const file = path.join(dir, first);
      const size = pngSize(file);
      if (size === null) throw new Error(`PNG не прочитан: ${file}`);
      const ink = bandInk(await decodeRgb(file), size.width, size.height);
      const where =
        `тёмных пикселей ${String(ink.dark)}, центр (${ink.cx.toFixed(0)}, ${ink.cy.toFixed(0)}) ` +
        `при кадре ${String(size.width)}×${String(size.height)}, рамка ` +
        `y ${String(ink.top)}…${String(ink.bottom)}, x ${String(ink.left)}…${String(ink.right)}, ` +
        `в левом верхнем углу ${String(ink.corner)}, белых внутри рамки ${String(ink.white)}`;

      // 1. ПОЛОСА ВООБЩЕ ЕСТЬ. Ноль тёмного означал бы, что правила трека до документа не
      //    доехали: без плашки кадр этой пробы белый целиком.
      expect(ink.dark, where).toBeGreaterThan(20_000);
      // 2. НЕ В УГЛУ. Ровно та картинка, которую владелец увидел в `final.mp4` фикстуры:
      //    браузерное умолчание ставит текст в левый верхний угол, и там он был бы ЧЁРНЫМ на
      //    белом, то есть попал бы в этот счёт. Здесь его там нет ни одного пикселя.
      expect(ink.corner, where).toBe(0);
      // 3. ПО ЦЕНТРУ ПО ГОРИЗОНТАЛИ. Допуск 60 px — это разница между «по центру» и «прижато
      //    к краю поля», а не точность вёрстки.
      expect(Math.abs(ink.cx - size.width / 2), where).toBeLessThan(60);
      // 4. ВНИЗУ, НО НЕ В ЗОНЕ ИНТЕРФЕЙСА. Безопасные зоны Shorts (решение владельца `H-07`):
      //    нижние ~15 % кадра заняты интерфейсом. Числа полосы — предложение (долг №188), и
      //    границы здесь широкие намеренно: тест стережёт ЗОНУ, а не выбранное число.
      expect(ink.cy / size.height, where).toBeGreaterThan(0.6);
      expect(ink.cy / size.height, where).toBeLessThan(0.8);
      expect(ink.bottom / size.height, where).toBeLessThan(0.85);
      // 5. ТЕКСТ ЛЕЖИТ НА ПЛАШКЕ — условие применимости **R13**, и оно теперь ИЗМЕРЕНО, а не
      //    объявлено комментарием: белые пиксели есть ВНУТРИ рамки плашки, а не рядом с ней.
      expect(ink.white, where).toBeGreaterThan(2000);
    },
    TIMEOUT,
  );
});

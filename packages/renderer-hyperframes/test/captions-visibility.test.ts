// **ОХРАННИК ДВУХ СТРОК ВИДИМОСТИ СУБТИТРОВ (нарушение Н6 протокола, поправка владельца П2).**
//
// ═══ ТРЕБУЕТ БРАУЗЕРА И СИСТЕМНОГО ШРИФТА. СКИПА ПО ПЕРЕМЕННОЙ ЗДЕСЬ НЕТ ═══
//
// ЧТО ОН СТЕРЕЖЁТ. `runtime.js` получил две строки (решение владельца `H-06`, вариант R2):
// `capsTimeline.set(el, {opacity: 1}, start)` и `… {opacity: 0}, end`. Удали их руками — и без
// этого файла НИЧЕГО не покраснеет: гейт всё равно даст PASS (три прогона одинаково покажут
// все группы сразу, друг на друге), юниты формы DOM тоже промолчат, потому что атрибуты
// `data-start`/`data-duration` останутся на месте. Ровно так эти данные и умерли в первый раз:
// их считал `runtime.js` и не читал никто.
//
// **ФОРМА АССЕРТА ВЫБРАНА ПО ЦЕНЕ** (владелец оставил выбор): сравниваются БАЙТЫ готовых PNG
// соседних кадров, а не пиксели и не MAD. Причины две. Первая — цена: один рендер на 12 кадров
// вместо серии, декодер не нужен вовсе. Вторая — граница: покадровый кроп полосы, MAD и порог
// 0.5 принадлежат **R13** и задаче `H-02`, и повторять их здесь значило бы завести второй
// прибор для того же правила. Здесь проверяется не «границы совпали с расчётными», а
// единственное: **картинка меняется там, где обязана, и не меняется там, где не должна**.
//
// РАСКЛАДКА ПРОБЫ. Двенадцать кадров, две группы субтитров — `[0,6)` и `[6,12)`, — и клип
// `captionEmphasis@1` с окном `[0,3)`. Отсюда два независимых утверждения:
//   * кадр 3 ≠ кадр 6 — группа сменилась (это и есть **Н6**: без двух строк все группы видны
//     всегда, и кадры совпали бы);
//   * кадры 3, 4, 5 равны между собой — внутри окна ничего не дрожит.
//
// **ТРЕТЬЕГО УТВЕРЖДЕНИЯ — «кадр 0 ≠ кадр 3, эмфаза включилась» — ЗДЕСЬ НЕТ, И ЭТО ИЗМЕРЕНИЕ,
// А НЕ ПРОПУСК.** `FACT` (`H-06`, проба на этой машине): при `font-family` шрифта проекта
// `font-weight: bold` и `font-weight: normal` дают **побайтово одинаковые кадры**. Причина —
// v1-правило «ровно один font-record в проекте», а этот единственный record есть
// `DejaVuSans-Bold.ttf`: `@font-face` без дескриптора веса объявляет его гарнитурой веса
// `normal`, а синтетическое утолщение Chrome поверх уже жирных глифов не накладывает. Та же
// проба БЕЗ `font-family` (системная гарнитура с настоящими начертаниями) кадры РАЗЛИЧАЕТ —
// значит механизм рабочий, невыразим вход. Долг заведён с адресом №13/`M-02`/`H-07`.
// Механизм при этом не оставлен без охраны: его стережёт юнит в `templates.test.ts`
// (переменная объявлена в правиле и ставится на корне документа таймлайном).
//
// ЧЕТВЁРТОЕ УТВЕРЖДЕНИЕ — ПРО ИНЪЕКЦИЮ `<style>`: тот же сегмент БЕЗ клипа эмфазы даёт другие
// кадры. Без него «полоса оформлена» осталось бы словами: правила CSS, не доехавшие до
// документа, выглядят как отсутствие плашки, а не как ошибка.
//
// **ПОЧЕМУ `scale: 1`, А НЕ ДЕШЁВЫЙ `0.25`.** ИЗМЕРЕНО (`H-06`, находка, долг заведён):
// при `scale < 1` адаптер сжимает композицию в ЛЕВУЮ ВЕРХНЮЮ ЧЕТВЕРТЬ кадра, остальное
// остаётся прозрачным, — то есть масштаб применяется дважды. Воспроизводится и на `solid@1`
// (`H-01`), значит дефект существовал до этой задачи и в её зону не входит. Но полоса
// субтитров на нём вырождается в несколько пикселей, и тест, проверяющий КАРТИНКУ, обязан
// идти там, где картинка верна. Цена — 1080×1920 вместо 270×480; измерено: ~2 с на рендер.

import { readFileSync, readdirSync } from 'node:fs';
import path from 'node:path';

import { describe, expect, it } from 'vitest';

import { renderSegment } from '../src/run.js';
import { rendererTemplates } from '../src/templates/index.js';
import { FIXTURE_PARAMS, makeTemplateFixture, readyRequest } from './fixture.js';

const FRAMES = 12;
/** Измерено: одиночный рендер 12 кадров 1080×1920 на этой машине — 2–3 с. Запас ×100. */
const TIMEOUT = 300_000;

const realClock = (): (() => number) => () => performance.now();

/** Кадры прогона по номеру, отсортированные по имени: порядок не зависит от ФС. */
function framesOf(dir: string): Buffer[] {
  return readdirSync(dir)
    .filter((n) => n.endsWith('.png'))
    .sort()
    .map((n) => readFileSync(path.join(dir, n)));
}

/** Один рендер: с клипом эмфазы или без него. */
async function render(withEmphasis: boolean): Promise<Buffer[]> {
  const clips = withEmphasis
    ? [
        {
          template: 'captionEmphasis@1',
          params: FIXTURE_PARAMS.captionEmphasis,
          z: 30,
          withFont: true,
          window: { start: 0, end: 3 },
        },
      ]
    : [{ template: 'flash@1', params: { strengthPct: 1, durationSamples: 1 }, z: 20 }];

  const fixture = makeTemplateFixture(clips, {
    frames: FRAMES,
    scale: 1,
    workers: 4,
    withCaptions: true,
    captionWindows: [
      [0, 6],
      [6, FRAMES],
    ],
  });
  const request = await readyRequest(fixture.request);
  const response = await renderSegment(request, {
    clock: realClock(),
    registry: rendererTemplates,
    parentEnv: process.env,
    gate: { mode: 'skip', why: 'проба видимости субтитров `H-06`: гейт здесь не снимается' },
  });
  if (!response.ok) throw new Error(`${response.error.rule}: ${response.error.message}`);
  expect(response.frames.frameCount).toBe(FRAMES);
  return framesOf(response.frames.dir);
}

describe('**Н6** — видимость групп субтитров живёт двумя строками `runtime.js`', () => {
  it(
    'кадры меняются на границе групп и на границе эмфазы, и не меняются внутри окна',
    async () => {
      const f = await render(true);
      expect(f).toHaveLength(FRAMES);

      const eq = (a: number, b: number): boolean => f[a]!.equals(f[b]!);

      // **Н6**: группа сменилась на кадре 6. Совпадение здесь означает, что двух строк
      // видимости в `runtime.js` больше нет и все группы показываются одновременно.
      expect(
        eq(3, 6),
        'кадр 3 и кадр 6 совпали: видимость групп не переключается — две строки ' +
          '`capsTimeline.set(el, {opacity}, …)` в `runtime.js` удалены или мертвы',
      ).toBe(false);
      // Внутри одного окна ничего не движется: субтитры не анимированы, эмфаза постоянна.
      expect(eq(3, 4)).toBe(true);
      expect(eq(4, 5)).toBe(true);
      expect(eq(6, 7)).toBe(true);
      // ИЗМЕРЕНИЕ, ЗАПИСАННОЕ УТВЕРЖДЕНИЕМ (см. шапку): на шрифте проекта эмфаза пикселей
      // не меняет. Тест закреплён на ФАКТЕ, а не на ожидании: когда у проекта появится
      // гарнитура с настоящими начертаниями (№13, `M-02`), эта строка покраснеет — и это
      // будет верным сигналом «долг закрылся», а не поломкой.
      expect(
        eq(0, 3),
        'кадры внутри и вне окна эмфазы РАЗОШЛИСЬ — значит начертание наконец различимо; ' +
          'долг №13/`M-02` закрыт, и утверждение пора перевернуть на `false`',
      ).toBe(true);
    },
    TIMEOUT,
  );

  it(
    'инъекция `<style>` шаблона ДОЕХАЛА: без клипа эмфазы те же группы выглядят иначе',
    async () => {
      const [withEmph, without] = await Promise.all([render(true), render(false)]);
      // Кадр 4 у обоих лежит внутри окна первой группы и ВНЕ окна эмфазы `[0,3)`, поэтому
      // различие здесь — это плашка, шрифт, кегль и раскладка, а не начертание.
      expect(
        withEmph[4]!.equals(without[4]!),
        'кадры совпали: правила `#captions`/`.caption-group` до документа не доехали, и ' +
          'условие применимости **R13** («полоса на непрозрачной плашке») не выполнено',
      ).toBe(false);
    },
    TIMEOUT,
  );
});

//
// РАСКЛАДКА ПРОБЫ. Двенадцать кадров, две группы субтитров — `[0,6)` и `[6,12)`, — и клип
// `captionEmphasis@1` с окном `[0,3)`. Отсюда два независимых утверждения:
//   * кадр 3 ≠ кадр 6 — группа сменилась (это и есть **Н6**: без двух строк все группы видны
//     всегда, и кадры совпали бы);
//   * кадры 3, 4, 5 равны между собой — внутри окна ничего не дрожит.
//
// ~~**ТРЕТЬЕГО УТВЕРЖДЕНИЯ — «кадр 0 ≠ кадр 3, эмфаза включилась» — ЗДЕСЬ НЕТ, И ЭТО
// ИЗМЕРЕНИЕ, А НЕ ПРОПУСК.**~~ *(изменено: `H-07`, 2026-08-31 — утверждение ПЕРЕВЁРНУТО.)*
//
// **ЧТО БЫЛО.** `FACT` (`H-06`, проба на той же машине): при `font-family` шрифта проекта
// `font-weight: bold` и `font-weight: normal` давали **побайтово одинаковые кадры**. Причина —
// v1-правило «ровно один font-record в проекте», а этот единственный record был

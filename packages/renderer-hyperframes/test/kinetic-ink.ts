// ПОЧЕМУ НЕ `band-ink.ts`, ХОТЯ ВОПРОС ПОХОЖ. Тот прибор ищет ТЁМНОЕ и отвечает на вопрос
// «где плашка субтитров»: полоса лежит на непрозрачной тёмной подложке, и тёмное в её пробе
// ровно одно. У `kineticType@1` плашки нет вовсе (решение спека), страница по умолчанию
// ЧЁРНАЯ (`index.html` ставит `background: #000` на `html`, `body` и `#root`), а текст —
// белый. То есть предмет зеркальный, и прогонять его через прибор, считающий тёмное, значило
// бы мерить фон: измерено на первой редакции этого теста — «тёмных» выходило 2 022 431 из
// 2 073 600, рамка `0…1079 × 0…1919`, и любое утверждение о раскладке было красным
// независимо от раскладки.
//
// ВТОРОГО PNG-ДЕКОДЕРА ПРИ ЭТОМ НЕ ЗАВОДИТСЯ: `decodeRgb` у вызывающего — тот же, которым
// `where` считает PSNR, и тот же, которым пользуется `band-ink.ts`.
//
// ПОДЛОЖКИ ТОЖЕ НЕ ЗАВОДИТСЯ. `captions-look.test.ts` кладёт под полосу белый `flash@1`,
// потому что ему нужно отличить «плашка» от «обводка» на светлом кадре. Здесь подложка была
// бы лишним клипом в измеряемой композиции: белое на чёрном локализуется само.

/** Рамка и площадь БЕЛЫХ пикселей кадра. Порог 200 по всем трём каналам — берёт сглаженные края глифов. */
export function inkBox(
  rgb: Uint8Array,
  width: number,
  height: number,
): { ink: number; top: number; bottom: number; left: number; right: number } {
  let ink = 0;
  let top = height;
  let bottom = -1;
  let left = width;
  let right = -1;
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const i = (y * width + x) * 3;
      if ((rgb[i] ?? 0) < 200 || (rgb[i + 1] ?? 0) < 200 || (rgb[i + 2] ?? 0) < 200) continue;
      ink += 1;
      if (y < top) top = y;
      if (y > bottom) bottom = y;
      if (x < left) left = x;
      if (x > right) right = x;
    }
  }
  return { ink, top, bottom, left, right };
}

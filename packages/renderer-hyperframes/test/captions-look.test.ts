// **ОХРАННИК ВИДА ПОЛОСЫ СУБТИТРОВ — ПИКСЕЛЯМИ** (`CAPTION-01`, 2026-09-11).
//
// ═══ ТРЕБУЕТ БРАУЗЕРА. СКИПА ПО ПЕРЕМЕННОЙ ЗДЕСЬ НЕТ — как и у соседнего файла. ═══
//
// ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ И ЧЕГО НЕТ В СОСЕДНЕМ ФАЙЛЕ.
// [`captions-visibility.test.ts`](./captions-visibility.test.ts) стережёт ВРЕМЯ полосы
// (группы переключаются) и ОДНУ раскладку — умолчание канала. Здесь стережётся другое:
// **ручки вида доезжают до пикселей**. До `CAPTION-01` вопроса не существовало — вид был
// константой рантайма; теперь автор пишет `bg: "none"` и обязан УВИДЕТЬ разницу, а не
// получить тихий no-op. Тихий no-op ровно того класса, что `{attr: …}` и твин по селектору в
// шапке реализации шаблона: оба «работали», пока их не измерили пикселями.
//
// ПОЧЕМУ ЭТОТ ВОПРОС НЕЛЬЗЯ ЗАКРЫТЬ ЮНИТОМ. Между `params` и кадром лежит цепочка из четырёх
// звеньев, и каждое умеет молчать: `mount` кладёт объект в `window.__VPE_CAPTION_BAND` →
// `runtime.js` накладывает его поверх умолчания ПО ЗАКРЫТОМУ СПИСКУ ИМЁН → строит текст CSS →
// браузер его применяет. Греп по коду (`templates.test.ts`) проверяет ПЕРВЫЕ ДВА звена —
// списки имён у обеих сторон совпадают, — и не может проверить последние два: опечатка в
// имени CSS-свойства или правило, перебитое соседним, видны только в кадре.
//
// ПРИБОР — ТОТ ЖЕ `bandInk`, ЧТО У СОСЕДА, И ЭТО НЕ ЭКОНОМИЯ. Второй счётчик тёмного дал бы
// два разных ответа на один вопрос «где полоса», и разошлись бы они на первой же правке
// порога. Прибор импортируется, а не копируется, и живёт в [`band-ink.ts`](./band-ink.ts) —
// обычным модулем, а не экспортом из соседнего `*.test.ts`: импорт теста в тест заставил бы
// vitest исполнить чужие `describe` ещё раз (измерено — см. шапку `band-ink.ts`).
//
// **ФОН ПРОБЫ БЕЛЫЙ, И НА ЭТОМ СТОИТ ВЕСЬ ФАЙЛ.** Белым его делает клип `flash@1` под
// субтитрами — тот же приём и тот же клип, которым пользуется соседний файл; страница сама по
// себе ЧЁРНАЯ (`background: #000` в `index.html`), и это измерено здесь первым же прогоном:
// без подложки «тёмных» в кадре 2 064 195 из 2 073 600, то есть счётчик меряет фон, а не
// полосу. Клип ОДИН И ТОТ ЖЕ в обоих прогонах — значит в разность он не попадает.
// Отсюда два следствия, оба используются:
//   * БЕЛЫЙ ТЕКСТ БЕЗ ОБВОДКИ НА БЕЛОМ ФОНЕ НЕ ДАЁТ НИ ОДНОГО ТЁМНОГО ПИКСЕЛЯ. Значит тёмное
//     при `bg: "none"` — это и есть обводка, и её наличие меряется прямо, а не косвенно;
//   * плашка — единственное КРУПНОЕ тёмное пятно в кадре, и её отсутствие меряется тем же
//     счётчиком с другой стороны.
//
// ЦЕНА: два рендера по 12 кадров 1080×1920 — измерено соседним файлом, 2–3 с каждый.

import { readdirSync } from 'node:fs';
import path from 'node:path';

import { describe, expect, it } from 'vitest';

import { renderSegment } from '../src/run.js';
import { rendererTemplates } from '../src/templates/index.js';
import { decodeRgb, pngSize } from '../src/where.js';
import { bandInk } from './band-ink.js';
import { makeTemplateFixture, readyRequest } from './fixture.js';

const FRAMES = 12;
/** Тот же запас, что у соседа: одиночный рендер 12 кадров 1080×1920 — 2–3 с. */
const TIMEOUT = 300_000;

/**
 * Общая часть обоих наборов — ВСЁ, КРОМЕ ФОНА И ОБВОДКИ.
 *
 * Это и есть форма утверждения: два прогона различаются РОВНО двумя ручками, поэтому разница
 * в кадрах не может прийти ни от кегля, ни от положения, ни от цвета текста. Положение —
 * `bottom` у обоих намеренно: `clean-shorts` стоит по центру, но сравнивать надо вид, а не
 * геометрию, иначе «плашки нет» было бы неотличимо от «полоса уехала».
 */
const COMMON = {
  font: 'caption',
  sizePx: 68,
  weight: 'bold',
  textColor: '#ffffff',
  activeColor: '#ffb347',
  position: 'bottom',
  marginPx: 500,
  widthPct: 85.185185,
  shadow: { dxPx: 0, dyPx: 2, blurPx: 10, color: '#000000', opacity: 0.55 },
} as const;

/** Вид канала: непрозрачная плашка, обводки нет. Дословно пресет `bottom-warm`. */
const WITH_PLATE = {
  ...COMMON,
  bg: 'plate',
  plateColor: '#05070c',
  outline: { widthPx: 0, color: '#000000' },
};

/** Шортсовый вид: плашки нет вовсе, читаемость держит обводка. Ручки пресета `clean-shorts`. */
const NO_PLATE = {
  ...COMMON,
  bg: 'none',
  outline: { widthPx: 4, color: '#000000' },
};

/** Один рендер с заданными `params` клипа эмфазы; возвращает измерение среднего кадра. */
async function inkOf(params: Record<string, unknown>): Promise<ReturnType<typeof bandInk>> {
  const fixture = makeTemplateFixture(
    [
      // СВЕТЛАЯ ПОДЛОЖКА — см. шапку: без неё страница чёрная и «тёмное» перестаёт означать
      // «плашка или обводка». Клип и его `params` те же, что у соседнего файла.
      { template: 'flash@1', params: { strengthPct: 1, durationSamples: 1 }, z: 20 },
      {
        template: 'captionEmphasis@1',
        params,
        z: 30,
        withFont: true,
        // Окно — весь сегмент: предмет здесь ВИД полосы, а не окно эмфазы.
        window: { frameStart: 0, frameEnd: FRAMES },
      },
    ],
    {
      frames: FRAMES,
      scale: 1,
      workers: 4,
      withCaptions: true,
      captionWindows: [
        [0, 6],
        [6, FRAMES],
      ],
    },
  );
  const request = await readyRequest(fixture.request);
  const response = await renderSegment(request, {
    clock: () => performance.now(),
    registry: rendererTemplates,
    parentEnv: process.env,
    gate: { mode: 'skip', why: 'проба вида субтитров `CAPTION-01`: гейт здесь не снимается' },
  });
  if (!response.ok) throw new Error(`${response.error.rule}: ${response.error.message}`);

  const name = readdirSync(response.frames.dir)
    .filter((n) => n.endsWith('.png'))
    .sort()[4];
  if (name === undefined) throw new Error('кадров на диске нет');
  const file = path.join(response.frames.dir, name);
  const size = pngSize(file);
  if (size === null) throw new Error(`PNG не прочитан: ${file}`);
  return bandInk(await decodeRgb(file), size.width, size.height);
}

describe('**CAPTION-01** — ручки вида доезжают до ПИКСЕЛЕЙ, а не молчат', () => {
  it(
    '`bg: "none"` — плашки в кадре нет, а обводка есть; `bg: "plate"` — наоборот',
    async () => {
      const plate = await inkOf(WITH_PLATE);
      const none = await inkOf(NO_PLATE);

      const where =
        `плашка: тёмных ${String(plate.dark)}, рамка y ${String(plate.top)}…${String(plate.bottom)}, ` +
        `x ${String(plate.left)}…${String(plate.right)}; без плашки: тёмных ${String(none.dark)}, ` +
        `рамка y ${String(none.top)}…${String(none.bottom)}, x ${String(none.left)}…${String(none.right)}`;

      // 1. ОБА ПРОГОНА ВООБЩЕ ЧТО-ТО НАРИСОВАЛИ. Ноль тёмного у ПЕРВОГО означал бы, что
      //    правила трека не доехали до документа вовсе, и тогда второе утверждение было бы
      //    зелёным по недоразумению.
      expect(plate.dark, `плашка не нарисована совсем — ${where}`).toBeGreaterThan(10_000);

      // 2. ОБВОДКА ЕСТЬ, И ЭТО ПРЯМОЕ ИЗМЕРЕНИЕ. Фон белый, текст белый: без обводки тёмного
      //    в кадре не было бы НИ ОДНОГО пикселя. Порог взят с большим запасом вниз — предмет
      //    утверждения «контур нарисован», а не «контур такой-то толщины».
      expect(
        none.dark,
        'при `bg: "none"` в кадре нет ни одного тёмного пикселя: белый текст на белом фоне ' +
          'без обводки неразличим — значит `outline` не доехал до CSS. Проверяемых причин ' +
          `три: имя выпало из списка договора, правило не построено, свойство перебито — ${where}`,
      ).toBeGreaterThan(200);

      // 3. ПЛАШКИ НЕТ. Контур букв на порядок меньше плашки: она заливает прямоугольник
      //    920×(строка) целиком, он же обводит глифы. Утверждение — про ПОРЯДОК, а не про
      //    число: точное отношение зависит от текста пробы, а вот «в разы» — не зависит.
      expect(
        none.dark * 3,
        `при \`bg: "none"\` тёмного столько же, сколько с плашкой — плашка не снялась: ${where}`,
      ).toBeLessThan(plate.dark);

      // 4. И ТОЧЕЧНО — УГОЛ ПЛАШКИ. Числа сравнивать мало: тёмного могло стать меньше и от
      //    того, что полоса уехала из кадра. Берётся точка ВНУТРИ рамки плашки первого
      //    прогона, на её левом краю (там поле в 32 px — глифов быть не может), и у второго
      //    прогона она обязана оказаться ВНЕ его рамки: без плашки полоса не заливает ничего
      //    левее первой буквы.
      const probeX = plate.left + 20;
      expect(
        probeX < none.left || none.dark === 0,
        `точка (${String(probeX)}, ~${plate.cy.toFixed(0)}) лежит в рамке плашки первого ` +
          `прогона и осталась тёмной во втором: подложка под текстом не исчезла — ${where}`,
      ).toBe(true);

      // 5. ПОЛОСА НЕ УЕХАЛА: обводка стоит там же, где стояла плашка, — внизу кадра.
      //    Без этого утверждения пункт 3 был бы зелёным и на полосе, выпавшей за кадр.
      expect(Math.abs(none.cy - plate.cy), `полоса сдвинулась по вертикали — ${where}`).toBeLessThan(40);
    },
    TIMEOUT * 2,
  );
});

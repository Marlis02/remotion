// Ошибка PCM-тракта (`M-03`).
//
// ОШИБКА НАЗЫВАЕТ ПРАВИЛО, А НЕ СЛЕДСТВИЕ — то же решение, что у `TimeModelError` (`C-01`)
// и `AssetCatalogError` (`M-02`). «Длина не кратна двум» — следствие; «формат тракта: PCM
// s16le моно» — причина, и по ней сразу видно, какую строку читать. Поэтому у ошибки есть
// поле `rule`, а не только текст.
//
// ПОЧЕМУ СРЕДИ ПРАВИЛ ЕСТЬ ОДНО БЕЗ ADR. Битность, число каналов и порядок байтов
// внутреннего формата не называет **ни один** ADR и не описывает схема `audio-profile/1`
// (решение владельца по вопросу 1 сессии `M-03`): это `INFERENCE`, выведенный из
// `FACT` r1 §0.6 (речь запрашивается в `pcm_24000` — s16le моно) и ADR-0003
// «Разделение sampleRate». Правило названо `M-03 формат тракта (INFERENCE)` именно затем,
// чтобы в сообщении об ошибке было видно: это наше допущение, а не строка ADR. Кандидат в
// правку ADR-0003 записан в отчёте сессии.

/** Правила, на которые ссылаются ошибки PCM-тракта. */
export type AudioRule =
  /** Микрофейд на краях уже отведённого интервала; длину дорожки он не меняет. */
  | 'ADR-0003 T7'
  /** `projectSampleRate` — источник истины физического времени; ресемплинг только на ingest. */
  | 'ADR-0003 «Разделение sampleRate»'
  /** Внутри пайплайна нет mp3 ни на одном шаге (инвариант **V6**). */
  | 'ADR-0010 §9 (V6)'
  /** Битность, каналы и порядок байтов внутреннего формата — `INFERENCE` сессии `M-03`. */
  | 'M-03 формат тракта (INFERENCE)';

/** Нарушение правила PCM-тракта: несёт имя правила, а не только текст. */
export class AudioError extends RangeError {
  readonly rule: AudioRule;

  constructor(rule: AudioRule, reason: string) {
    super(`${rule}: ${reason}`);
    this.name = 'AudioError';
    this.rule = rule;
  }
}

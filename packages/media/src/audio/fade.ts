// Микрофейд на краях уже отведённого интервала (ADR-0003 T7; roadmap §4 «`M-03`»).
//
// ЧТО ЭТО ЗА ОПЕРАЦИЯ. T7 требует, чтобы все стыки PCM (чанк↔чанк, речь↔тишина) выполнялись
// «с детерминированным микрофейдом фиксированной длины **внутри** уже отведённого интервала —
// длину дорожки он не меняет». Здесь это исполнено буквально: фейд гасит края ТОГО, ЧТО ЕСТЬ,
// не сдвигая ни одной границы и не добавляя ни одного сэмпла.
//
// ДЛИНА ЖИВЁТ В ПРОФИЛЕ, А НЕ ЗДЕСЬ. `audio-profile/1 → crossfadeSamples`, в
// `fixtures/minimal/profiles/audio.yaml` — 72, что равно `msToSamples(3, 24000)`. Своей
// константы у этого файла нет намеренно: величина, вошедшая в ключ кэша `audioTrack`
// (ADR-0006 §5), обязана жить в профиле, иначе её правка не инвалидирует кэш.
//
// РАЗНОЧТЕНИЕ, НАЗВАННОЕ ВСЛУХ (кандидат в правку ADR-0003, отчёт `M-03` — решение владельца,
// вопрос 4). ADR-0003 T7 пишет «**равномощным** микрофейдом», а поле профиля названо
// `crossfadeSamples`, то есть кросс-фейдом. Исполняется **линейный краевой** фейд, и вот
// почему это не произвол: равномощный закон (√/косинус) осмыслен для ПЕРЕКРЫВАЮЩЕГОСЯ
// кросс-фейда двух источников, а перекрытие двух краёв укоротило бы дорожку ровно на `N`
// сэмплов — то, что тот же T7 прямо запрещает. Непересекающиеся краевые фейды линейны,
// целочисленны и границ не двигают.
//
// ПОРЯДОК ОТНОСИТЕЛЬНО МИКСА — «ФЕЙД ДО МИКСА, К КАЖДОЙ ДОРОЖКЕ» (решение владельца A,
// сессия `M-03`). Зеркальная строка и разбор — в шапке `mix.ts`; здесь важно следствие:
// эта функция ничего не знает про сумму и вызывается вызывающим явно.

import { addExact, assertSafeInteger, floorDiv, mulExact } from '@vpe/core-model';

import { AudioError } from './errors.js';
import { pcmS16, type PcmS16 } from './pcm.js';

/**
 * Умножение сэмпла на дробь `numerator / denominator` с ЕДИНСТВЕННЫМ правилом округления
 * тракта: **к ближайшему, ничьи — от нуля** (решение владельца, вопрос 4 сессии `M-03`).
 *
 * ПОЧЕМУ ИМЕННО ЭТО ПРАВИЛО. Оно симметрично по знаку, а несимметричное (`floor`, `trunc`
 * к −∞) внесло бы постоянную составляющую: ADR-0003 T7 требует ассерта «|DC offset| ниже
 * порога» на импорте, и правило округления фейда — ровно то место, где смещение появилось
 * бы системно. Ошибка ≤ 0.5 LSB против ≤ 1 LSB у усечения.
 *
 * ЦЕЛОЧИСЛЕННО ЦЕЛИКОМ: `round(|s|·i/N)` = `floorDiv(2·|s|·i + N, 2·N)`. Переполнения нет по
 * построению — результат по модулю не превосходит `|s|`, а промежутки проверены T2
 * (`mulExact`/`addExact` из `@vpe/core-model`).
 */
export function scaleSample(sample: number, numerator: number, denominator: number): number {
  assertSafeInteger(sample, 'сэмпл');
  assertSafeInteger(numerator, 'числитель усиления');
  assertSafeInteger(denominator, 'знаменатель усиления');
  if (denominator <= 0) {
    throw new AudioError('ADR-0003 T7', `знаменатель усиления = ${String(denominator)}: ожидалось > 0`);
  }
  const magnitude = sample < 0 ? -sample : sample;
  const doubled = mulExact(mulExact(magnitude, numerator, 'сэмпл · числитель'), 2, 'удвоенное произведение');
  const rounded = floorDiv(
    addExact(doubled, denominator, 'округление к ближайшему'),
    mulExact(denominator, 2, 'удвоенный знаменатель'),
  );
  return sample < 0 ? -rounded : rounded;
}

/**
 * Линейный микрофейд на обоих краях дорожки.
 *
 * Усиление: на входе `g_i = i / N` для `i = 0 … N−1` (нулевой сэмпл гасится в ноль ровно —
 * в этом весь смысл: щёлкает именно скачок из тишины в ненулевой сэмпл), на выходе — зеркально,
 * `g = j / N`, где `j` — расстояние от последнего сэмпла. Сэмпл с индексом `N` и дальше
 * остаётся нетронутым: фейд заканчивается ровно там, где обещал.
 *
 * `fadeSamples = 0` — законное значение схемы (`z.int().nonnegative()`), означает «фейда нет»;
 * дорожка возвращается копией, а не тем же массивом (значение, а не ссылка).
 *
 * ОТКАЗ ПРИ `len < 2·N` — решение владельца (вопрос 7): фейды входа и выхода перекрылись бы
 * и погасили середину, а тихое усечение `N = ⌊len/2⌋` спрятало бы ошибку вызывающего.
 * Длину интервала гарантирует T7/`CP-01`, и её нарушение — не повод «сделать что-нибудь».
 */
export function applyEdgeFade(pcm: PcmS16, fadeSamples: number): PcmS16 {
  assertSafeInteger(fadeSamples, 'crossfadeSamples');
  if (fadeSamples < 0) {
    throw new AudioError(
      'ADR-0003 T7',
      `\`crossfadeSamples\` = ${String(fadeSamples)}: длина микрофейда неотрицательна`,
    );
  }

  const length = pcm.samples.length;
  const needed = mulExact(fadeSamples, 2, 'два фейда');
  if (length < needed) {
    throw new AudioError(
      'ADR-0003 T7',
      `интервал ${String(length)} сэмплов короче двух микрофейдов по ` +
        `${String(fadeSamples)} (нужно ${String(needed)}). Фейды перекрылись бы и погасили ` +
        'середину интервала; длину интервала гарантирует вызывающий (T7 / `CP-01`), ' +
        'молча укоротить фейд тракт не имеет права.',
    );
  }

  const out = new Int16Array(pcm.samples);
  for (let i = 0; i < fadeSamples; i += 1) {
    out[i] = scaleSample(pcm.samples[i] ?? 0, i, fadeSamples);
    const tail = length - 1 - i;
    out[tail] = scaleSample(pcm.samples[tail] ?? 0, i, fadeSamples);
  }
  return pcmS16(pcm.sampleRate, out);
}

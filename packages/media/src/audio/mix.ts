// Микс — СЛОЖЕНИЕ ЦЕЛЫХ СЭМПЛОВ (ADR-0010 §9; roadmap §4 «`M-03`»).
//
// ПОЧЕМУ ЭТО ВООБЩЕ ВАЖНО. Критерий готовности задачи звучит «микс двух дорожек не зависит
// от версии ресемплера», и держится он не на аккуратности, а на порядке шагов: музыка
// приводится к `projectSampleRate` ОДИН РАЗ на ingest (ADR-0010 §9), поэтому сюда приходят
// дорожки одной частоты, и складывать их можно целыми числами. Ни одного float-пути в этом
// файле нет и быть не может; дорожка с чужой частотой не ресемплится здесь «на лету», а
// отвергается (`assertProjectRate`).
//
// ПОРЯДОК ОПЕРАЦИЙ — ФЕЙД ДО МИКСА, К КАЖДОЙ ДОРОЖКЕ; ПОСЛЕ МИКСА — НИКОГДА.
// Решение владельца A, сессия `M-03`. Три основания, и ни одно не про удобство:
//
//   1. фейд — операция над интервалом T7, а интервал есть у ДОРОЖКИ, а не у суммы: T7 гасит
//      края склеиваемого фрагмента, а у суммы стыки уже внутри и уже сложены;
//   2. короткие дорожки дополняются тишиной (см. ниже), поэтому фейд ПОСЛЕ микса гасил бы
//      дополнение — общий ноль в конце, — а настоящие края контента (конец короткой речевой
//      дорожки в середине суммы) остались бы без фейда. Свойство исчезло бы молча, а тест
//      «первый и последний сэмпл суммы» остался бы зелёным;
//   3. `fade(a) + fade(b) ≠ fade(a + b)`, как только у дорожек разные границы, — а они разные
//      всегда, иначе микса бы не было. Значит, порядок обязан быть НАЗВАН.
//
// Отсюда же то, чего в этом файле нет: `mixSaturating` не зовёт `applyEdgeFade` сам. Позови
// он его внутри — порядок стал бы неявным, и вызывающий перестал бы его видеть.
//
// ДЛИНЫ И НАСЫЩЕНИЕ — РЕШЕНИЕ ВЛАДЕЛЬЦА (вопросы 1 и 6). Длина результата — максимум длин,
// короткие дорожки дополняются тишиной. Насыщение НЕ молчит: `clippedSamples` — факт в
// отчёте; отказа здесь нет, решение «так и должно быть» принимает `CP-05`, у которого есть
// план дорожки.

import { mulExact } from '@vpe/core-model';

import { AudioError } from './errors.js';
import { PCM_SAMPLE_MAX, PCM_SAMPLE_MIN, assertProjectRate, pcmS16, type PcmS16 } from './pcm.js';

export interface MixResult {
  /** Сумма: `projectSampleRate`, длина — максимум длин входов. */
  readonly mixed: PcmS16;
  /**
   * Сколько сэмплов упёрлись в границу шкалы. Ноль — обычное состояние; ненулевое значение
   * не является ошибкой здесь, но обязано быть видно вызывающему (решение владельца).
   */
  readonly clippedSamples: number;
  /** Длины входов в порядке аргументов — чтобы «дополнено тишиной» было наблюдаемо. */
  readonly inputLengths: readonly number[];
}

/**
 * Сложение дорожек с насыщением в границах s16.
 *
 * ПОЧЕМУ СЛОЖЕНИЕ ИДЁТ ОБЫЧНЫМ `+`, А НЕ `addExact` НА КАЖДОМ СЭМПЛЕ. T2 требует, чтобы
 * каждое промежуточное произведение и сумма были в пределах `Number.isSafeInteger`. Здесь это
 * доказывается ОДИН РАЗ на границе: любая частичная сумма по модулю не превосходит
 * `32768 · (число дорожек)`, и эта величина проверена `mulExact` ниже. Проверка на каждом
 * сэмпле повторяла бы доказанное миллион раз за прогон и ничего бы не добавила.
 */
export function mixSaturating(tracks: readonly PcmS16[], projectSampleRate: number): MixResult {
  if (tracks.length === 0) {
    throw new AudioError(
      'M-03 формат тракта (INFERENCE)',
      'микс без дорожек: пустая сумма — это тишина неизвестной длины. Нужна тишина — ' +
        'постройте её `silence(sampleRate, lengthSamples)` явно.',
    );
  }

  const inputLengths: number[] = [];
  let length = 0;
  for (const [index, track] of tracks.entries()) {
    assertProjectRate(track, projectSampleRate, `дорожка №${String(index + 1)} микса`);
    inputLengths.push(track.samples.length);
    if (track.samples.length > length) length = track.samples.length;
  }

  // Граница суммы, проверенная T2 один раз: 32768 — модуль самого громкого сэмпла шкалы.
  mulExact(-PCM_SAMPLE_MIN, tracks.length, 'граница суммы дорожек');

  const out = new Int16Array(length);
  let clippedSamples = 0;
  for (let i = 0; i < length; i += 1) {
    let sum = 0;
    for (const track of tracks) {
      // Короткая дорожка за своим концом — тишина: `?? 0` здесь и есть дополнение тишиной.
      sum += track.samples[i] ?? 0;
    }
    if (sum > PCM_SAMPLE_MAX) {
      out[i] = PCM_SAMPLE_MAX;
      clippedSamples += 1;
    } else if (sum < PCM_SAMPLE_MIN) {
      out[i] = PCM_SAMPLE_MIN;
      clippedSamples += 1;
    } else {
      out[i] = sum;
    }
  }

  return { mixed: pcmS16(projectSampleRate, out), clippedSamples, inputLengths };
}

// Атомарная запись файла — инвариант **K7** (`tmp + fsync + rename`, ADR-0005 §8).
//
// ПОЧЕМУ ОТДЕЛЬНЫЙ ФАЙЛ. K7 — правило про ОДНУ последовательность системных вызовов, и она
// обязана читаться целиком в одном месте: «записали во временный файл, дождались, что байты
// на диске, переименовали». Размазанная по методам `LocalStore`, она проверялась бы глазами.
// Второе следствие того же решения: это **единственный** файл каталога `store/`, которому
// разрешено удалять что-либо с диска, и удаляет он ровно свой tmp — на этом построен
// охранник **K10** (`tests/…/store-layout.test.ts`).
//
// ПОЧЕМУ ИМЕННО RENAME. `rename(2)` в пределах одной файловой системы атомарен: наблюдатель
// видит либо старое содержимое по адресу, либо новое, и никогда — половину. Это и есть
// «в CAS не остаётся частичного блоба» из критерия готовности `M-01`. Именно поэтому tmp
// кладётся В ТОТ ЖЕ КАТАЛОГ, что цель: файл из `os.tmpdir()` уехал бы на другое устройство,
// и `rename` выродился бы в copy + unlink, то есть перестал быть атомарным.

import { mkdir, open, rename, unlink } from 'node:fs/promises';
import path from 'node:path';

/**
 * Счётчик внутри процесса. Вместе с `process.pid` даёт имя tmp, уникальное между
 * параллельными записями, — **без случайности**: Charter V8 требует, чтобы недетерминизм был
 * объявленным, а здесь он не нужен вовсе. Имя tmp не входит ни в один артефакт и живёт
 * миллисекунды.
 */
let counter = 0;

/**
 * Имя временного файла. НИКОГДА не равно имени цели, и это половина смысла K7: запись
 * «на месте» оставила бы по адресу sha256 половину блоба, а `has()` вернул бы на неё `true`.
 * Суффикс распознаваем глазами в каталоге и не может быть принят за sha256 (в нём точка).
 */
export function tempNameFor(targetPath: string): string {
  counter += 1;
  return `${path.basename(targetPath)}.tmp-${String(process.pid)}-${String(counter)}`;
}

/**
 * Записывает байты по адресу `targetPath` так, что промежуточного состояния по этому адресу
 * не существует.
 *
 * Порядок шагов значим целиком:
 *   1. создать каталог (шард CAS появляется лениво — пустых каталогов в сторе не заводится);
 *   2. создать tmp флагом `wx` — «создать, но не поверх существующего»: столкновение имён
 *      обязано быть ошибкой, а не тихой перезаписью чужого tmp;
 *   3. записать байты;
 *   4. `fsync` файла — иначе `rename` может стать видимым РАНЬШЕ данных, и после сбоя
 *      питания по адресу окажется файл нужной длины из нулей;
 *   5. `rename` — момент, в который блоб становится существующим;
 *   6. `fsync` каталога — чтобы сама запись каталога пережила сбой.
 *
 * На любой ошибке tmp удаляется, и ошибка пробрасывается: лечение — повторный `put`.
 */
export async function writeAtomic(targetPath: string, bytes: Uint8Array): Promise<void> {
  const dir = path.dirname(targetPath);
  await mkdir(dir, { recursive: true });

  const tempPath = path.join(dir, tempNameFor(targetPath));
  try {
    const handle = await open(tempPath, 'wx');
    try {
      await handle.writeFile(bytes);
      await handle.sync();
    } finally {
      await handle.close();
    }
    await rename(tempPath, targetPath);
  } catch (error) {
    await removeQuietly(tempPath);
    throw error;
  }

  await syncDirectory(dir);
}

/**
 * Удаление tmp на пути ошибки. Тихое намеренно: настоящая ошибка — та, ради которой мы сюда
 * попали, и подменять её на `ENOENT` при уборке значило бы потерять причину.
 *
 * ЭТО ЕДИНСТВЕННОЕ УДАЛЕНИЕ ФАЙЛА ВО ВСЁМ КАТАЛОГЕ `store/` (K10), и оно адресует tmp,
 * а не блоб: имя приходит из `tempNameFor`, то есть заведомо не равно sha256.
 */
async function removeQuietly(tempPath: string): Promise<void> {
  try {
    await unlink(tempPath);
  } catch {
    // Файла нет — значит, сбой случился до его создания. Это не ошибка уборки.
  }
}

/**
 * `fsync` каталога. Отдельной функцией и с проглоченной ошибкой — по одной причине: на части
 * платформ каталог нельзя открыть на чтение вовсе (Windows), и там этот шаг физически
 * отсутствует. Проглатывается ТОЛЬКО он; сбой любого шага записи выше — ошибка.
 */
async function syncDirectory(dir: string): Promise<void> {
  try {
    const handle = await open(dir, 'r');
    try {
      await handle.sync();
    } finally {
      await handle.close();
    }
  } catch {
    // Каталог не открывается на чтение — шаг неприменим на этой платформе.
  }
}

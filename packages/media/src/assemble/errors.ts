// Ошибка сборки (`M-04`).
//
// ОШИБКА НАЗЫВАЕТ ПРАВИЛО, А НЕ СЛЕДСТВИЕ — то же решение, что у `AudioError` (`M-03`),
// `TimeModelError` (`C-01`) и `AssetCatalogError` (`M-02`). «150 против 149» — следствие;
// «**R8**: `Σ durationInFrames == frameCount(final) == ceil(N_samples / samplesPerFrame)`»
// — причина, и по ней сразу видно, какую строку реестра читать.
//
// ПОЧЕМУ ПРАВИЛА ЗДЕСЬ — ЭТО ИНВАРИАНТЫ, А НЕ ADR. У `M-03` в `rule` стояли адреса ADR,
// потому что тракт исполнял ADR-0003/0010. Сборка исполняет четыре строки
// [`docs/invariants.md`](../../../../docs/invariants.md) — **R5**, **R8**, **R9**, **R10**, —
// и в сообщении полезнее видеть имя инварианта: именно по нему ищется охранник.
// Пятое правило (`M-04` закрытость GOP) инвариантом не является: ADR-0008 «Сборка» требует
// задавать `gopSize` явно, «чтобы GOP не решал энкодер», но отдельной строки в реестре у
// этого нет — поэтому имя правила названо задачей, а не выдуманным номером.

/** Правила, на которые ссылаются ошибки сборки. */
export type AssembleRule =
  /** **R5**: в сегменте нет аудио-дорожки. */
  | 'R5'
  /** **R8**: `Σ durationInFrames == frameCount(final) == ceil(N_samples / samplesPerFrame)`. */
  | 'R8'
  /** **R9**: `StreamFingerprint` финала == первого сегмента. */
  | 'R9'
  /** **R10**: видео кодируется ровно один раз; конкат только `-c copy`. */
  | 'R10'
  /** ADR-0008 «Сборка»: `gopSize` задан явно, GOP не решает энкодер. Строки в реестре нет. */
  | 'M-04 закрытость GOP'
  /** Форма вызова: профиль исполняется дословно, умолчаний версии ffmpeg нет. */
  | 'M-04 форма вызова';

/** Нарушение правила сборки: несёт имя правила, а не только текст. */
export class AssembleError extends RangeError {
  readonly rule: AssembleRule;

  constructor(rule: AssembleRule, reason: string) {
    super(`${rule}: ${reason}`);
    this.name = 'AssembleError';
    this.rule = rule;
  }
}
